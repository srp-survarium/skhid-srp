"""The DLSS link's motion pass (dlss_motion_026g.comp, GLSL) built into the
SPIR-V words the patch crate includes (dlss_motion_026g.rs, generated: never
edited by hand).

    python dlss_motion_026g.py --write    builds the shader, writes dlss_motion_026g.rs
    python dlss_motion_026g.py --check    builds it and compares with dlss_motion_026g.rs

Needs glslangValidator (`nix develop ./srp-026g`; the flake's lock pins it,
so the words are the same on every machine). link_026g.py runs the check
before it builds the crate: a shader edited without --write cannot ship.
"""
import argparse
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "dlss_motion_026g.comp"
OUT = HERE / "dlss_motion_026g.rs"
SPIRV_MAGIC = 0x07230203


class Refused(Exception):
    pass


def words():
    """The shader's SPIR-V, as its 32-bit words (Vulkan 1.1's SPIR-V 1.3,
    no debug names: nothing of the build's paths in it)."""
    with tempfile.TemporaryDirectory() as folder:
        out = Path(folder) / "motion.spv"
        try:
            done = subprocess.run(
                ["glslangValidator", "-V", "--target-env", "vulkan1.1", "-g0", "-S", "comp", "-o", str(out),
                 str(SOURCE)], capture_output=True, text=True)
        except FileNotFoundError:
            raise Refused("glslangValidator is not on the PATH (nix develop ./srp-026g)") from None
        if done.returncode != 0:
            raise Refused(f"{SOURCE.name} does not build:\n{done.stdout}{done.stderr}")
        blob = out.read_bytes()
    if len(blob) % 4 or len(blob) < 20:
        raise Refused(f"{SOURCE.name}: {len(blob)} bytes of SPIR-V, not whole words")
    code = list(struct.unpack(f"<{len(blob) // 4}I", blob))
    if code[0] != SPIRV_MAGIC:
        raise Refused(f"{SOURCE.name}: the build's first word is {code[0]:#x}, not SPIR-V's")
    return code


def render(code):
    lines = [
        "// Generated by dlss_motion_026g.py from dlss_motion_026g.comp: do not edit.",
        "// (`python dlss_motion_026g.py --write` after a change of the shader.)",
        "",
        "/// The motion pass's compute shader, SPIR-V words (entry point `main`).",
        f"pub(super) static MOTION_SPIRV: [u32; {len(code)}] = [",
    ]
    for at in range(0, len(code), 8):
        lines.append("    " + " ".join(f"{word:#010x}," for word in code[at:at + 8]))
    lines.append("];")
    return "\n".join(lines) + "\n"


def check():
    """Raises Refused when dlss_motion_026g.rs is not what the shader builds to."""
    made = render(words())
    if not OUT.is_file() or OUT.read_text(encoding="utf-8") != made:
        raise Refused(f"{OUT.name} is not what {SOURCE.name} builds to: python dlss_motion_026g.py --write")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write == args.check:
        parser.error("--write or --check")
    try:
        if args.write:
            code = words()
            OUT.write_text(render(code), encoding="utf-8")
            print(f"{OUT.name}: {len(code)} words of SPIR-V from {SOURCE.name}")
        else:
            check()
            print(f"{OUT.name}: what {SOURCE.name} builds to")
    except Refused as refused:
        sys.exit(f"dlss_motion_026g.py: {refused}")


if __name__ == "__main__":
    main()
