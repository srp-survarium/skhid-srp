#!/usr/bin/env python3
"""The Rust hook glue (docs/notes/rust_patches.md, "The design principle").
A patch's declaration is only names -- which site, and the handler:

    # rust/patches/src/<patch>.toml
    [[hook]]
    site = "input_builder.spot_query"    # a row of sites_026g.tsv
    handler = "on_spot"                  # patches::<patch>::on_spot

Everything else is a fact written once in the raw tables and read here:

    sites_026g.tsv    a named site: its VA, its kind (call/splice/pointer/
                      vtable/callback/lohook/code; `entry`, VA `-`: a Rust
                      handler our own NASM calls, cdecl, aligned as a
                      lohook), the callee it uses (an
                      engine_026g.tsv row, for the kinds that call a game
                      function), the span it covers, its named exits (lohook)
                      and a short `what`. The kind follows from the site, so a
                      patch names no kind.
    engine_026g.tsv   the callee: its VA and convention (from the re-kit), and
                      a `vostok` column, the typed signature a Rust hook takes
                      (`arg: Type, .. -> Result`). The Vostok types are
                      vostok's (InputHandler, Action, Out<u32>, ..).

From these this generates, at build time: the NASM entries
(hook_entries_026g.asm, the arena's block patches.code), the Rust shims and
`Original` types (hooks_026g.rs, inside vostok), and the install descriptors.
The replaced bytes are derived (a call/jump to the callee) or read from the
original exe (a span); patch_026g.py's apply() checks every write against the
exe, so a site that drifted fails the build. Nothing is looked up at run time.

    python hooks_026g.py --write     writes hook_entries_026g.asm and hooks_026g.rs
    python hooks_026g.py --check     says whether they are current (the self-test runs the same)

A span hook (lohook, splice, code) needs the original exe for its bytes: the
caller's reader, else the file `--exe` or SRP_026G_EXE names (sha256
checked); patch_026g.py passes the exe it builds from.
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import tomllib
from pathlib import Path

import engine_026g

HERE = Path(__file__).resolve().parent
TOML_DIR = HERE / "rust" / "patches" / "src"
SITES = HERE / "sites_026g.tsv"
RS = HERE / "hooks_026g.rs"
ASM = HERE / "hook_entries_026g.asm"
GENERATED = "generated by hooks_026g.py from the patches' <patch>.toml: do not edit"

# A Vostok type a `call` argument may have: the `raw` layer's type
# engine_026g.tsv must give for it (checked; the shim's argument has that
# type, the entry passing the game's dword), how the shim builds it from that
# argument `{a}`, the type and the raw expression the Original uses, and how
# it is passed to the handler. `fallible` builds an Option (a handle; null
# takes the unpatched path); `binding` is the shim's `let`.
TYPES = {
    "InputHandler": {
        "raw": "Option<PlayerInputHandler>",
        "fallible": True,
        "build": "InputHandler::from_raw(&thread, {a})",
        "orig_type": "&mut InputHandler",
        "orig_raw": "Some({n}.raw())",
        "pass": "&mut {n}",
        "null": "{a}",
    },
    "Action": {
        "raw": "u32",
        "binding": "let {n} = Action({a});",
        "orig_type": "Action",
        "orig_raw": "{n}.0",
        "pass": "{n}",
        "null": "{a}",
    },
    "Out<u32>": {
        "raw": "*mut u32",
        "binding": "let mut {n} = unsafe {{ Out::<u32>::new(&thread, {a}) }};",
        "orig_type": "&mut Out<u32>",
        "orig_raw": "{n}.at()",
        "pass": "&mut {n}",
        "null": "{a}",
    },
}
# A query's callback (`callback` kind, handed to the game at run time): the
# results the game passes and the word the patch bound to its query.
TYPES["QueryResults"] = {
    "raw": "Option<QueriesResult>",
    "binding": "let {n} = unsafe {{ QueryResults::from_raw(&thread, {a}) }};",
    "orig_type": "&QueryResults", "orig_raw": "-", "pass": "{n}", "null": "{a}",
}
TYPES["QueryTag"] = {
    "raw": "*mut c_void",
    "binding": "let {n} = QueryTag::from_raw({a} as usize as u32);",
    "orig_type": "QueryTag", "orig_raw": "-", "pass": "{n}", "null": "{a}",
}
# A binary config's query (`vostok::resources::query_config`): its result, the config, and the
# word the patch bound to it.
TYPES["ConfigQuery"] = {**TYPES["QueryResults"],
                        "binding": "let {n} = unsafe {{ ConfigQuery::from_raw(&thread, {a}) }};",
                        "orig_type": "&ConfigQuery"}
TYPES["ConfigTag"] = {**TYPES["QueryTag"], "binding": "let {n} = ConfigTag::from_raw({a} as usize as u32);",
                      "orig_type": "ConfigTag"}
# Native presentation interfaces. Their raw kinds come from fields_026g.tsv;
# the public views borrow the generated hook's thread.
for _view in ("RenderVisual", "GameScene", "ObjectLight"):
    TYPES[_view] = {
        "raw": f"Option<{_view}>", "fallible": True,
        "build": f"{_view}::from_raw(&thread, {{a}})",
        "orig_type": f"&mut {_view}", "orig_raw": "Some({n}.raw())",
        "pass": "&mut {n}", "null": "{a}",
    }

# A handler result, mapped to F's: the raw result engine_026g.tsv must give,
# the Vostok type and how F's raw result `{x}` becomes it (`Original::call`),
# and how that Vostok value `{v}` becomes the shim's u32 (EAX).
RESULTS = {
    None: {"raw": (None,), "type": "()", "from_raw": "{x}", "to_u32": "{{ {v}; 0 }}"},
    "bool": {"raw": ("AL", "EAX"), "type": "bool", "from_raw": "{x} != 0", "to_u32": "u32::from({v})"},
    "u32": {"raw": ("EAX",), "type": "u32", "from_raw": "{x}", "to_u32": "{v}"},
}


class Bad(Exception):
    """A TOML the glue cannot make a hook of."""


def read_tomls():
    out = []
    for path in sorted(TOML_DIR.glob("*.toml")):
        data = tomllib.loads(path.read_text())
        if data.get("name") != path.stem:
            raise Bad(f"{path.name}: its `name` is the file's stem ({path.stem})")
        out.append(data)
    return out


def engine_row(symbol, functions):
    for f in functions:
        if f["symbol"] == symbol:
            return f
    raise Bad(f"{symbol}: no such row in engine_026g.tsv")


def camel(name):
    return "".join(w.title() for w in name.split("_"))


def read_sites(path=None):
    """sites_026g.tsv as {site name: dict}. A site is a named place the game
    is hooked -- its VA, its kind, the callee row it uses (engine_026g.tsv,
    for the kinds that call a game function), the span it occupies, its named
    exits (lohook), and a short `what`. The VAs live here (and in
    engine_026g.tsv), not in the patches; the re-kit (tools/re-kit/v026g) is
    the RE source a site's VA and its callee's ABI come from, as for the
    engine library."""
    out = {}
    for row in engine_026g.read_tsv(SITES if path is None else path):
        name = row["site"].strip()
        if not re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", name):
            raise Bad(f"sites_026g.tsv: {name!r} is no site name (dotted, e.g. input_builder.spot_query)")
        exits = [] if row["exits"].strip() in ("", "-") else [
            (e.split("@")[0], engine_026g.number(e.split("@")[1])) for e in row["exits"].split(";")]
        kind = row["kind"].strip()
        # an `entry` is called by our own code, not the game's: it has no VA
        if (row["va"].strip() == "-") != (kind == "entry"):
            raise Bad(f"sites_026g.tsv: {name}: a VA is `-` for an entry, and only for one")
        out[name] = {"site": name, "va": None if kind == "entry" else engine_026g.number(row["va"]), "kind": kind,
                     "callee": row["callee"].strip(), "span": None if row["span"].strip() in ("", "-")
                     else engine_026g.number(row["span"]), "exits": exits, "what": row["what"].strip()}
    return out


def site_of(patch_name, kind, row, sites):
    """The site a patch's row names (`site`), its kind matching the TOML
    section's."""
    if "site" not in row or "handler" not in row and kind != "code":
        raise Bad(f"{patch_name}: a [[{kind}]] needs `site`" + ("" if kind == "code" else " and `handler`"))
    site = sites.get(row["site"])
    if site is None:
        raise Bad(f"{patch_name}: no site {row['site']!r} in sites_026g.tsv")
    if site["kind"] != kind:
        raise Bad(f"{patch_name}: site {row['site']} is a {site['kind']}, used as a {kind}")
    return site


def _branch_free(bytes_, where):
    """Decode whole instructions before copying a span to another address.
    Opcode-looking bytes inside immediates/displacements are harmless; near
    conditional branches and prefixed branches still need relocation.
    ndisasm prints undecodable/truncated instructions as db or lone prefixes.
    """
    tool = os.path.join(os.environ.get("NASM_DIR", ""), "ndisasm")
    try:
        done = subprocess.run([tool, "-b", "32", "-"], input=bytes_, capture_output=True,
                              check=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as error:
        raise Bad(f"{where}: cannot decode the span with ndisasm: {error}") from error
    prefixes = {"o16", "o32", "a16", "a32", "lock", "rep", "repe", "repne", "repz", "repnz",
                "cs", "ds", "es", "fs", "gs", "ss", "bnd", "xacquire", "xrelease"}
    decoded = bytearray()
    for line in done.stdout.decode().splitlines():
        continuation = re.fullmatch(r"\s+-([0-9A-F]+)", line)
        if continuation:
            decoded.extend(bytes.fromhex(continuation[1]))
            continue
        row = re.fullmatch(r"([0-9A-F]+)\s+([0-9A-F]+)\s+(.+)", line)
        if row is None or int(row[1], 16) != len(decoded):
            raise Bad(f"{where}: cannot decode the complete span: {line!r}")
        decoded.extend(bytes.fromhex(row[2]))
        instruction = row[3].strip()
        words = instruction.split()
        while words and words[0] in prefixes:
            words.pop(0)
        if not words or words[0] == "db":
            raise Bad(f"{where}: the span contains an invalid or incomplete instruction: {instruction}")
        if re.search(r"\b(?:j[a-z]+|loop[a-z]*|call|xbegin)\s+"
                     r"(?:(?:near|short|word|dword)\s+)*0x[0-9a-f]+$", instruction):
            raise Bad(f"{where}: the bytes have a relative branch; they cannot be relocated or replayed "
                      "(use a code hook)")
    if decoded != bytes_:
        raise Bad(f"{where}: ndisasm did not decode the complete span")


def _typed(patch_name, patch_no, kind, site, handler, f):
    """The game function a hook wraps (`f`, an engine_026g.tsv row) and the
    typed arguments and result the handler and its `Original` take -- from the
    callee's `vostok` column, so every patch hooking it gets the same typed
    signature. The `Original` type's name is made from the function's."""
    v = f.get("vostok")
    if not v:
        raise Bad(f"{patch_name}: {f['symbol']} has no `vostok` typed signature in engine_026g.tsv; a {kind} hook "
                  "needs one (the raw layer owns the typing)")
    args = []
    tags = set(engine_026g.kinds(engine_026g.fields()))
    for (ckind, _), (label, vtype) in zip(f["params"], v["args"]):
        if vtype not in TYPES:
            raise Bad(f"{patch_name}: {f['symbol']}'s vostok type {vtype!r} is unknown (have {', '.join(TYPES)})")
        if engine_026g.raw_type(ckind, tags) != TYPES[vtype]["raw"]:
            raise Bad(f"{patch_name}: {label} is {vtype} (raw {TYPES[vtype]['raw']}), but {f['symbol']} takes "
                      f"{engine_026g.raw_type(ckind, tags)} there")
        args.append((label, vtype))
    returns = v["result"]
    if returns not in RESULTS:
        raise Bad(f"{patch_name}: {f['symbol']}'s vostok result {returns!r} is unknown (have {', '.join(RESULTS)})")
    if f["result"] not in RESULTS[returns]["raw"]:
        raise Bad(f"{patch_name}: the vostok result is {returns}, but {f['symbol']}'s is {f['result']}")
    return args, {"patch": patch_name, "patch_no": patch_no, "kind": kind, "site": site["va"],
                  "site_name": site["site"], "function": f["symbol"], "handler": handler, "args": args,
                  "returns": returns, "orig": "Orig" + camel(f["symbol"].removeprefix("engine_")),
                  "what": site["what"], "target": f["va"], "pops": f["cleanup"], "params": f["params"],
                  "raw_params": [engine_026g.raw_type(ckind, tags, "raw::") for ckind, _ in f["params"]],
                  "raw_ret": None if engine_026g.return_kind(f["ret"]) is None
                  else engine_026g.raw_type(f["ret"], tags, "raw::"),
                  "entry": f"{patch_name}_{handler}", "shim": f"hook_{patch_name}_{handler}"}


def call_hook(patch, row, sites, functions, exe=None):
    """A `[[call]]`: the game's `call F` at the site becomes a call of the
    entry (RUST_CALL), which hands the shim F's arguments. The replaced bytes
    (a `call rel32` to F) are derived; the install checks them against the
    exe."""
    name = patch["name"]
    site = site_of(name, "call", row, sites)
    f = engine_row(site["callee"], functions)
    if f["call"] not in ("stdcall", "cdecl"):
        raise Bad(f"{name}: {site['callee']} is {f['call']}; a call hook needs stdcall or cdecl (a register "
                  "convention would need a reverse thunk, not built yet)")
    args, h = _typed(name, patch["patch"], "call", site, row["handler"], f)
    original = b"\xE8" + struct.pack("<I", (f["va"] - (site["va"] + 5)) & 0xFFFFFFFF)
    h.update(original=original, entry_macro=("RUST_CALL", len(args), f["cleanup"]), install=("call", 0xE8),
             orig_kind="direct")
    return h


def convention_hook(patch, row, sites, functions, kind, exe=None):
    """A `[[pointer]]`, `[[vtable]]` or `[[callback]]`: the game calls our
    entry in the callee's convention (thiscall or cdecl); the `Original` is
    the callee (the function the slot or callback used to name)."""
    name = patch["name"]
    site = site_of(name, kind, row, sites)
    f = engine_row(site["callee"], functions)
    convention = f["call"]
    if convention not in ("thiscall", "cdecl"):
        raise Bad(f"{name}: {site['callee']} is {convention}; a {kind} hook needs thiscall or cdecl")
    args, h = _typed(name, patch["patch"], kind, site, row["handler"], f)
    nargs = len(args) - (1 if convention == "thiscall" else 0)
    if nargs < 0:
        raise Bad(f"{name}: a thiscall {kind} takes `this` as its first argument")
    macro = "RUST_THISCALL" if convention == "thiscall" else "RUST_CDECL"
    h.update(original=struct.pack("<I", f["va"]), convention=convention, entry_macro=(macro, nargs),
             install=(kind, None), orig_kind="direct", this=convention == "thiscall", proof=row.get("proof"))
    return h


def splice_hook(patch, row, sites, functions, exe=None):
    """A `[[splice]]`: the function start jumps to our entry (the game calls
    it in the function's convention), and the `Original` is a trampoline --
    the relocated prologue then a jump past it. The prologue is the site's
    span, read from the exe and checked branch-free."""
    name = patch["name"]
    site = site_of(name, "splice", row, sites)
    f = engine_row(site["callee"], functions)
    convention = f["call"]
    if convention not in ("stdcall", "cdecl", "thiscall"):
        raise Bad(f"{name}: {site['callee']} is {convention}; a splice needs stdcall, cdecl or thiscall")
    prologue = span_bytes(name, site, exe)
    _branch_free(prologue, f"{name} splice at {site['va']:#x}")
    args, h = _typed(name, patch["patch"], "splice", site, row["handler"], f)
    this = convention == "thiscall"
    nargs = len(args) - (1 if this else 0)
    if this and nargs < 0:
        raise Bad(f"{name}: a thiscall splice takes `this` as its first argument")
    macro = {"stdcall": ("RUST_CALL", nargs, f["cleanup"]), "cdecl": ("RUST_CDECL", nargs),
             "thiscall": ("RUST_THISCALL", nargs)}[convention]
    h.update(original=prologue, convention=convention, this=this, entry_macro=macro, install=("splice", 0xE9),
             orig_kind="trampoline", trampoline=(prologue, site["va"] + len(prologue)))
    # A splice's Original must call this entry's trampoline, not the direct
    # function (which now detours) or another hook's trampoline.
    h["orig"] += "For" + camel(name) + "_" + camel(row["handler"])
    return h


_DEFAULT_EXE = []


def original_reader(data):
    """Bounded VA reader for both native instructions and read-only tables."""
    import patch_026g
    sections = list(patch_026g.Headers(data).sections(data))
    def read(va, count):
        rva = va - patch_026g.IMAGE_BASE
        for _, start, _, raw, size, _ in sections:
            offset = rva - start
            if offset >= 0 and count >= 0 and offset + count <= size:
                return data[raw + offset:raw + offset + count]
        raise Bad(f"{va:#x}: {count} bytes outside the original exe's backed sections")
    return read


def default_exe():
    """A reader of the original exe the environment names (SRP_026G_EXE, or
    `--exe`), its sha256 checked; None without one."""
    if not _DEFAULT_EXE:
        path = os.environ.get("SRP_026G_EXE")
        reader = None
        if path and os.path.isfile(path):
            import hashlib
            import patch_026g
            data = open(path, "rb").read()
            if hashlib.sha256(data).hexdigest() != patch_026g.EXE_SHA256:
                raise Bad(f"{path}: not the original 0.26g exe (sha256)")
            reader = original_reader(data)
        _DEFAULT_EXE.append(reader)
    return _DEFAULT_EXE[0]


def span_bytes(patch_name, site, exe):
    """The site's replaced bytes, read from the original exe (the span length
    is the site's). The exe is where arbitrary game bytes come from; a call or
    pointer derives its bytes instead and does not need it."""
    if site["span"] is None:
        raise Bad(f"{patch_name}: site {site['site']} needs a `span` (its length) in sites_026g.tsv")
    exe = exe or default_exe()
    if exe is None:
        raise Bad(f"{patch_name}: site {site['site']} ({site['kind']}) needs the original exe to read its "
                  f"{site['span']} bytes")
    return bytes(exe(site["va"], site["span"]))


def lohook_hook(patch, row, sites, exe=None):
    """A `[[lohook]]`: a detour at the site's span (read from the exe,
    branch-free so Continue can replay it). The handler gets a Context and
    returns a Flow; the site's `exits` name the jump targets."""
    name = patch["name"]
    site = site_of(name, "lohook", row, sites)
    span = span_bytes(name, site, exe)
    if len(span) < 5:
        raise Bad(f"{name}: the lohook span at {site['va']:#x} is {len(span)} bytes; a jump needs 5")
    _branch_free(span, f"{name} lohook at {site['va']:#x}")
    return {"patch": name, "patch_no": patch["patch"], "kind": "lohook", "site": site["va"],
            "site_name": site["site"], "original": span, "handler": row["handler"], "what": site["what"],
            "exits": site["exits"], "order": row.get("order"), "install": ("lohook", 0xE9),
            "entry": f"{name}_{row['handler']}", "shim": f"hook_{name}_{row['handler']}"}


def lohook_entry(h):
    """The NASM of a lohook entry: save, call the shim, take its Flow code,
    restore, and jump where it says (the replay stub, past the span, or an
    exit). Reached by a jump from the site; leaves esp as it was."""
    e, past = h["entry"], h["site"] + len(h["original"])
    lines = [f"global {e}", f"extern {h['shim']}", f"{e}:",
             "    lea esp, [esp - 4]",                  # dispatch slot; keep the game's flags for pushfd
             "    pushfd", "    pushad", "    cld",
             "    mov ebp, esp",                        # ebp -> Regs; [ebp+36] the slot
             "    sub esp, 512", "    and esp, -16", "    fxsave [esp]", "    mov edi, esp",
             "    sub esp, 8", "    and esp, -16",      # the Context Frame {regs, fxsave}
             "    mov [esp], ebp", "    mov [esp+4], edi",
             "    mov eax, esp", "    sub esp, 12", "    push eax",
             f"    call {h['shim']}",                   # eax = the Flow code
             f"    mov edx, {e}_replay",                # 0: Continue
             "    cmp eax, 0", f"    je {e}_go",
             f"    mov edx, {past:#x}",                 # 1: Skip
             "    cmp eax, 1", f"    je {e}_go"]
    for i, (_, addr) in enumerate(h["exits"]):          # 2 + i: the named exits
        lines += [f"    mov edx, {addr:#x}", f"    cmp eax, {2 + i}", f"    je {e}_go"]
    lines += ["    ud2",                                # an undeclared Flow: a bug
              f"{e}_go:", "    mov [ebp + 36], edx",
              "    fxrstor [edi]", "    mov esp, ebp", "    popad", "    popfd", "    ret",
              f"{e}_replay:", "    db " + ", ".join(f"0x{b:02x}" for b in h["original"]), f"    jmp {past:#x}"]
    return lines


def entry_hook(patch, row, sites):
    """An `[[entry]]`: a Rust handler our own NASM calls (cdecl; a patch's
    code at a fixed place calls it through a dword the build writes). No site
    in the exe, nothing replaced or installed: the entry saves the machine
    and aligns the stack as a lohook's does, hands the handler a Context
    (its arguments are the site's ESP frame, `holds`), and returns to the
    caller. Its handler returns Flow::Continue."""
    name = patch["name"]
    site = site_of(name, "entry", row, sites)
    if site["exits"] or site["span"] is not None:
        raise Bad(f"{name}: entry {site['site']} has no span and no exits (it returns to its caller)")
    return {"patch": name, "patch_no": patch["patch"], "kind": "entry", "site": None,
            "site_name": site["site"], "original": b"", "handler": row["handler"], "what": site["what"],
            "exits": [], "install": ("entry", None), "entry": f"{name}_{row['handler']}",
            "shim": f"hook_{name}_{row['handler']}"}


def entry_template(h):
    """The NASM of an entry: a lohook's save (the same frame, so the
    Context's site ESP is the caller's: the return address, then the
    arguments) with the stack aligned to 16 at the shim's call, then the
    machine restored and a `ret` to the caller. A Flow other than Continue
    is a bug (ud2)."""
    e = h["entry"]
    return [f"global {e}", f"extern {h['shim']}", f"{e}:",
            "    lea esp, [esp - 4]",                   # a lohook's dispatch slot: the same Regs frame
            "    pushfd", "    pushad", "    cld",
            "    mov ebp, esp",
            "    sub esp, 512", "    and esp, -16", "    fxsave [esp]", "    mov edi, esp",
            "    sub esp, 8", "    and esp, -16",
            "    mov [esp], ebp", "    mov [esp+4], edi",
            "    mov eax, esp", "    sub esp, 12", "    push eax",
            f"    call {h['shim']}",
            "    cmp eax, 0", f"    je {e}_go",
            "    ud2",
            f"{e}_go:", "    fxrstor [edi]", "    mov esp, ebp", "    popad", "    popfd",
            "    lea esp, [esp + 4]", "    ret"]


def code_hook(patch, row, sites, exe=None):
    """A `[[code]]`: hand-written NASM (the escape hatch) the author gives
    (`source`, its `symbol`, a byte `limit`); linked into patches.code and
    installed from the site by a jump or call. The site gives the VA and the
    span (its replaced bytes, read from the exe)."""
    name = patch["name"]
    site = site_of(name, "code", row, sites)
    for key in ("source", "symbol"):
        if key not in row:
            raise Bad(f"{name}: a [[code]] needs `{key}`")
    opcode = row.get("opcode", 0xE9)
    if opcode not in (0xE8, 0xE9):
        raise Bad(f"{name}: a [[code]] `opcode` is 0xE8 (call) or 0xE9 (jmp)")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", row["symbol"]) or not str(row["source"]).endswith(".asm"):
        raise Bad(f"{name}: a [[code]] `symbol` is an identifier and `source` a .asm file")
    return {"patch": name, "patch_no": patch["patch"], "kind": "code", "site": site["va"],
            "site_name": site["site"], "original": span_bytes(name, site, exe), "entry": row["symbol"],
            "source": row["source"], "install": ("code", opcode), "limit": row.get("limit"), "what": site["what"]}


def hooks(tomls=None, functions=None, sites=None, exe=None):
    tomls = read_tomls() if tomls is None else tomls
    functions = engine_026g.every_function() if functions is None else functions
    sites = read_sites() if sites is None else sites
    out = []
    for patch in tomls:
        for row in patch.get("hook", ()):
            if "site" not in row or row["site"] not in sites:
                raise Bad(f"{patch['name']}: a [[hook]] names a `site` of sites_026g.tsv "
                          f"(got {row.get('site')!r})")
            kind = sites[row["site"]]["kind"]       # the kind follows from the site
            if kind == "call":
                out.append(call_hook(patch, row, sites, functions, exe))
            elif kind in ("pointer", "vtable", "callback"):
                out.append(convention_hook(patch, row, sites, functions, kind, exe))
            elif kind == "splice":
                out.append(splice_hook(patch, row, sites, functions, exe))
            elif kind == "code":
                out.append(code_hook(patch, row, sites, exe))
            elif kind == "lohook":
                out.append(lohook_hook(patch, row, sites, exe))
            elif kind == "entry":
                out.append(entry_hook(patch, row, sites))
            else:
                raise Bad(f"{patch['name']}: site {row['site']} has unknown kind {kind!r}")
    entries = [h["entry"] for h in out]
    if len(set(entries)) != len(entries):
        raise Bad("two hooks with the same entry symbol")
    # Sharing an exact lohook site is explicit and ordered. Partial overlaps,
    # mixed kinds and implicit order remain errors. One machine save/replay
    # wraps the chain; the first non-Continue result ends it.
    # A callback rewrites nothing at its VA (the game is handed its entry): each is its own.
    grouped = {}
    for h in out:
        key = h["site_name"] if h["site"] is None else h["entry"] if h["kind"] == "callback" else h["site"]
        grouped.setdefault(key, []).append(h)
    out = []
    for group in grouped.values():
        if len(group) == 1:
            out.extend(group)
            continue
        orders = [h.get("order") for h in group]
        if (any(h["kind"] != "lohook" for h in group)
                or any(type(order) is not int for order in orders)
                or len(set(orders)) != len(orders)):
            raise Bad("shared hook site needs lohooks with distinct explicit orders")
        first = group[0]
        if any((h["site_name"], h["original"], h["exits"]) !=
               (first["site_name"], first["original"], first["exits"]) for h in group):
            raise Bad("shared lohooks must name the same site, span and exits")
        chain = sorted(group, key=lambda h: h["order"])
        out.append({**chain[0], "shim": chain[0]["shim"] + "_chain", "chain": chain})
    # The overlap audit for the Rust hooks (the whole arena's, across the asm
    # and C installs too, is selftest_026g.py's span check): no two sites'
    # replaced spans overlap. Each hook names its owning patch.
    spans = sorted((h["site"], h["site"] + len(h["original"]), h["patch"]) for h in out
                   if h["site"] is not None and h["kind"] != "callback")
    for (lo, hi, a), (lo2, _, b) in zip(spans, spans[1:]):
        if lo2 < hi:
            raise Bad(f"the hooks of {a} and {b} overlap at {lo2:#x} (the bytes {lo:#x}..{hi:#x})")
    return out


def runtime_vtables(tomls=None, hs=None, fields=None):
    """Copies declared by name, with their layout from the raw field table.

    The source is an image obj<methods> row. That kind gives its byte size
    and RTTI locator at -4. A declared vtable hook must belong to exactly one
    copy owned by that patch; its callee supplies the slot's checked ABI.
    """
    tomls = read_tomls() if tomls is None else tomls
    if hs is None:
        sites = read_sites()
        only_vtables = [{**p, "hook": [r for r in p.get("hook", ()) if sites[r["site"]]["kind"] == "vtable"]} for p in tomls]
        hs = hooks(tomls=only_vtables)
    fields = engine_026g.fields() if fields is None else fields
    kinds = engine_026g.kinds(fields)
    images = {f["field"]: f for f in fields if f["module"] == "image"}
    tables, claimed, symbols = [], set(), set()
    for patch in tomls:
        for declaration in patch.get("vtable", ()):
            name, source = declaration.get("name"), declaration.get("source")
            image = images.get(source)
            if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", name) or not image or image["of"] != "obj":
                raise Bad(f"{patch['name']}: vtable needs a name and a typed image source")
            layout = kinds[engine_026g.module_of(image["target"])]
            size = layout["size"]["offset"] if layout["size"] else 0
            if size <= 0 or size % 4 or size > 1024 or not any(
                    f["field"] == "rtti" and f["offset"] == -4 and f["type"] == "u32" for f in layout["fields"]):
                raise Bad(f"{patch['name']}: vtable source {source} needs whole slots and its RTTI at -4")
            start = image["offset"]
            slots = { (h["site"] - start) // 4: h for h in hs
                      if h["kind"] == "vtable" and h["patch"] == patch["name"]
                      and start <= h["site"] < start + size and (h["site"] - start) % 4 == 0 }
            if not slots:
                raise Bad(f"{patch['name']}: vtable {name} replaces no slots")
            for h in slots.values():
                if h["entry"] in claimed:
                    raise Bad(f"{patch['name']}: vtable slot {h['site_name']} belongs to several copies")
                if not h.get("proof") or not declaration.get("check"):
                    raise Bad(f"{patch['name']}: vtable slots need their native dispatch check and proof labels")
                claimed.add(h["entry"])
            symbol = f"{patch['name']}_{name}_vtable"
            if symbol in symbols:
                raise Bad(f"duplicate vtable symbol {symbol}")
            symbols.add(symbol)
            tables.append(dict(symbol=symbol, source=start, count=size // 4, slots=slots,
                               check=declaration["check"], patch=patch["name"], layout=layout["type"]))
    for h in hs:
        if h["kind"] == "vtable" and h["entry"] not in claimed:
            raise Bad(f"{h['patch']}: vtable hook {h['site_name']} has no runtime copy")
    return tables


def vtable_words(table, exe=None):
    exe = exe or default_exe()
    if exe is None:
        raise Bad(f"{table['symbol']}: runtime vtable needs the original exe")
    size = (table["count"] + 1) * 4
    data = bytes(exe(table["source"] - 4, size))
    if len(data) != size:
        raise Bad(f"{table['symbol']}: truncated native vtable")
    words = list(struct.unpack(f"<{table['count'] + 1}I", data))
    for index, hook in table["slots"].items():
        if words[index + 1] != hook["target"]:
            raise Bad(f"{table['symbol']}: slot {index} does not name its declared native callee")
        words[index + 1] = hook["entry"]
    return words


def installed_vtables(tomls=None, hs=None, fields=None):
    """The same generated copies feed the whole-client ABI/dispatch audit."""
    return tuple((f"{t['patch']} runtime vtable", "patches.code", t["symbol"], t["source"],
                  t["count"], len(t["slots"]),
                  {i: (t["check"], h["proof"]) for i, h in t["slots"].items()})
                 for t in runtime_vtables(tomls, hs, fields))


def rs_text(hs, tables=()):
    originals = {}
    lines = [f"// The Rust hooks' glue ({GENERATED}).",
             "//",
             "// Included inside `vostok` (crate::vostok::generated): each hook's",
             "// `Original` (the game's own function, typed) and its `extern \"C\"` shim,",
             "// which the generated NASM entry (hook_entries_026g.asm) calls with the",
             "// site's arguments. The shim builds the typed arguments and calls the",
             "// patch's function (rust_patches.md)."]
    for h in [member for h in hs for member in h.get("chain", [h])]:
        if h["kind"] == "code":
            continue                                   # raw NASM, no shim or Original
        if h["kind"] in ("lohook", "entry"):
            lines += ["", f"// ---- {h['patch']} (patch {h['patch_no']}) ----", ""]
            arms = ["        Flow::Continue => 0,", "        Flow::Skip => 1,"]
            if h["exits"]:
                camel = lambda s: "".join(w.title() for w in s.split("_"))
                enum = camel(h["patch"]) + camel(h["handler"]) + "Exit"
                lines += [f"/// The named exits of {h['patch']}::{h['handler']} (the order the shim's Flow code",
                          "/// follows, 2 upward).", "#[repr(u32)]", "#[allow(dead_code)]",
                          f"pub enum {enum} {{ " + ", ".join(camel(n) for n, _ in h["exits"]) + " }"]
                arms.append("        Flow::Exit(e) => 2 + e as u32,")
            else:
                arms.append("        Flow::Exit(e) => match e {},")
            at = h["site_name"] if h["site"] is None else f"{h['site']:#x}"
            whence = (f"from our own code's call ({h['site_name']})" if h["site"] is None
                      else f"from the game's jump at {h['site']:#x}")
            lines += [
                f"/// The entry `{h['entry']}` ({at}, {h['what']}) calls this with the saved machine.",
                "#[unsafe(no_mangle)]",
                f"pub extern \"C\" fn {h['shim']}(frame: &mut Frame) -> u32 {{",
                f"    // SAFETY: only the entry `{h['entry']}` calls this, {whence},",
                "    // on the game's thread; `frame` is its saved registers and fxsave area.",
                "    let mut ctx = unsafe { Context::new(frame) };",
                f"    match crate::{h['patch']}::{h['handler']}(&mut ctx) {{",
                *arms,
                "    }",
                "}",
            ]
            continue
        result = RESULTS[h["returns"]]
        if h["kind"] == "callback":
            # A callback the patch hands the game: no Original to call (the
            # callee only names the convention), so the handler gets the typed
            # arguments alone; the marker type names the entry's convention.
            lines += ["", f"// ---- {h['patch']} (patch {h['patch_no']}) ----", ""]
            if h["orig"] not in originals:
                originals[h["orig"]] = ("callback",)
                lines += [f"/// The convention of {h['function']} ({h['target']:#x}), a callback's: a marker for",
                          "/// the callback entries made in it (no function of the game is called through it).",
                          f"pub struct {h['orig']};", ""]
            elif originals[h["orig"]] != ("callback",):
                raise Bad(f"{h['orig']}: a callback's marker and an Original have the same generated name")
            lines += [
                f"/// The entry `{h['entry']}` (a callback in {h['function']}'s convention, {h['what']})",
                f"/// calls this with its {len(h['args'])} arguments, typed by the row (the `raw` layer's).",
                "///",
                "/// # Safety",
                f"/// Called only by the entry `{h['entry']}`.",
                "#[unsafe(no_mangle)]",
                f"pub unsafe extern \"C\" fn {h['shim']}({', '.join(f'a{i}: {t}' for i, t in enumerate(h['raw_params']))}) -> u32 {{",
                f"    // SAFETY: only the entry `{h['entry']}` calls this, when the game calls the callback",
                f"    // a patch handed it, on the thread that asked; a0.. are the callback's arguments.",
                "    let thread = unsafe { Thread::new() };",
            ]
            for i, (n, v) in enumerate(h["args"]):
                if TYPES[v].get("fallible"):
                    raise Bad(f"{h['patch']}: a callback's {v} must be a binding, not fallible (no Original to fall back on)")
                lines.append("    " + TYPES[v]["binding"].format(n=n, a=f"a{i}"))
            passed = ", ".join(TYPES[v]["pass"].format(n=n) for n, v in h["args"])
            lines += ["    " + result["to_u32"].format(v=f"crate::{h['patch']}::{h['handler']}({passed})"), "}"]
            continue
        # the function to call: itself (`call`, convention entries) or the
        # splice trampoline (its start now jumps to us, so calling it would
        # recurse); the trampoline runs the relocated prologue and the rest.
        if h["orig_kind"] == "trampoline":
            target_fn, abi = f"{h['entry']}_tramp", h["convention"]
        else:
            target_fn, abi = h["function"], None
        raw_call = f"{target_fn}(" + ", ".join(TYPES[v]["orig_raw"].format(n=n) for n, v in h["args"]) + ")"
        if abi is None:
            raw_call = "raw::" + raw_call
        orig_body = result["from_raw"].format(x=raw_call)
        orig_params = ", ".join(f"{n}: {TYPES[v]['orig_type']}" for n, v in h["args"])
        lines += ["", f"// ---- {h['patch']} (patch {h['patch_no']}) ----", ""]
        if h["orig_kind"] == "trampoline":
            ret = "" if h["raw_ret"] is None else f" -> {h['raw_ret']}"
            lines += [f"/// The splice trampoline for {h['function']} ({h['target']:#x}): its relocated prologue,",
                      "/// then a jump past the start our entry replaced (hook_entries_026g.asm).",
                      f'unsafe extern "{abi}" {{ fn {h["entry"]}_tramp('
                      + ", ".join(f"a{i}: {t}" for i, t in enumerate(h["raw_params"])) + f"){ret}; }}",
                      ""]
        original_key = (target_fn, abi, orig_params, result["type"])
        if h["orig"] in originals and originals[h["orig"]] != original_key:
            raise Bad(f"{h['orig']}: two different Originals have the same generated type name")
        if h["orig"] not in originals:
            originals[h["orig"]] = original_key
            lines += [
                f"/// {h['function']} ({h['target']:#x}), as the {h['kind']} hook at {h['site']:#x} wraps it.",
                f"pub struct {h['orig']};",
                "",
                f"impl {h['orig']} {{",
                "    /// The game's own function, with these typed arguments.",
                f"    pub fn call(&self, {orig_params})" + ("" if result["type"] == "()" else f" -> {result['type']}") + " {",
                f"        // SAFETY: {h['function']} at its own site; the arguments are the hook's,",
                "        // typed by the row (engine_026g.tsv).",
                f"        unsafe {{ {orig_body} }}",
                "    }",
                "}",
                "",
            ]
        lines += [
            f"/// The entry `{h['entry']}` ({h['site']:#x}, {h['what']}) calls this with",
            f"/// {h['function']}'s {len(h['args'])} arguments, typed by its row (the `raw` layer's).",
            "///",
            "/// # Safety",
            f"/// Called only by the entry `{h['entry']}`.",
            "#[unsafe(no_mangle)]",
            f"pub unsafe extern \"C\" fn {h['shim']}({', '.join(f'a{i}: {t}' for i, t in enumerate(h['raw_params']))}) -> u32 {{",
            f"    // SAFETY: only the entry `{h['entry']}` calls this, from the game's call at",
            f"    // {h['site']:#x}, on the game's thread; a0.. are {h['function']}'s arguments.",
            "    let thread = unsafe { Thread::new() };",
        ]
        null_args = ", ".join(TYPES[v]["null"].format(a=f"a{i}") for i, (_, v) in enumerate(h["args"]))
        null = f"unsafe {{ {'raw::' if abi is None else ''}{target_fn}({null_args}) }}"
        null_ret = result["to_u32"].format(v=result["from_raw"].format(x=null))
        for i, (n, v) in enumerate(h["args"]):
            t = TYPES[v]
            if t.get("fallible"):
                lines += [
                    f"    let Some(mut {n}) = (unsafe {{ {t['build'].format(a=f'a{i}')} }}) else {{",
                    f"        // a null {v} never happens at this site; take the unpatched path.",
                    f"        return {null_ret};",
                    "    };",
                ]
            else:
                lines.append("    " + t["binding"].format(n=n, a=f"a{i}"))
        passed = ", ".join(["&orig"] + [TYPES[v]["pass"].format(n=n) for n, v in h["args"]])
        call = f"crate::{h['patch']}::{h['handler']}({passed})"
        lines += [
            f"    let orig = {h['orig']};",
            "    " + result["to_u32"].format(v=call),
            "}",
        ]
    for h in hs:
        if "chain" not in h:
            continue
        lines += ["", "#[unsafe(no_mangle)]",
                  f'pub extern "C" fn {h["shim"]}(frame: &mut Frame) -> u32 {{']
        for member in h["chain"]:
            lines += [f"    let flow = {member['shim']}(frame);", "    if flow != 0 { return flow; }"]
        lines += ["    0", "}"]
    for h in hs:
        if h["kind"] != "callback":
            continue
        lines += ["", f'unsafe extern "C" {{ fn {h["entry"]}(); }}',
                  f"/// The entry `{h['entry']}`, in {h['function']}'s convention ({h['what']}): a",
                  "/// callback the patch hands the game (no site is rewritten).",
                  f"pub fn {h['entry']}_entry() -> super::hook::CallbackEntry<{h['orig']}> {{",
                  "    // SAFETY: the generated entry lives for the executable's lifetime and takes the",
                  f"    // arguments of {h['function']}, whose `Original` names the entry's type.",
                  f"    unsafe {{ super::hook::CallbackEntry::from_entry({h['entry']} as *const () as *const c_void) }}",
                  "}"]
    for table in tables:
        symbol, count = table["symbol"], table["count"]
        lines += ["", f'unsafe extern "C" {{ static {symbol}: [u32; {count + 1}]; }}',
                  f"pub fn {symbol}_handle() -> super::project::NativeVtable<raw::{table['layout']}> {{",
                  "    // SAFETY: the generated immutable table lives for the executable's lifetime.",
                  f"    unsafe {{ super::project::NativeVtable::from_address(core::ptr::addr_of!({symbol}).cast::<u32>().add(1) as usize as u32) }}",
                  "}"]
    return "\n".join(lines) + "\n"


def asm_text(hs, tables=(), exe=None):
    lines = [f"; The Rust hooks' NASM entries ({GENERATED}).",
             "; Each entry (RUST_CALL, rust_hook_026g.inc) presents a site's arguments to",
             "; its shim and cleans up as the game's function did. The arena's block",
             "; patches.code (with the crate); link_026g.py installs each site.",
             "bits 32",
             "section .text",
             '%include "rust_hook_026g.inc"']
    for h in hs:
        if h["kind"] == "code":
            continue                                   # its own .asm source, not generated here
        if h["kind"] == "lohook":
            lines += ["", f"; {h['site']:#x} {h['what']}: lohook -> {h['entry']}"] + lohook_entry(h)
            continue
        if h["kind"] == "entry":
            lines += ["", f"; {h['site_name']} {h['what']}: entry -> {h['entry']}"] + entry_template(h)
            continue
        macro = h["entry_macro"]
        lines += ["", f"; {h['site']:#x} {h['what']}: {h['kind']} -> {h['entry']} (wraps {h['function']} "
                  f"{h['target']:#x})"]
        if macro[0] == "RUST_CALL":
            lines += [f"global {h['entry']}", f"{h['entry']}:", f"    RUST_CALL {h['shim']}, {macro[1]}, {macro[2]}"]
        else:                                          # RUST_THISCALL / RUST_CDECL define the label themselves
            lines.append(f"    {macro[0]} {h['entry']}, {h['shim']}, {macro[1]}")
        if h.get("trampoline"):                        # splice: the relocated prologue, then a jump past it
            prologue, past = h["trampoline"]
            lines += [f"global {h['entry']}_tramp", f"{h['entry']}_tramp:",
                      "    db " + ", ".join(f"0x{b:02x}" for b in prologue), f"    jmp {past:#x}"]
    for table in tables:
        lines += ["", "section .rodata", "align 4", f"global {table['symbol']}", f"{table['symbol']}:"]
        lines += [f"    dd {word if isinstance(word, str) else hex(word)}" for word in vtable_words(table, exe)]
    return "\n".join(lines) + "\n"


def outputs(tomls=None, functions=None, sites=None, exe=None):
    hs = hooks(tomls, functions, sites, exe)
    tables = runtime_vtables(tomls, hs)
    return {RS: rs_text(hs, tables).encode(), ASM: asm_text(hs, tables, exe).encode()}


def installs(exe=None, tomls=None, functions=None, sites=None):
    """(site VA, replaced bytes, entry symbol, opcode, owner) for each hook
    installed by rewriting a call or jump site, for patch_026g.py. A call's
    bytes are derived (a `call rel32` to the callee), so the exe is not
    needed for one; a span hook (splice, lohook, code) reads its bytes from
    `exe`. patch_026g.py's apply() checks every write against the exe. A
    Runtime vtable slots belong to generated copies, validated here and in
    the whole-client ABI audit. Other pointer installs remain unsupported."""
    out = []
    hs = hooks(tomls, functions, sites, exe)
    tables = runtime_vtables(tomls, hs)
    for table in tables:
        vtable_words(table, exe)
    for h in hs:
        how, opcode = h["install"]
        if how in ("vtable", "callback"):
            continue  # a runtime copy (audited above) or a callback handed at run time: no write
        if how == "entry":
            continue  # called by our own code, through what the build writes (no image install)
        if opcode is None:
            raise Bad(f"{h['patch']}: a {how} hook is not installed by a call/jump rewrite; patch_026g.py must "
                      "integrate its install before it can ship")
        out.append((h["site"], h["original"], h["entry"], opcode, h["patch"]))
    return out


