#!/usr/bin/env python3
"""The Rust hook glue: a patch declares its hooks in `rust/patches/src/
<patch>.toml` (docs/notes/rust_patches.md), and this writes the NASM entries
and the Rust shims that join the game's sites to the patch's functions.

    python hooks_026g.py --write
        writes hook_entries_026g.asm (the entries, the arena's block
        patches.code with the crate) and hooks_026g.rs (the shims and the
        `Original`s, included inside vostok)
    python hooks_026g.py --check
        says whether those two files are what the patches' TOML gives here
        (the self-test runs the same)

Each `[[call]]` row of a `<patch>.toml` is a hook on a game `call F`:

    at              the site (the `call rel32`)
    original        its five bytes; `at + 5 + rel32` must be F's VA
    function        F, a row of engine_026g.tsv (stdcall or cdecl, so Rust
                    calls it directly: no register thunk yet)
    handler         the patch's function (patches::<patch>::<handler>)
    args            one per F parameter, "name: VostokType": the typed value
                    the shim builds and the handler (and the Original) take
    returns         the handler's result, mapped to F's
    original_name   the generated `Original<F>` type the handler calls
    what            the site, for the comments and the self-test

The shim builds the typed arguments from the raw ones and calls the handler
with an `Original` (F, typed); the entry (RUST_CALL, rust_hook_026g.inc)
aligns the stack and cleans up as F did. link_026g.py installs the site to
the entry and audits the overlap. Only the kinds a ported patch needs are
generated; splice, lohook, pointer, vtable, callback and code are the
design's (rust_patches.md) and come with their first patch.
"""
import argparse
import re
import struct
import sys
import tomllib
from pathlib import Path

import engine_026g

HERE = Path(__file__).resolve().parent
TOML_DIR = HERE / "rust" / "patches" / "src"
RS = HERE / "hooks_026g.rs"
ASM = HERE / "hook_entries_026g.asm"
GENERATED = "generated by hooks_026g.py from the patches' <patch>.toml: do not edit"

# A Vostok type a `call` argument may have: the raw C type engine_026g.tsv
# must give for it (checked), how the shim builds it from the raw dword
# `{a}`, the type and the raw expression the Original uses, and how it is
# passed to the handler. `fallible` builds an Option (a handle; null takes
# the unpatched path); `binding` is the shim's `let`.
TYPES = {
    "InputHandler": {
        "raw": "*mut c_void",
        "fallible": True,
        "build": "InputHandler::from_raw(&thread, {a})",
        "orig_type": "&mut InputHandler",
        "orig_raw": "{n}.ptr()",
        "pass": "&mut {n}",
        "null": "{a} as usize as *mut _",
    },
    "Action": {
        "raw": "u32",
        "binding": "let {n} = Action({a});",
        "orig_type": "Action",
        "orig_raw": "{n}.0",
        "pass": "{n}",
        "null": "{a}",
    },
    "Out<u32>": {
        "raw": "*mut u32",
        "binding": "let mut {n} = unsafe {{ Out::<u32>::new(&thread, {a} as usize as *mut u32) }};",
        "orig_type": "&mut Out<u32>",
        "orig_raw": "{n}.at()",
        "pass": "&mut {n}",
        "null": "{a} as usize as *mut _",
    },
}
# A handler result, mapped to F's: the raw result engine_026g.tsv must give,
# the Vostok type and how F's raw result `{x}` becomes it (`Original::call`),
# and how that Vostok value `{v}` becomes the shim's u32 (EAX).
RESULTS = {
    "bool": {"raw": ("AL", "EAX"), "type": "bool", "from_raw": "{x} != 0", "to_u32": "u32::from({v})"},
    "u32": {"raw": ("EAX",), "type": "u32", "from_raw": "{x}", "to_u32": "{v}"},
}


class Bad(Exception):
    """A TOML the glue cannot make a hook of."""


def read_tomls():
    out = []
    for path in sorted(TOML_DIR.glob("*.toml")):
        data = tomllib.loads(path.read_text())
        if data.get("name") != path.stem:
            raise Bad(f"{path.name}: its `name` is the file's stem ({path.stem})")
        out.append(data)
    return out


def engine_row(symbol, functions):
    for f in functions:
        if f["symbol"] == symbol:
            return f
    raise Bad(f"{symbol}: no such row in engine_026g.tsv")


def call_hook(patch, row, functions):
    """A checked `[[call]]`: a dict the writers use."""
    name = patch["name"]
    for key in ("at", "original", "function", "handler", "args", "returns", "original_name", "what"):
        if key not in row:
            raise Bad(f"{name}: a [[call]] needs `{key}`")
    site = row["at"]
    original = bytes.fromhex(row["original"])
    if len(original) != 5 or original[0] != 0xE8:
        raise Bad(f"{name} at {site:#x}: `original` is a `call rel32` (five bytes, E8)")
    f = engine_row(row["function"], functions)
    target = (site + 5 + struct.unpack("<i", original[1:])[0]) & 0xFFFFFFFF
    if target != f["va"]:
        raise Bad(f"{name} at {site:#x}: the call goes to {target:#x}, not {row['function']}'s {f['va']:#x}")
    if f["call"] not in ("stdcall", "cdecl"):
        raise Bad(f"{name}: {row['function']} is {f['call']}; a `call` hook needs stdcall or cdecl (a register "
                  "convention would need a reverse thunk, not built yet)")
    if len(row["args"]) != len(f["params"]):
        raise Bad(f"{name}: {len(f['params'])} arguments of {row['function']}, {len(row['args'])} in `args`")
    args = []
    for (ckind, _), spec in zip(f["params"], row["args"]):
        label, _, vostok = spec.partition(":")
        label, vostok = label.strip(), vostok.strip()
        if vostok not in TYPES:
            raise Bad(f"{name}: no Vostok type {vostok!r} (have {', '.join(TYPES)})")
        if engine_026g.rust_type(ckind) != TYPES[vostok]["raw"]:
            raise Bad(f"{name}: {label} is {vostok} (raw {TYPES[vostok]['raw']}), but {row['function']} takes "
                      f"{engine_026g.rust_type(ckind)} there")
        args.append((label, vostok))
    if row["returns"] not in RESULTS:
        raise Bad(f"{name}: no result {row['returns']!r} (have {', '.join(RESULTS)})")
    if f["result"] not in RESULTS[row["returns"]]["raw"]:
        raise Bad(f"{name}: the handler returns {row['returns']}, but {row['function']}'s result is {f['result']}")
    pops = f["cleanup"]
    return {"patch": name, "patch_no": patch["patch"], "site": site, "original": original, "target": target,
            "function": row["function"], "handler": row["handler"], "args": args, "returns": row["returns"],
            "orig": row["original_name"], "what": row["what"], "pops": pops, "entry": f"{name}_{row['handler']}",
            "shim": f"hook_{name}_{row['handler']}", "params": f["params"]}


def hooks(tomls=None, functions=None):
    tomls = read_tomls() if tomls is None else tomls
    functions = engine_026g.every_function() if functions is None else functions
    out = []
    for patch in tomls:
        for row in patch.get("call", ()):
            out.append(call_hook(patch, row, functions))
        for kind in ("splice", "lohook", "pointer", "vtable", "callback", "code"):
            if patch.get(kind):
                raise Bad(f"{patch['name']}: `{kind}` hooks are the design's but not generated yet "
                          "(rust_patches.md); the first patch that needs one adds it")
    entries = [h["entry"] for h in out]
    if len(set(entries)) != len(entries):
        raise Bad("two hooks with the same entry symbol")
    # The overlap audit for the Rust hooks (the whole arena's, across the asm
    # and C installs too, is selftest_026g.py's span check): no two sites'
    # replaced spans overlap. Each hook names its owning patch.
    spans = sorted((h["site"], h["site"] + len(h["original"]), h["patch"]) for h in out)
    for (lo, hi, a), (lo2, _, b) in zip(spans, spans[1:]):
        if lo2 < hi:
            raise Bad(f"the hooks of {a} and {b} overlap at {lo2:#x} (the bytes {lo:#x}..{hi:#x})")
    return out


def rs_text(hs):
    lines = [f"// The Rust hooks' glue ({GENERATED}).",
             "//",
             "// Included inside `vostok` (crate::vostok::generated): each hook's",
             "// `Original` (the game's own function, typed) and its `extern \"C\"` shim,",
             "// which the generated NASM entry (hook_entries_026g.asm) calls with the",
             "// site's arguments. The shim builds the typed arguments and calls the",
             "// patch's function (rust_patches.md)."]
    for h in hs:
        result = RESULTS[h["returns"]]
        raw_call = f"raw::{h['function']}(" + ", ".join(TYPES[v]["orig_raw"].format(n=n) for n, v in h["args"]) + ")"
        orig_body = result["from_raw"].format(x=raw_call)
        orig_params = ", ".join(f"{n}: {TYPES[v]['orig_type']}" for n, v in h["args"])
        lines += [
            "",
            f"// ---- {h['patch']} (patch {h['patch_no']}) ----",
            "",
            f"/// {h['function']} ({h['target']:#x}), as the `call` hook at {h['site']:#x} wraps it.",
            f"pub struct {h['orig']};",
            "",
            f"impl {h['orig']} {{",
            "    /// The game's own function, with these typed arguments.",
            f"    pub fn call(&self, {orig_params}) -> {result['type']} {{",
            f"        // SAFETY: {h['function']} at its own site; the arguments are the hook's,",
            "        // typed by the row (engine_026g.tsv).",
            f"        unsafe {{ {orig_body} }}",
            "    }",
            "}",
            "",
            f"/// The entry `{h['entry']}` ({h['site']:#x}, {h['what']}) calls this with",
            f"/// {h['function']}'s {len(h['args'])} arguments.",
            "#[unsafe(no_mangle)]",
            f"pub extern \"C\" fn {h['shim']}({', '.join(f'a{i}: u32' for i in range(len(h['args'])))}) -> u32 {{",
            f"    // SAFETY: only the entry `{h['entry']}` calls this, from the game's call at",
            f"    // {h['site']:#x}, on the game's thread; a0.. are {h['function']}'s arguments.",
            "    let thread = unsafe { Thread::new() };",
        ]
        null = (f"unsafe {{ raw::{h['function']}("
                + ", ".join(TYPES[v]["null"].format(a=f"a{i}") for i, (_, v) in enumerate(h["args"])) + ") }")
        null_ret = result["to_u32"].format(v=result["from_raw"].format(x=null))
        for i, (n, v) in enumerate(h["args"]):
            t = TYPES[v]
            if t.get("fallible"):
                lines += [
                    f"    let Some(mut {n}) = (unsafe {{ {t['build'].format(a=f'a{i}')} }}) else {{",
                    f"        // a null {v} never happens at this site; take the unpatched path.",
                    f"        return {null_ret};",
                    "    };",
                ]
            else:
                lines.append("    " + t["binding"].format(n=n, a=f"a{i}"))
        passed = ", ".join(["&orig"] + [TYPES[v]["pass"].format(n=n) for n, v in h["args"]])
        call = f"crate::{h['patch']}::{h['handler']}({passed})"
        lines += [
            f"    let orig = {h['orig']};",
            "    " + result["to_u32"].format(v=call),
            "}",
        ]
    return "\n".join(lines) + "\n"


def asm_text(hs):
    lines = [f"; The Rust hooks' NASM entries ({GENERATED}).",
             "; Each entry (RUST_CALL, rust_hook_026g.inc) presents a site's arguments to",
             "; its shim and cleans up as the game's function did. The arena's block",
             "; patches.code (with the crate); link_026g.py installs each site.",
             "bits 32",
             "section .text",
             '%include "rust_hook_026g.inc"']
    for h in hs:
        lines += [
            "",
            f"; {h['site']:#x} {h['what']}: `call {h['function']}` ({h['target']:#x}) -> {h['entry']}",
            f"global {h['entry']}",
            f"{h['entry']}:",
            f"    RUST_CALL {h['shim']}, {len(h['args'])}, {h['pops']}",
        ]
    return "\n".join(lines) + "\n"


def outputs(tomls=None, functions=None):
    hs = hooks(tomls, functions)
    return {RS: rs_text(hs).encode(), ASM: asm_text(hs).encode()}


def installs(tomls=None, functions=None):
    """(site, original bytes, entry symbol, opcode, owner) per hook, for
    patch_026g.py."""
    return [(h["site"], h["original"], h["entry"], 0xE8, h["patch"]) for h in hooks(tomls, functions)]


def arena_sources():
    """The sources of the arena's block patches.code."""
    return ("rust/patches/Cargo.toml", ASM.name)


def stale():
    return [path.name for path, content in outputs().items()
            if not path.exists() or path.read_bytes() != content]


def strip_rust(text):
    """Rust source without its comments and string insides (so the layer
    check does not trip over them)."""
    text = re.sub(r'"(?:\\.|[^"\\])*"', '""', text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def check_layers():
    """The three layers (rust_patches.md): in the crate's own sources
    (rust/patches/src/**, not the generated `raw` includes) no game address,
    no hand-made binding (`GameFn`, `Import`, `transmute`, an `extern`
    block); and a patch module (src/<patch>.rs) forbids `unsafe` and never
    names `raw`. Raises Bad on a breach."""
    patches = {p.stem for p in TOML_DIR.glob("*.toml")}
    for path in sorted(TOML_DIR.rglob("*.rs")):
        where = path.relative_to(TOML_DIR.parent)
        # the game's build drops `#[cfg(test)]` (it is only the host tests);
        # those modules use plain values, not the game's, so skip them.
        code = strip_rust(path.read_text()).split("#[cfg(test)]")[0]
        number = r"(?<![\w.])(0[xX][0-9a-fA-F_]+|[0-9][0-9_]*)(?:[iu](?:8|16|32|64|128|size))?(?![\w.])"
        for m in re.finditer(number, code):
            token = m.group(1).replace("_", "")
            value = int(token, 16) if token[:2].lower() == "0x" else int(token)
            if value >= 0x10000:
                raise Bad(f"{where}: the literal {m.group(0)} is an address; game addresses are the generated "
                          "`raw` layer's alone (engine_026g.tsv, fields_026g.tsv)")
        hit = re.search(r"\bGameFn\b|\bImport\b|\btransmute\b|\blink_name\b|\bextern\s+(?:\"[^\"]*\"\s*)?\{", code)
        if hit:
            raise Bad(f"{where}: `{hit.group(0).strip()}` is a hand-made binding; a game function is a row of "
                      "engine_026g.tsv (the `raw` layer), never written by hand")
        if path.parent == TOML_DIR and path.stem in patches:
            if "#![forbid(unsafe_code)]" not in code:
                raise Bad(f"{where}: a patch module must have `#![forbid(unsafe_code)]`")
            if re.search(r"\braw\b", code):
                raise Bad(f"{where}: a patch module uses `vostok` alone, never `raw`")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write == args.check:
        parser.error("--write or --check")
    try:
        files = outputs()
    except Bad as error:
        sys.exit(f"hooks_026g: {error}")
    if args.write:
        for path, content in files.items():
            path.write_bytes(content)
        print(f"{RS.name} and {ASM.name}: {len(hooks())} hook(s)")
        return
    bad = [path.name for path, content in files.items() if not path.exists() or path.read_bytes() != content]
    print("hooks_026g: " + ("current" if not bad else "NOT what the TOML gives: " + ", ".join(bad)))
    raise SystemExit(1 if bad else 0)


if __name__ == "__main__":
    main()
