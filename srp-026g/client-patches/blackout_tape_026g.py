#!/usr/bin/env python3
"""Blackout's duct-tape table as exe patch 65 reads it (rust/patches/src/
blackout/tape.rs, docs/notes/blackout.md): blackout_tape_026g.rs, generated,
never edited, from ../scripts/blackout-tape/tape.tsv's rows of method `tape`.

    python blackout_tape_026g.py --write    # write blackout_tape_026g.rs
    python blackout_tape_026g.py --check    # whether it is the table's (exit 1 if not)

tape.tsv: tab-separated, `#` comment lines, a header row with at least
`slot` (torso, gloves or legs), `base_model`, `surface` (the model's
part_name), `method` (`tape` or `none`) and `status` (free text). A row of
method `tape` gives that slot's records of the model and surface a shell
record `ported/blackout_tape/<base_model, '/' as '_'>__<surface>` (surface
`tape`) in a Blackout match; the name and its zero must fit a record's 104h
bytes.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE.parent / "scripts" / "blackout-tape" / "tape.tsv"
RUST = HERE / "blackout_tape_026g.rs"
SLOTS = {"torso": "Torso", "gloves": "Gloves", "legs": "Legs"}
METHODS = ("tape", "none")
DIR = "ported/blackout_tape/"
ROOM = 0x104                         # a record's text room, its zero included
TEXT = re.compile(r"[A-Za-z0-9_./-]+")


class Bad(Exception):
    pass


def rows(path=TABLE):
    """tape.tsv's rows, as dicts (comment and blank lines skipped)."""
    lines = [line for line in path.read_text(encoding="utf-8").splitlines()
             if line.strip() and not line.lstrip().startswith("#")]
    reader = csv.DictReader(lines, delimiter="\t", quoting=csv.QUOTE_NONE)
    missing = {"slot", "base_model", "surface", "method", "status"} - set(reader.fieldnames or ())
    if missing:
        raise Bad(f"{path.name}: no column {', '.join(sorted(missing))}")
    return list(reader)


def taped(path=TABLE):
    """The rows of method `tape`: [(slot, base_model, surface)], sorted, each once."""
    out, seen = [], set()
    for number, row in enumerate(rows(path), 1):
        slot, model, surface, method = (row[k].strip() for k in ("slot", "base_model", "surface", "method"))
        where = f"{path.name}: row {number} ({slot} {model} {surface})"
        if slot not in SLOTS:
            raise Bad(f"{where}: slot is one of {', '.join(SLOTS)}")
        if method not in METHODS:
            raise Bad(f"{where}: method is tape or none")
        if not TEXT.fullmatch(model) or not TEXT.fullmatch(surface):
            raise Bad(f"{where}: a model and a surface are letters, digits, _ . / -")
        key = (slot, model, surface)
        if key in seen:
            raise Bad(f"{where}: twice")
        seen.add(key)
        if method != "tape":
            continue
        shell = f"{DIR}{model.replace('/', '_')}__{surface}"
        if len(shell) + 1 > ROOM:
            raise Bad(f"{where}: its shell {shell} and its zero do not fit a record's {ROOM:#x} bytes")
        out.append(key)
    if not out:
        raise Bad(f"{path.name}: no row of method tape")
    return sorted(out)


def rust(path=TABLE):
    """The Rust source of RUST."""
    keys = taped(path)
    lines = ["// Generated by blackout_tape_026g.py from srp-026g/scripts/blackout-tape/tape.tsv: do not edit.",
             "// The taped surfaces (its rows of method `tape`): a slot's model and its surface.",
             f"pub const TAPED: [Taped; {len(keys)}] = ["]
    lines += [f'    Taped {{ slot: TapeSlot::{SLOTS[slot]}, base_model: b"{model}", surface: b"{surface}" }},'
              for slot, model, surface in keys]
    return "\n".join(lines + ["];", ""])


def issue():
    """None when RUST is the table's, else what is wrong."""
    try:
        text = rust()
    except Bad as error:
        return str(error)
    try:
        current = RUST.read_text(encoding="utf-8")
    except OSError:
        current = None
    if current != text:
        return f"{RUST.name} is not {TABLE.name}'s: run python blackout_tape_026g.py --write"
    return None


def main():
    if sys.argv[1:] == ["--write"]:
        try:
            text = rust()
        except Bad as error:
            sys.exit(f"blackout_tape_026g: {error}")
        RUST.write_text(text, encoding="utf-8")
        print(f"wrote {RUST.name}: {text.count('Taped {')} taped surface(s)")
    elif sys.argv[1:] == ["--check"]:
        problem = issue()
        print(f"blackout_tape_026g: {problem or 'current'}")
        sys.exit(1 if problem else 0)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
