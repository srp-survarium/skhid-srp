    /// A crate 0.9 m high (a jump up) is a wall to a body walking by: no
    /// floor is left nearer a side of it than the body's radius, so a way
    /// along it keeps clear (level_08's crate by the wall, where bodies
    /// stood caught for minutes), and it is still jumped on, from a step
    /// back.
    #[test]
    fn a_body_walking_by_a_crate_it_could_jump_on_keeps_its_radius_off_it() {
        let mut tris = floor(0.0, 0.0, 10.0, 10.0, 0.0).to_vec();
        tris.extend(crate_box(4.0, 4.0, 6.0, 6.0, 0.9));
        let grid = WalkGrid::build(&tris, AREA, 0.25, Body::default());
        let radius = Body::default().radius - 0.01;
        // By a side (a corner's diagonal is eroded no more than a
        // wall's: the body slides round it).
        let beside = |p: Vec3| {
            let dx = (4.0 - p.x).max(p.x - 6.0).max(0.0);
            let dz = (4.0 - p.z).max(p.z - 6.0).max(0.0);
            p.y < 0.5 && dx.min(dz) == 0.0 && dx.max(dz) < radius
        };
        for node in 0..grid.len() as NodeId {
            let p = grid.position(node);
            assert!(
                !beside(p),
                "a floor at {p:?} is within the body's radius of the crate"
            );
        }
        // Along its side: the way keeps the radius off it.
        let a = grid.locate(Vec3::new(3.6, 0.0, 2.0), 0.3).unwrap();
        let b = grid.locate(Vec3::new(3.6, 0.0, 8.0), 0.3).unwrap();
        for node in grid.path(a, b).unwrap().nodes {
            assert!(!beside(grid.position(node)));
        }
        // Up on it: by a jump.
        let top = grid.locate(Vec3::new(5.0, 0.9, 5.0), 0.3).unwrap();
        let up: Vec<LinkKind> = grid
            .path(a, top)
            .unwrap()
            .nodes
            .windows(2)
            .filter_map(|w| grid.links(w[0]).find(|l| l.0 == w[1]).map(|l| l.1))
            .collect();
        assert!(up.contains(&LinkKind::Jump), "{up:?}");
    }

    /// A wall 1 m high and a cell thick is no jump's landing (the body
    /// slides off its top; level_07's wall had bots jumping at it): it is
    /// a wall, and no way goes over it.
    #[test]
    fn the_top_of_a_thin_wall_is_no_landing() {
        let mut tris = floor(0.0, 0.0, 10.0, 10.0, 0.0).to_vec();
        tris.extend(crate_box(5.0, 0.0, 5.2, 10.0, 1.0));
        let grid = WalkGrid::build(&tris, AREA, 0.25, Body::default());
        for node in 0..grid.len() as NodeId {
            assert!(
                grid.links(node).all(|(_, kind)| kind != LinkKind::Jump),
                "a jump from {:?}",
                grid.position(node)
            );
        }
        let a = grid.locate(Vec3::new(2.0, 0.0, 5.0), 0.3).unwrap();
        let b = grid.locate(Vec3::new(8.0, 0.0, 5.0), 0.3).unwrap();
        assert!(!grid.distances_from(&[a]).reaches(b));
    }

    /// A yard (x 0..10, z 0..10) with a ledge 0.9 m high from x 10 on, `depth` m deep and with nothing beyond it, with steps up to
    /// it from z 8 on when `steps`, `span` m wide (z) about z 5: built with the carried landings when `carry`. A seed on the yard's ground.
    fn ledge_island(depth: f32, span: f32, steps: bool, carry: bool) -> (WalkGrid, BuildStats) {
        ledge_island_with(depth, span, steps, Body { landing_carry: carry, ..Body::default() })
    }

    /// [`ledge_island`] on a given body.
    fn ledge_island_with(depth: f32, span: f32, steps: bool, body: Body) -> (WalkGrid, BuildStats) {
        let rise = 0.9;
        let mut tris: Vec<Triangle> = floor(0.0, 0.0, 10.0, 10.0, 0.0).to_vec();
        let (z0, z1) = (5.0 - 0.5 * span, 5.0 + 0.5 * span);
        tris.extend(floor(10.0, z0, 10.0 + depth, z1, rise));
        tris.extend(wall_x(10.0, z0, z1, rise));
        if steps {
            for s in 0..5 {
                let x0 = 8.0 + 0.4 * s as f32;
                tris.extend(floor(x0, 8.0, x0 + 0.4, 10.0, rise / 5.0 * (s + 1) as f32));
            }
        }
        let seeds = [Vec3::new(2.0, 0.0, 5.0)];
        WalkGrid::build_kept_with_stats(&tris, [0.0, 0.0, 20.0, 10.0], 0.25, body, &seeds, &seeds)
    }

    /// The Jump links straight up the ledge (along x), not by the steps.
    fn jumps(grid: &WalkGrid) -> usize {
        (0..grid.len() as NodeId)
            .map(|n| {
                let from = grid.position(n);
                grid.links(n)
                    .filter(|&(b, kind)| {
                        let to = grid.position(b);
                        kind == LinkKind::Jump && (to.x - from.x).abs() > 0.1 && (to.z - from.z).abs() < 0.1 && to.z < 7.5
                    })
                    .count()
            })
            .sum()
    }

    /// A jump's clip carries the body on past the ledge's face whatever it landed on ([`walking_press_lead`]): off the far
    /// side of a top 0.75 m deep, so with the steps up no jump is made onto it; a top 6 m deep keeps its jumps across.
    #[test]
    fn a_jump_onto_a_top_the_clip_carries_the_body_off_is_cut() {
        let (plain, stats) = ledge_island(0.75, 10.0, true, false);
        assert!(jumps(&plain) > 0, "{stats:?}");
        let (grid, shallow) = ledge_island(0.75, 10.0, true, true);
        assert_eq!(jumps(&grid), 0, "{shallow:?}");
        assert!(shallow.overshot_cut > 20 && shallow.overshot_kept == 0, "{shallow:?}");
        // Only the slanting ones at the ledge's ends are short of room.
        let (deep, stats) = ledge_island(6.0, 10.0, true, true);
        assert!(jumps(&deep) > 0 && stats.overshot_cut * 5 < shallow.overshot_cut, "{stats:?}");
    }

    /// A walking jump is pressed farther before a short top (the clip's root ends 2.67 m from the press), up to where the ledge's face is
    /// past the root's reach; a top 4 m deep is pressed as ever, and a ledge above the clip's apex has none.
    #[test]
    fn a_walking_jump_up_a_short_top_is_pressed_earlier() {
        assert!((walking_jump_far(0.9).unwrap() - 2.05).abs() < 0.02);
        assert_eq!(walking_jump_far(1.2), None);
        assert_eq!(walking_press_lead(0.9, 0.5, 4.0), Some(JUMP_PRESS_LEAD_M));
        let lead = walking_press_lead(0.9, 0.5, 1.0).unwrap();
        assert!(lead > JUMP_PRESS_LEAD_M && (lead - 1.37).abs() < 0.02, "{lead}");
        assert_eq!(walking_press_lead(0.9, 0.5, 0.5), None, "a top 0.75 m deep is past what any press holds");
        // The nearer the ledge's height to the apex, the less room to press early.
        assert!(walking_press_lead(0.99, 0.5, 1.0).is_none() || walking_press_lead(0.99, 0.5, 1.0) > walking_press_lead(0.9, 0.5, 1.0));
    }

    /// … but a jump that is the only way onto the ledge is kept: the cut disconnects nothing.
    #[test]
    fn a_carried_off_jump_that_is_the_only_way_up_is_kept() {
        let top = |grid: &WalkGrid| {
            let a = grid.locate(Vec3::new(2.0, 0.0, 5.0), 0.5).unwrap();
            grid.locate(Vec3::new(10.4, 0.9, 5.0), 0.3).is_some_and(|b| grid.distances_from(&[a]).reaches(b))
        };
        let (plain, stats) = ledge_island(0.75, 0.5, false, false);
        assert!(top(&plain), "up the ledge without the carry: {stats:?}");
        let (grid, stats) = ledge_island(0.75, 0.5, false, true);
        assert!(top(&grid) && stats.overshot_kept > 0, "{stats:?}");
    }

    /// With the last resorts not kept, the jump that is the only way onto a ledge too short for it is taken away like the others, and the
    /// ledge is out of reach.
    #[test]
    fn a_last_resort_is_cut_when_it_is_not_kept() {
        let top = |grid: &WalkGrid| {
            let a = grid.locate(Vec3::new(2.0, 0.0, 5.0), 0.5).unwrap();
            grid.locate(Vec3::new(10.4, 0.9, 5.0), 0.3).is_some_and(|b| grid.distances_from(&[a]).reaches(b))
        };
        let (kept, stats) = ledge_island_with(0.75, 0.5, false, Body { landing_carry: true, ..Body::default() });
        assert!(top(&kept) && stats.overshot_kept > 0, "{stats:?}");
        let (cut, stats) = ledge_island_with(0.75, 0.5, false, Body { landing_carry: true, keep_last_resorts: false, ..Body::default() });
        assert!(!top(&cut) && stats.overshot_kept == 0 && stats.overshot_cut > 0, "{stats:?}");
    }

    /// A beam over a ledge's top, its underside 1.3 m over it (a crouched body goes under, a standing one does not), makes the floors
    /// under and by it crouch-only (the exact erosion keeps them): no jump lands on or starts from one, and no landing run goes on
    /// over one.
    #[test]
    fn no_jump_starts_or_lands_under_a_low_beam() {
        let mut tris: Vec<Triangle> = floor(0.0, 0.0, 10.0, 10.0, 0.0).to_vec();
        tris.extend(floor(10.0, 0.0, 16.0, 10.0, 0.9));
        tris.extend(wall_x(10.0, 0.0, 10.0, 0.9));
        // The beam: a box x 10.4..11.2, z 0..10, from 2.2 to 2.7 (1.3 m over the ledge's top), vertical faces.
        for x in [10.4f32, 11.2] {
            tris.extend(wall_x(x, 0.0, 10.0, 2.7).into_iter().map(|mut t| {
                for v in &mut t.v {
                    if v.y == 0.0 {
                        v.y = 2.2;
                    }
                }
                t
            }));
        }
        let body = Body { erosion: Erosion::Exact, ..Body::default() };
        let grid = WalkGrid::build(&tris, [0.0, 0.0, 20.0, 10.0], 0.25, body);
        let low = (0..grid.len() as NodeId).filter(|&n| !grid.can_stand(n)).count();
        assert!(low > 0, "floors under the beam are crouch-only");
        for a in 0..grid.len() as NodeId {
            for (b, kind) in grid.links(a) {
                assert!(
                    kind != LinkKind::Jump || (grid.can_stand(a) && grid.can_stand(b)),
                    "a jump {:?} -> {:?} at a low ceiling",
                    grid.position(a),
                    grid.position(b)
                );
            }
        }
    }

    /// Ground steeper than 50° is not walked up past a step (the
    /// client's `impassable_slope`; level_05's rubble, where bodies stood
    /// caught at the foot); 45° is. Its floors stay, for coming down.
    #[test]
    fn ground_steeper_than_fifty_degrees_is_not_walked_up() {
        let ramp = |degrees: f32| {
            let rise = 3.0 * degrees.to_radians().tan();
            let mut tris = floor(0.0, 0.0, 2.0, 10.0, 0.0).to_vec();
            tris.extend(floor(5.0, 0.0, 10.0, 10.0, rise));
            let (a, b) = (Vec3::new(2.0, 0.0, 0.0), Vec3::new(2.0, 0.0, 10.0));
            let (c, d) = (Vec3::new(5.0, rise, 10.0), Vec3::new(5.0, rise, 0.0));
            for v in [[a, b, c], [a, c, d]] {
                tris.push(Triangle {
                    v,
                    walker: WalkerBehaviour::BySlope,
                });
            }
            let grid = WalkGrid::build(&tris, AREA, 0.25, Body::default());
            let foot = grid.locate(Vec3::new(1.0, 0.0, 5.0), 0.3).unwrap();
            let top = grid.locate(Vec3::new(7.5, rise, 5.0), 0.3).unwrap();
            let up = grid.distances_from(&[foot]).reaches(top);
            assert!(
                grid.distances_from(&[top]).reaches(foot),
                "down at {degrees}°"
            );
            up
        };
        assert!(ramp(45.0));
        assert!(!ramp(55.0));
        // A curb's steep face, lower than a step, is stepped up.
        let mut tris = floor(0.0, 0.0, 3.0, 10.0, 0.0).to_vec();
        tris.extend(floor(3.5, 0.0, 10.0, 10.0, 0.45));
        let (a, b) = (Vec3::new(3.0, 0.0, 0.0), Vec3::new(3.0, 0.0, 10.0));
        let (c, d) = (Vec3::new(3.5, 0.45, 10.0), Vec3::new(3.5, 0.45, 0.0));
        for v in [[a, b, c], [a, c, d]] {
            tris.push(Triangle {
                v,
                walker: WalkerBehaviour::BySlope,
            });
        }
        let grid = WalkGrid::build(&tris, AREA, 0.25, Body::default());
        let foot = grid.locate(Vec3::new(1.0, 0.0, 5.0), 0.3).unwrap();
        let top = grid.locate(Vec3::new(7.0, 0.45, 5.0), 0.3).unwrap();
        assert!(grid.distances_from(&[foot]).reaches(top));
    }
