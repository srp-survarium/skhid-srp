/// The body and how it moves. Defaults: the 0.26g client's character
/// (`gameplay/players/default.player`; step 0xa7ab08), except the jump.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Body {
    /// `s_step_height`: the highest step taken by walking. PROVEN 0.6 m.
    pub step: f32,
    /// `stand_capsule_height`. PROVEN 1.8 m.
    pub stand_height: f32,
    /// The crouched capsule's height: the lowest gap the body passes.
    /// PROVEN 1.1 m.
    pub crouch_height: f32,
    /// Half of `stand_capsule_width` (0.76 m). PROVEN.
    pub radius: f32,
    /// The cosine of the steepest ground walked up: 50° (PROVEN: the
    /// character controller's `impassable_slope` 0x7de10 refuses ground
    /// whose normal's y is under the cosine of 0.8727 rad, set at
    /// 0x84d780; a body standing still slides from 40°, 0x7bc20). Faces up
    /// to 60° are still floors; a climb up such ground is cut past a step
    /// ([`WalkGrid::cut_steep_climbs`]). Was 60° (LIKELY) for both.
    pub min_ground_normal_y: f32,
    /// The highest drop taken (`fall_params.harmless_height`, 5 m).
    pub max_drop: f32,
    /// The highest ledge reached by a standing jump; a Jump link above it is a sprint jump (a run-up with sprint held,
    /// [`SPRINT_JUMP_LOW_M`]). The exe's body has 1.05 m (LIKELY: the client's jump follows its animation; in the live
    /// logs of 2026-10-17..23 bots stuck at the foot of ledges 1.15-1.3 m high 4-8 times as often as at those 0.8-1.0 m,
    /// `player_bots_stuck.md`; was 1.3). The maps' grids set it from `GridTuning::jump_cap_m` (the clip's root tops at
    /// [`STANDING_JUMP_M`], PROVEN; whether the body reaches a ledge above it is what the client test G-V4 settles).
    pub max_jump: f32,
    /// How fast a body walks off a ledge, m/s, for the Drop links: 0 (the default) is the cell model (a Drop is the
    /// step down to the floor of the next cell, [`Self::max_drop`] deep); over 0 a Drop is kept only if the body that
    /// walks off at this speed, carried on through the air (fall time sqrt(2 h / g)), comes down on a floor within
    /// `max_drop` of the edge ([`WalkGrid::drop_deep_flights`]): a ledge below which the ground falls away in steps is
    /// one fall, not several harmless drops (Chemical Plant, the team 1 spawn deck: 1.43 m then 4.66 m, 7.5 m in all).
    /// A build input only: not in the digest or the file, in the key when set.
    pub drop_flight_mps: f32,
    /// How the floors near walls are eroded ([`Erosion`]). Not in the grid file: a grid read back has the cells'.
    pub erosion: Erosion,
    /// Whether the take-off floor of a walk-off gap drop (a drop of a lip's height or more, walked off with no key) is a lip
    /// ([`WalkGrid::is_lip`]), as a Drop link's is: the guards of the walk read the lip bits. A build input: in the key when
    /// set; a grid read back is given it ([`WalkGrid::read`]).
    pub walk_off_lips: bool,
    /// Whether a Jump link is kept only where the top it lands on goes on as far as the jump's clip carries the body past the
    /// ledge's face ([`WalkGrid::drop_overshot_landings`], [`walking_press_lead`], [`SPRINT_TOP_M`]): the clip's root runs
    /// to its end whatever it has landed on, so a body on a top shorter than that walks off its far side and comes down below
    /// (a wall's top, a rail, a plank); a walking jump is pressed earlier for a short top ([`WalkGrid::press_lead`]). Off: the landing needs the body's width only ([`WalkGrid::lands`]). A build input: in
    /// the key when set; a grid read back is given it ([`WalkGrid::read`]).
    pub landing_carry: bool,
    /// With [`Body::landing_carry`]: whether a Jump link no press keeps the body on the top of is kept where it is the only way to a
    /// floor or back from it. Off: every such link is taken away but those that are the only way back out of a floor a body can walk
    /// to (a pit), and the floors only they led to are out of reach (A170: the live
    /// players stood on those floors in 0-7 lives of 1,000-3,000 a map, and never within 2 m of the 4 objectives they alone led to; on
    /// the bench the bots pressed them, 3 of 81 up). A build input: in the key when off.
    pub keep_last_resorts: bool,
    /// With [`Erosion::Exact`]: whether a floor only a crouched capsule fits by the walls is kept as a crouch-only floor
    /// ([`WalkGrid::can_stand`] false). Off: it is taken away as the standing capsule's meeting a wall always did. A build input:
    /// in the key when off.
    pub crouch_only_floors: bool,
    /// Whether a rise up a ledge's edge within [`Body::edge_step`] is walked (a Walk link up; down it stays a Drop), not jumped.
    /// The client's `step_up` (0x7C900) lifts the capsule from below by the step and moves it on; `step_down` (0x7E1B0) sweeps
    /// it down and keeps it where `impassable_slope` passes the contact's normal. A capsule's round bottom resting on an edge
    /// over the step meets it at a normal within the slope up to [`Body::edge_step`] over the feet (LIKELY: the re-kit's
    /// notes of those functions, not run in the client): Vostok Radar Station's 0.86-0.90 m edge at (8.41, -16.51), walked up
    /// with no jump by the live players (A198). Off: a rise over [`Body::step`] is a jump. A build input: in the key when set.
    pub capsule_steps: bool,
    /// Whether a walk-off (a Drop link, a walk-off GapDrop) is kept only where the capsule walking off the edge has room: no wall
    /// ([`Erosion::Exact`]'s walls) on the move's side of the take-off, between a step and the crouched height over the take-off,
    /// within [`WalkGrid::walk_off_clearance`] of the way from the take-off's centre to the landing or [`WALK_OFF_REACH_M`] on
    /// ([`WalkGrid::cut_blocked_walk_offs`]). A link checks only the landing's ceiling over the take-off; a rail or a parapet at the
    /// edge (a face, not a floor) leaves a Drop link the client's capsule cannot walk (A206). A build input: in the key when set.
    pub drop_room: bool,
    /// [A238] Whether the floor a body comes down on when it slips off a walk-off gap drop's take-off slower than any walk-off is
    /// flown for (`gap::WALK_OFF_SPEEDS`) is reached: the highest floor under the edge open above the take-off
    /// ([`WalkGrid::slip_landing`], [`WalkGrid::open_to`]), where the
    /// link's flight lands cells out. The reach and the pockets are flooded along it too (`Wide::slips`); it is no link, so no
    /// route plans a slip and the pieces and searches are as before. A floor only a slip gets to is then reached, and a pocket
    /// when no walk returns: Vector Laboratory's 16.22 ledge under the 20.6 lip, where two bots that slipped in a fight stood
    /// unseen by the pocket marks, the escape and the bench's pocket counts (`fx-smoke-pockets.md` §1). A build input: in the
    /// key when set.
    pub slip_landings: bool,
    /// Whether the sprint jumps' run-ups ([`SPRINT_RUN_UP_M`] straight behind the take-off, `WalkGrid::drop_short_run_ups`) are
    /// asked after the erosion, of the take-offs and floors it leaves, in metres (a floor along a diagonal is a cell's diagonal
    /// on), not before it in cells with the radius the erosion takes. The erosion makes Jump links of its own (a
    /// jump past a floor that went starts a cell back; a jump whose landing went lands further on) and takes floors off a run-up's
    /// line: checked before it, 366 of the offered maps' 3,716 sprint-band jumps over 1.05 m are left with less than 1.5 m straight
    /// behind them, 290 of them jumps the erosion made (A236). A build input: in the key when set.
    pub run_ups_after_erosion: bool,
    /// Whether a walk up off a perched steep floor (steeper than [`Body::min_ground_normal_y`] by its neighbours, not a `walk` face, its
    /// cell's centre over ground more than 0.3 m lower: the top of something in a corner of the cell) is measured from where the body
    /// stands, whatever the floor it reaches: the walkable ground its climb began on, or the ground under the floor if that is higher,
    /// and a drop's or jump's landing on it gives it no base of its own ([`WalkGrid::cut_steep_climbs`]). The client's body does not
    /// rest on such ground: it slides back to where it stood. Floors that are not perched are as without it (measured from no base at
    /// all, a perched floor come to by a walk down or a landing, and a landing on a steep slope with no base, left pits: a floor
    /// reached with every walk out cut, School 12 floors and Mamayev Kurgan day 4 23; A248).
    /// Off: only a walk onto steep ground is so measured, and a landing is a base, so a steep floor a drop lands on walks onto a
    /// top a step over it however far over the ground it stands on that is: Mamayev Kurgan day 4's boulder floor (-2.90, 29.58,
    /// 105.38), 63 degrees by its neighbours, its base reset by a drop, walks 0.58-0.76 m onto the top; a live bot walked onto the
    /// boulder (29.33), held forward toward the top for 5 s with no jump and sank to 29.00, 0.9-1.2 m under the top, the height of the
    /// walkable floors the climb began on (29.03, 29.34; A237, PROVEN: its inputs). A build input: in the key when set.
    pub steep_walk_base: bool,
}

/// How the floors a body's radius from walls are taken away.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Erosion {
    /// By cells: a floor goes when a wall is in the cell beside it along a side, round after round
    /// ([`erosion_rounds`]); the walls diagonal to a cell and the far edge of the next cell are missed, up to
    /// the cell's width.
    #[default]
    Cells,
    /// The rounds, then every floor a wall comes nearer to than the radius less a quarter of a cell
    /// ([`WalkGrid::exact_clearance`]), measured exactly on the ground (the module `exact`): A84 item 13, a floor
    /// 0.25 m from a post in a 0.65 m opening.
    Exact,
}

