/// The links while the grid is built, a whole floor id a direction; packed
/// into `to` and `how` at the end (28 B a floor instead of 56).
struct Wide {
    links: Vec<[u32; 8]>,
    kinds: Vec<[LinkKind; 8]>,
    /// Floors at an unwalled side over a fall ([`WalkGrid::erode`]).
    fall: Vec<bool>,
    /// The off-mesh links ([`gap`]), by take-off then landing.
    off: Vec<OffLink>,
    /// [`Body::slip_landings`]: each walk-off take-off and the floor a slip off it comes down on, by take-off; floods of the
    /// reach only, not links ([`Wide::out`] leaves them out).
    slips: Vec<(u32, u32)>,
}

impl Wide {
    /// The floors a slip off floor `a` comes down on ([`Body::slip_landings`]).
    fn slips_from(&self, a: u32) -> impl Iterator<Item = u32> + '_ {
        let first = self.slips.partition_point(|&(f, _)| f < a);
        self.slips[first..].iter().take_while(move |&&(f, _)| f == a).map(|&(_, s)| s)
    }

    /// The links out of floor `a`: its neighbours' and its off-mesh ones.
    fn out(&self, a: usize) -> impl Iterator<Item = u32> + '_ {
        let first = self.off.partition_point(|l| (l.from as usize) < a);
        let last = self.off.partition_point(|l| (l.from as usize) <= a);
        self.links[a]
            .iter()
            .copied()
            .filter(|&b| b != NONE)
            .chain(self.off[first..last].iter().map(|l| l.to))
    }

    /// Every link as (from, to), compressed by take-off: `first` (one
    /// more entry than floors) and the landings, for floods.
    fn adjacency(&self) -> (Vec<u32>, Vec<u32>) {
        let n = self.links.len();
        let mut first = Vec::with_capacity(n + 1);
        let mut to = Vec::new();
        for a in 0..n {
            first.push(to.len() as u32);
            to.extend(self.out(a));
        }
        first.push(to.len() as u32);
        (first, to)
    }
}

