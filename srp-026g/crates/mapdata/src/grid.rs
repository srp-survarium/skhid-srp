/// How one floor reaches the next.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum LinkKind {
    Walk = 0,
    /// Down a ledge; one way.
    Drop = 1,
    /// Up a ledge higher than a step; one way.
    Jump = 2,
    /// A short jump across a gap to a floor at most a step lower or
    /// higher, two or more cells on; one way, off-mesh ([`gap`]).
    GapJump = 3,
    /// A short jump across a gap down to a floor more than a step lower;
    /// one way, off-mesh ([`gap`]).
    GapDrop = 4,
}

impl LinkKind {
    /// From its two bits in [`WalkGrid`]'s packed links.
    fn from_bits(bits: u32) -> Self {
        match bits & 3 {
            0 => Self::Walk,
            1 => Self::Drop,
            _ => Self::Jump,
        }
    }

    /// From its number (`kind as u8`).
    pub fn from_u8(value: u8) -> Option<Self> {
        Some(match value {
            0 => Self::Walk,
            1 => Self::Drop,
            2 => Self::Jump,
            3 => Self::GapJump,
            4 => Self::GapDrop,
            _ => return None,
        })
    }

    /// Extra path cost, in metres, so paths prefer walking (tuning, not
    /// game data). A gap link pays the jump's or the drop's and its own
    /// per metre ([`gap::GAP_PENALTY_PER_M`], in [`WalkGrid::link_cost`]).
    pub fn penalty(self) -> f32 {
        match self {
            Self::Walk => 0.0,
            Self::Drop | Self::GapDrop => 0.5,
            Self::Jump | Self::GapJump => 1.5,
        }
    }

    /// Whether the body jumps to take it (a jump link or a gap link).
    pub fn is_leap(self) -> bool {
        matches!(self, Self::Jump | Self::GapJump | Self::GapDrop)
    }

    /// Whether it is an off-mesh link ([`OffLink`]), not a neighbour's.
    pub fn is_off_mesh(self) -> bool {
        matches!(self, Self::GapJump | Self::GapDrop)
    }
}

