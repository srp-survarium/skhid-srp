impl Body {
    /// The numbers the 0.26g clients run: `startup.cfg` of the game's `resources.db` sets `cc_step_height 0.80`
    /// (the exe's default is the 0.6 of [`Body::default`]) and `cc_max_slope_angle_cos 0.57358`, 55° (the exe's
    /// default 50° is read by `impassable_slope` 0x7de10; the cvar replaces it). PROVEN on the owner's barrel pile
    /// (Chemical Plant): its +z plane at 53.1° is walked, its -z plane at 58.0° is not. Another key: its grids are
    /// built apart from the default body's.
    pub fn client() -> Self {
        Self {
            step: 0.8,
            min_ground_normal_y: 0.573_58,
            ..Self::default()
        }
    }

    /// The highest rise a Jump link is made for: [`Self::max_jump`], and with the clients' numbers the sprint
    /// jump's [`SPRINT_JUMP_LOW_M`] (a link above `max_jump` is a sprint jump: a run-up with sprint held, not for a
    /// body that cannot sprint, `with_max_jump_rise`).
    pub fn jump_cap(&self) -> f32 {
        if self.client_slope() { SPRINT_JUMP_LOW_M.max(self.max_jump) } else { self.max_jump }
    }

    /// The highest edge the capsule steps up onto ([`Self::capsule_steps`]): the step, and the part of the radius over which its
    /// round bottom meets an edge at a normal within the slope, `radius * (1 - min_ground_normal_y)`. With the clients'
    /// numbers 0.80 + 0.38 * (1 - 0.574) = 0.96 m.
    pub fn edge_step(&self) -> f32 {
        self.step + self.radius * (1.0 - self.min_ground_normal_y)
    }

    /// The highest rise a Walk link up climbs: the step, or with [`Self::capsule_steps`] the [`Self::edge_step`].
    pub fn walk_climb(&self) -> f32 {
        if self.capsule_steps { self.edge_step() } else { self.step }
    }

    /// Whether the body walks ground as steep as the clients do (55°, not the exe's 50°): a jump then does not land
    /// on steep ground, which the client slides off ([`WalkGrid::cut_steep_climbs`]).
    pub(crate) fn client_slope(&self) -> bool {
        self.min_ground_normal_y < Self::default().min_ground_normal_y
    }
}

