//! A piece of Rudnya's ground as the game has it: 6 x 6 m of the terrain
//! of both Rudnyas (native level_01's `terrain.model` and the v0.69 port's
//! `terrain_game_center_3.model` are the same here), around (16.5, 21.19,
//! -47.0), west of the decent house, moved so that the walker collision is
//! at y = 0 under the origin. Three meshes, each the triangles that touch
//! the square:
//!
//! - `WALKER`: the model's `walker_collision` (cgroup 2, cmask 4), what the
//!   players' feet stand on;
//! - `HITTABLE`: its `collision` (cgroup 8, cmask 16), what bullets hit;
//! - `DRAWN`: the drawn ground, the top of its render surfaces (`sand_grass_s`
//!   and its blend overlay `grass_vc`).
//!
//! Rudnya's walker mesh is coarse and lies under the drawn ground (here 4 to
//! 10 cm; over the play area a median 4 cm, 10 cm at the 90th percentile);
//! its collision follows the drawn ground within 2 cm. Patch 76's ray filter
//! (`LEVEL_GROUP` / `LEVEL_MASK` in the ragdoll patch) says which of the two
//! the ragdoll meets.

use super::*;
extern crate std;

pub(super) type Triangle = [[f32; 3]; 3];

/// The level as `ray_test` answers over triangle meshes: the nearest
/// triangle the ray crosses (either face, as Bullet's ray callback), the
/// normal toward the ray's start. A ray that starts under a mesh and goes
/// down does not meet it.
pub(crate) struct Floor {
    pub meshes: std::vec::Vec<&'static [Triangle]>,
}

fn vec(p: [f32; 3]) -> Vec3 {
    Vec3::new(p[0], p[1], p[2])
}

/// The ray's distance to the triangle and its normal toward the ray's start
/// (Möller-Trumbore, both faces).
fn ray_triangle(o: Vec3, d: Vec3, t: &Triangle) -> Option<(f32, Vec3)> {
    let (a, b, c) = (vec(t[0]), vec(t[1]), vec(t[2]));
    let (e1, e2) = (b - a, c - a);
    let p = d.cross(e2);
    let det = e1.dot(p);
    if det.abs() < 1e-9 {
        return None;
    }
    let s = o - a;
    let u = s.dot(p) / det;
    let q = s.cross(e1);
    let v = d.dot(q) / det;
    if u < 0.0 || v < 0.0 || u + v > 1.0 {
        return None;
    }
    let n = e1.cross(e2).direction()?;
    Some((e2.dot(q) / det, if n.dot(d) > 0.0 { -n } else { n }))
}

impl Floor {
    /// The height of `mesh` under (x, z), its top-most triangle.
    pub(crate) fn height(mesh: &[Triangle], x: f32, z: f32) -> Option<f32> {
        let o = Vec3::new(x, 100.0, z);
        mesh.iter()
            .filter_map(|t| ray_triangle(o, -Vec3::Y, t))
            .map(|(t, _)| 100.0 - t)
            .reduce(f32::max)
    }
}

impl Level for Floor {
    fn sweep(&mut self, from: Vec3, to: Vec3, radius: f32) -> Sweep {
        let along = to - from;
        let Some(d) = along.direction() else {
            return Sweep::Clear;
        };
        let length = along.length() + radius;
        let best = self
            .meshes
            .iter()
            .flat_map(|m| m.iter())
            .filter_map(|t| ray_triangle(from, d, t))
            .filter(|&(t, _)| (0.0..=length).contains(&t))
            .reduce(|a, b| if a.0 <= b.0 { a } else { b });
        match best {
            Some((t, normal)) => Sweep::Hit {
                point: from + d * t,
                normal,
            },
            None => Sweep::Clear,
        }
    }
}

