#!/usr/bin/env python3
"""London (v0.32)'s red team spawns at the owner's picks (2026-11-23: "multiple red london 0.32 spawns in tdm and
chargers which look not towards the ceonter of the map/doors, having people to adjust as they spawn, not good";
13 `where` places in the red team's building, facing as a spawning player should; "yep, let's use mine").

london-v032-red-picks.tsv is check-points' picks output for team 1 (the red team: the site's map page draws team
1 red) on the ten projects with team spawns, as every row of release/content.tsv above london-v032-red-spawns-1
leaves them (the picks binary's doc says how each pick is put on its ground):

  cd ../ffa-mode/check-points && cargo run --release --bin picks -- --db <resources.db> --patch ... \\
      --points <london-v032-red-2026-11-23.tsv> --team 1 --project v032a_level_09/day_2 ... \\
      --project v032a_level_09/evening_4 > ../../london-v032/london-v032-red-picks.tsv

(the points file: the `where` lines' n, x, y, z and yaw, in the order he typed them). Then

  python3 make_red_spawns.py --live <folder>

with the ten projects at their game paths as those rows leave them writes ../content-edit/london-v032-red-spawns-1.json:
each `moved` row's red point, by point id, full_name and team, takes the pick's position and rotation [0, ry, 0]
(its id, name, radii, priority and protection stay); each `added` row is a new red point after the project's last
entry, a copy of its red point with the lowest id at the row's place, named red_pick_<n>. Free for All's day_8 (a
copy of day_4 made by ffa-london-v032-1, a row above) is not named; Artifact Hunt's <weather>_ah projects are copies
of the <weather>_4 ones made by artefact-hunt-maps-1, a row below, and carry the points.
"""
import argparse
import csv
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'ffa-mode'))
import make_edits as base  # noqa: E402

PICKS = HERE / 'london-v032-red-picks.tsv'
OUT = HERE.parent / 'content-edit' / 'london-v032-red-spawns-1.json'
RED = 1
ABOUT = ("London (v0.32)'s red team spawns at the owner's picks (2026-11-23: \"multiple red london 0.32 spawns in tdm "
         "and chargers which look not towards the ceonter of the map/doors\"; his 13 `where` places, facing as a "
         "spawning player should; \"yep, let's use mine\"). Generated by scripts/london-v032/make_red_spawns.py from "
         "london-v032-red-picks.tsv (check-points picks --team 1): all 13, each on its ground, body clear, 2 m from "
         "harmful zones, facing as he faced (rotation [0, -yaw, 0]); the project's 10 red points take picks 1-10 "
         "(position and rotation only: ids, names, radii, priority and protection kept), picks 11-13 (12 and 13 on the "
         "lower floor) are new points after the last entry, copies of the project's first red point. In the ten "
         "team projects v032a_level_09/<weather>_<mode>, after ffa-london-v032-1 (Free for All's day_8, a copy of "
         "day_4, keeps the old ones) and before artefact-hunt-maps-1 (Artifact Hunt's copies of the _4 projects "
         "carry these); Blackout and Freeze Tag play the _2 and _4 projects themselves.")


def picks():
    """{project path: {verdict: {point id: (n, position, ry)}}} of the picks table."""
    out = {}
    with PICKS.open(newline='') as stream:
        for row in csv.DictReader(stream, delimiter='\t'):
            by = out.setdefault(f"projects/{row['project']}/client_project", {'moved': {}, 'added': {}})
            if row['verdict'] not in by:
                raise ValueError(f"{row['project']} {row['point']}: verdict {row['verdict']}, not moved or added")
            values = [float(row[k]) for k in ('x', 'y', 'z', 'ry')]
            if not all(math.isfinite(v) for v in values):
                raise ValueError(f"{row['project']} {row['point']}: not finite")
            n = int(re.match(r"the owner's pick (\d+) ", row['reason'])[1])
            by[row['verdict']][int(row['point'])] = (n, values[:3], values[3])
    return out


def edits(live):
    out = {'_about': ABOUT, 'set_entry': [], 'add_entry': []}
    for path, by in picks().items():
        entries = base.tree((live / path).read_bytes())['server_objects']['respawn_points']
        if [e['point_id'] for e in entries] != list(range(len(entries))):
            raise ValueError(f'{path}: point ids are not the entries\' indices')
        red = {e['point_id']: e for e in entries if e['team'] == RED}
        moved, added = by['moved'], by['added']
        if set(moved) != set(red):
            raise ValueError(f'{path}: the picks move {sorted(moved)}, the red points are {sorted(red)}')
        if sorted(added) != list(range(len(entries), len(entries) + len(added))):
            raise ValueError(f'{path}: new points are not numbered after the last entry')
        if sorted(n for n, *_ in [*moved.values(), *added.values()]) != list(range(1, len(moved) + len(added) + 1)):
            raise ValueError(f'{path}: not every pick, once')
        for i in sorted(moved):
            entry = red[i]
            _, position, ry = moved[i]
            out['set_entry'].append({'file': path, 'list': base.POINTS,
                'where': {k: entry[k] for k in ('point_id', 'full_name', 'team')},
                'from': {'position': [round(v, 6) for v in entry['position']],
                         'rotation': [round(v, 6) for v in entry['rotation']]},
                'to': {'position': position, 'rotation': [0., ry, 0.]}})
        model = red[min(red)]
        folder = model['full_name'].rsplit('/', 1)[0]
        for i in sorted(added):
            n, position, ry = added[i]
            name = f'red_pick_{n}'
            out['add_entry'].append({'files': path, 'list': base.POINTS, 'after': {'point_id': i - 1},
                'like': {'point_id': model['point_id']}, 'expected_files': 1, 'values': {
                    'name': name, 'full_name': f'{folder}/{name}', 'point_id': i,
                    'position': position, 'rotation': [0., ry, 0.]}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    base.write(edits(args.live), OUT)
    print(OUT)


if __name__ == '__main__':
    main()
