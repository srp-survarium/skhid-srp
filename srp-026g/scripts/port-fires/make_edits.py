#!/usr/bin/env python3
"""Writes content-edit/port-campfires-1.json: a ported map's campfires burn.

A port brought a bonfire's model and its flame, never its damage: London's two campfires burnt
nobody (the owner, 2026-11-15: "fireplaces which don't do damage"). A map of MAPS gets what Training
Camp got (training-camp-fires-1, make_training_fires.py): 0.26g's own fire of level_05, its damage
zone and the collision geometry it names, one sphere 0.16 m over each lit bonfire, Training Camp's
radius. A lit bonfire is a bonefire_0N_on model with its flame particle; barrels and stoves with a
flame do not burn in the stock maps either. The 0.21 Mamayev Kurgan (v021d_level_06) has the same
gap on seven bonfires and is not here: one stands 0.98 m from a spawn point (the one the stock map
leaves harmless too), so it needs a rule for that first.

    python3 make_edits.py --native <folder> --live <folder>

<native> holds the stock projects/level_05/day_4/client_project; <live> the maps' projects as the
manifest's rows above the list leave them (every project of MAPS' folders, each of its modes).
"""
import argparse
import json
import math
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'stalker-maps'))
import make_training_fires as training  # noqa: E402
from make_ffa_edits import tree  # noqa: E402

OUTPUT = HERE.parent / 'content-edit/port-campfires-1.json'
MAPS = {'London': 'level_09'}
BONFIRES = ('props/light/bonefire_01_on', 'props/light/bonefire_02_on')
FLAME, FLAME_REACH = 'fx/lights/bonfire', 0.5


def lit_bonfires(project, path):
    """The positions of a project's burning bonfires, which no fire of ours covers yet."""
    objects = project['client_objects']
    taken = [o['full_name'] for o in objects if o.get('full_name') in (training.ZONE, training.COLLISION)]
    if taken:
        raise ValueError(f'{path}: {taken[0]} is there already')
    flames = [o['position'] for o in objects if o.get('game_object_type') == 'particle' and o.get('lib_name') == FLAME]
    return [list(v['position']) for v in project['render_visuals']
            if v['lib_name'].endswith(BONFIRES) and any(math.dist(v['position'], f) < FLAME_REACH for f in flames)]


def build(native, live):
    zone, collision = training.stock(native)
    edits = {'_about': "A ported map's campfires burn: 0.26g's fire damage zone of level_05 "
             f'({training.ZONE}) and its collision geometry, a {training.RADIUS} m sphere '
             f"{training.ABOVE} m over each lit bonfire, as Training Camp's (training-camp-fires-1), in "
             'every project of ' + ' and '.join(f'{name} ({folder})' for name, folder in MAPS.items())
             + '. Generated by scripts/port-fires/make_edits.py.', 'append_entry': []}
    for name, folder in MAPS.items():
        paths = sorted(p.relative_to(live).as_posix() for p in live.glob(f'projects/{folder}/*/client_project'))
        projects = [tree((live / p).read_bytes()) for p in paths]
        fires = lit_bonfires(projects[0], paths[0])
        if not fires or any(lit_bonfires(project, p) != fires for project, p in zip(projects, paths)):
            raise ValueError(f"{name}: its projects' lit bonfires differ, or it has none")
        centre = [fires[0][0], fires[0][1] + training.ABOVE, fires[0][2]]
        spheres = [{**collision['meshes'][0], 'scale': [training.RADIUS] * 3,
                    'position': [f[i] + (training.ABOVE if i == 1 else 0) - centre[i] for i in range(3)]} for f in fires]
        counts = [len(project['client_objects']) for project in projects]
        for i, value in enumerate(({**collision, 'position': centre, 'meshes': spheres}, {**zone, 'position': centre})):
            edits['append_entry'].append({'files': paths, 'list': 'client_objects',
                                          'expected_counts': [n + i for n in counts], 'unique_key': 'full_name',
                                          'value': value, 'vectors': True})
        print(f'{name}: {len(fires)} campfires in {len(paths)} projects')
    return edits


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native', type=Path, required=True)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    OUTPUT.write_text(json.dumps(build(args.native, args.live), indent=2) + '\n')
    print(OUTPUT)
