#!/usr/bin/env python3
"""Training Camp's campfires burn: one fire damage zone over its four bonfires, in both its projects.

The zone is 0.26g's own over the same bonfire (props/light/bonefire_01_on): level_05's
logic/fire_damage/fire_damage_zone (fire, 0.1 to hips and feet every 500 ms) and its
collision_geometry, a sphere 0.16 m over each bonfire, copied from --native (the stock
projects/level_05/day_4/client_project). Only the sphere is larger: the stock's 0.5 m barely
passes the bonfire's walker sphere (0.38 m), which holds a body (0.38 m) 0.76 m from the fire's
middle; at RADIUS a body against or on the logs (0.5 m) burns, and one a step (0.6 m) from them
does not. The bonfires are those --pack's Team Deathmatch project draws (stalker-maps@6).
"""
import argparse
import json
from pathlib import Path

from make_ffa_edits import c, tree

HERE = Path(__file__).resolve().parent
PROJECTS = ['projects/v010b_cs_training_camp/day_4/client_project',
            'projects/v010b_cs_training_camp/day_8/client_project']
# client_objects of day_4 and day_8 when the list applies (after every earlier row of the manifest).
COUNTS = [44, 26]
STOCK = 'projects/level_05/day_4/client_project'
ZONE = 'logic/fire_damage/fire_damage_zone'
COLLISION = 'logic/fire_damage/fire_collision'
BONFIRE = 'props/light/bonefire_01_on'
ABOVE = 0.16
RADIUS = 0.8


def bonfires(pack):
    project = tree((pack / 'files' / PROJECTS[0]).read_bytes())
    return [list(v['position']) for v in project['render_visuals'] if v['lib_name'] == BONFIRE]


def typed(buf, off=0):
    """make_ffa_edits.tree with the config's booleans as booleans (an entry is written anew)."""
    kind = c.rec(buf, off)[3]
    if kind == c.T_NAMED:
        return {c.name_at(buf, c.rec(buf, k)[1]).decode(): typed(buf, k) for k in c.children(buf, off)}
    if kind == c.T_INDEXED:
        return [typed(buf, k) for k in c.children(buf, off)]
    return bool(c.value_of(buf, off)) if kind == c.T_BOOL else c.value_of(buf, off)


def stock(native):
    objects = typed((native / STOCK).read_bytes())['client_objects']
    zone, = (o for o in objects if o.get('full_name') == ZONE)
    collision, = (o for o in objects if o.get('full_name') == COLLISION)
    assert zone['damage_type'] == 'fire' and zone['collision_geometries'] == [{'name': COLLISION}]
    assert {m['type'] for m in collision['meshes']} == {0}, 'the stock fire is spheres'
    return json.loads(json.dumps(zone)), json.loads(json.dumps(collision))


def build(native, pack):
    zone, collision = stock(native)
    fires = bonfires(pack)
    assert len(fires) == 4, fires
    centre = [fires[0][0], fires[0][1] + ABOVE, fires[0][2]]
    collision['position'] = centre
    collision['meshes'] = [{**collision['meshes'][0], 'position': [f[i] + (ABOVE if i == 1 else 0) - centre[i] for i in range(3)],
                            'scale': [RADIUS] * 3} for f in fires]
    zone['position'] = centre
    edits = {'_about': f"Training Camp's {len(fires)} campfires burn, in Team Deathmatch's and Free for All's projects: "
             f"0.26g's fire damage zone of level_05 ({ZONE}, the same bonfire model's), its sphere {RADIUS} m "
             f'(the stock 0.5 m) {ABOVE} m over each bonfire. Generated by scripts/stalker-maps/make_training_fires.py.',
             'append_entry': []}
    for i, value in enumerate([collision, zone]):
        edits['append_entry'].append({'files': PROJECTS, 'list': 'client_objects',
            'expected_counts': [n + i for n in COUNTS], 'unique_key': 'full_name',
            'value': value, 'vectors': True})
    return edits


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--native', type=Path, required=True)
    ap.add_argument('--pack', type=Path, required=True)
    ap.add_argument('--out', type=Path, default=HERE.parent / 'content-edit/training-camp-fires-1.json')
    args = ap.parse_args()
    args.out.write_text(json.dumps(build(args.native, args.pack), indent=2) + '\n')
    print(args.out)
