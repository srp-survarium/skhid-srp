#!/usr/bin/env python3
"""Repair Depot's Free for All arena as a source edit: a walker wall round the depot and the field
just south of it, in Free for All's own copy of the project (day_8; day_4 is never edited).

--native is the stock level/04/level_border.model extracted with srp-game-data.
rembasa-arena.tsv, the arena's outline, is shared with the spawn planner, the spawn rule (to_cover
--fence) and the HUD minimap's frame. On three sides it runs a metre or two outside the depot's own
walls, which already stop a walker; on the south it crosses the open field, which runs on for some
120 m. The wall stands just outside the line (make_training_arena.behind), walkers only: bullets
and sight pass. Models are copied by build-content, never assembled into a patch by this script.
"""
import argparse
import csv
import json
from pathlib import Path

from make_training_arena import behind, border_wall

HERE = Path(__file__).resolve().parent
PROJECT = 'projects/v010b_cs_mp_rembasa/day_8/client_project'
MODEL = 'models/srp/rembasa_border.model'
LEVEL = 'resources/models/ported/v010b/ported/cs/rembasa/rembasa_%03d.model/collision'
# The last collision object of the project as the pack makes it: an ammo crate's container (its
# collision objects repeat the library at their crates' places, so it is named with its position).
LAST = {'lib_name': 'resources/models/item/quest/container_closed.model/collision',
        'position': [3.38, 0.31, -19.59]}


def outline():
    """The arena's vertices, counter-clockwise seen from above (+x right, +z up)."""
    with (HERE / 'rembasa-arena.tsv').open() as f:
        points = [(float(r['x']), float(r['z'])) for r in csv.DictReader(f, delimiter='\t')]
    area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(points, points[1:] + points[:1])) / 2
    if area <= 0:
        raise ValueError('rembasa-arena.tsv: the vertices go counter-clockwise')
    return points


def build(native):
    walls = border_wall(native, MODEL, behind(outline()), '|rembasa_arena|walker_col|side_')
    edits = {'_about': "Repair Depot's Free for All arena (the owner, 2026-11-14: Repair Depot in Free for All, "
             '"not too big"): a walker wall round the depot and the field just south of it (rembasa-arena.tsv), in '
             "Free for All's own copy of the project; the far field is scenery. Walkers only: bullets and sight "
             'pass. Team Deathmatch\'s project is unchanged. Generated by scripts/stalker-maps/make_rembasa_arena.py.',
             'copy': walls['copy'], 'append_entry': walls['append_entry'], 'remove_entry': walls['remove_entry']}
    # A walker-only object (cmask 4, cgroup 2), a copy of the level's first collision chunk's record.
    edits['add_entry'] = [{'files': PROJECT, 'list': 'collision_objects', 'after': LAST,
        'like': {'lib_name': LEVEL % 0},
        'values': {'rotation': [0.0, 0.0, 0.0], 'position': [0.0, 0.0, 0.0],
                   'cmask': 4, 'cgroup': 2, 'scale': [1.0, 1.0, 1.0],
                   'lib_name': f'resources/{MODEL}/walker_collision'}}]
    return edits


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--native', type=Path, required=True)
    ap.add_argument('--out', type=Path, default=HERE.parent / 'content-edit/rembasa-arena-1.json')
    args = ap.parse_args()
    args.out.write_text(json.dumps(build(args.native), indent=2) + '\n')
    print(args.out)
