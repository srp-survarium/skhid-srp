#!/usr/bin/env python3
"""Author the late Research/battery edit from pinned base maps and research-mode@3.

The late edit copies the fully composed v0.11 day_4 project. The early config
edit copies native Vostok Research before modes.tsv and music apply.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path

import make_pack as anomalies

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('research_builder', HERE.parent / 'research-mode/make_pack.py')
research = importlib.util.module_from_spec(spec)
spec.loader.exec_module(research)
bcw = anomalies.bcw
MAP_ID = 249
PROJECT = 'projects/v011e_level_03/day_5/client_project'
CONFIG = 'gameplay/game_modes/v011e_level_03_day_5.options'
BATTERY = 'projects/v011e_level_03/day_2/client_project'


def checked(folder, path, sums, prefix):
    data = (folder / path).read_bytes()
    if hashlib.sha256(data).hexdigest() != sums[prefix + path]:
        raise ValueError(f'{prefix}{path}: not the pinned source')
    return bcw.loads(data)


def build(base, research_pack):
    sums = dict((path, sha) for sha, path in
                (line.split() for line in (HERE / 'modes-inputs.sha256').read_text().splitlines()))
    native4 = checked(base, 'projects/level_03/day_4/client_project', sums, 'base/')
    native2 = checked(base, 'projects/level_03/day_2/client_project', sums, 'base/')
    old4 = checked(base, 'projects/v011e_level_03/day_4/client_project', sums, 'base/')
    old2 = checked(base, BATTERY, sums, 'base/')
    donor = checked(research_pack / 'files', 'projects/level_03/day_5/client_project', sums, 'research/')
    edits = {
        '_about': 'Vostok v0.11: selectable Research (map 249) with native Vostok Research stations; '
                  'Protective Device and Blackout use 45 checked stock 0.26g battery locations, instead of 21. '
                  'Five incompatible positions are excluded (battery-exclusions.tsv); point IDs are contiguous. '
                  'Generated by scripts/v011e-vostok-anomalies/make_modes_edit.py. Apply last: copy the '
                  'fully edited day_4, retaining anomalies, Keeper, spawns, lamps, vegetation and release fixes. '
                  'The companion config edit and modes.tsv supply native Research rules and capture volumes. Station props append after '
                  'existing visuals, preserving every breakable-lamp index. No existing map geometry is removed.',
        'copy': [
            {'files': 'projects/v011e_level_03/day_4/client_project',
             'from': 'projects/v011e_level_03/day_4/', 'to': 'projects/v011e_level_03/day_5/'},
        ],
        'add_entry': [], 'append_entry': [], 'remove_entry': [],
    }
    # Only the station layout's additions, already converted to native 0.26g
    # by research-mode@3. Keep the early map's geometry and objects intact.
    for section, key, count in (('render_visuals', research.entry_key, 55),
                                ('collision_objects', research.entry_key, 88)):
        before = {key(entry) for entry in native4[section]}
        additions = [entry for entry in donor[section] if key(entry) not in before]
        assert len(additions) == count
        target_keys = {key(entry) for entry in old4[section]}
        assert not any(key(entry) in target_keys for entry in additions)
        def selector(entry):
            return {key: value for key, value in entry.items() if key != 'sectors'}
        after = selector(old4[section][-1])
        for entry in additions:
            # A template with exactly these keys avoids inheriting old sector
            # visibility bindings. All source values, including vectors, replace it.
            like = next(item for item in old4[section] if item.keys() == entry.keys())
            edits['add_entry'].append({'files': PROJECT, 'list': section,
                                       'after': after, 'like': selector(like), 'values': entry})
            after = selector(entry)
    original_names = {entry['full_name'] for entry in native4['client_objects']}
    additions = [entry for entry in donor['client_objects'] if entry['full_name'] not in original_names]
    assert len(additions) == 12
    assert all(entry['full_name'].startswith('mode_cp_props/') for entry in additions)
    # Existing base, the 70 restored anomaly objects and the Keeper pool.
    count = len(old4['client_objects']) + 70 + 1
    for i, entry in enumerate(additions):
        edits['append_entry'].append({'file': PROJECT, 'list': 'client_objects',
                                      'expected_count': count + i, 'unique_key': 'full_name',
                                      'vectors': True, 'value': entry})
    path = 'server_objects/victory_item_spawners'
    previous = old2['server_objects']['victory_item_spawners']
    replacement = native2['server_objects']['victory_item_spawners']
    assert len(previous) == 21 and len(replacement) == 50
    excluded = {line.split('\t')[0] for line in (HERE / 'battery-exclusions.tsv').read_text().splitlines()[1:]}
    assert len(excluded) == 5 and excluded <= {entry['full_name'] for entry in replacement}
    replacement = [copy.deepcopy(entry) for entry in replacement if entry['full_name'] not in excluded]
    for i, entry in enumerate(replacement):
        entry['point_id'] = i
    assert not ({o['full_name'] for o in previous} & {o['full_name'] for o in replacement})
    for i, entry in enumerate(replacement):
        edits['append_entry'].append({'file': BATTERY, 'list': path,
                                      'expected_count': len(previous) + i, 'unique_key': 'full_name',
                                      'vectors': True, 'value': entry})
    edits['remove_entry'] = [{'file': BATTERY, 'list': path, 'where': {'full_name': e['full_name']}}
                             for e in previous]
    edits['append_entry'].append({'file': 'gameplay/db_static_dictionaries', 'list': 'maps_dict',
                                  # Includes the six stalker-maps@6 and four stalker-maps-2@1 TDM registrations.
                                  'expected_count': 164, 'unique_key': 'id',
                                  'value': {'cfg_mode_name': 'v011e_level_03_day_5.options', 'id': MAP_ID}})
    return edits


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', type=Path, required=True)
    parser.add_argument('--research-pack', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.write_text(json.dumps(build(args.base, args.research_pack), indent=2) + '\n')


if __name__ == '__main__':
    main()
