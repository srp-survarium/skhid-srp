#!/usr/bin/env python3
"""Rebind existing fixtures to restored donor lights. RESTORE_OUTPUT OUTPUT_JSON."""
import json
from pathlib import Path
import sys

from make_edits import rebound_lights


def main():
    source, output = map(Path, sys.argv[1:])
    objects = {}
    for entry in json.loads((source / 'v021d-two-maps-original-lights-1.json').read_text())['append_entry']:
        for path in entry.get('files', [entry.get('file')]):
            objects.setdefault(path, []).append(entry['value'])
    edits = {'_about': 'Rebind existing breakable fixtures to restored original 0.21 lights using the shared fixture association rule. Lamp geometry, break state and authored light values are unchanged. Generated by scripts/breakable-lamps/rebind_021.py.', 'set': []}
    for entry in json.loads((source / 'lamps.json').read_text()):
        path, lamps = entry['file'], entry['lamps']
        bindings = rebound_lights(path, lamps, objects[path])
        changed = 0
        for name, lights in bindings.items():
            if lights == lamps[name]['lights']:
                continue
            old = lamps[name]['lights']
            if old.keys() != lights.keys() or any(old[key]['name'] != light['name'] for key, light in lights.items()):
                raise ValueError(f'{path}: {name} changes light identities; inspect the fixture layout')
            for key, light in lights.items():
                for axis in ('x', 'y', 'z'):
                    if light[axis] != old[key][axis]:
                        edits['set'].append({'file': path, 'path': f'srp_lamps/lamps/{name}/lights/{key}/{axis}',
                                             'from': old[key][axis], 'to': light[axis]})
            changed += 1
        print(path, changed, 'fixture bindings updated')
    output.write_text(json.dumps(edits, indent=2) + '\n')


if __name__ == '__main__':
    main()
