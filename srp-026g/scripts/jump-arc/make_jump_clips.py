"""make_jump_clips.py <anim dir> <out jump_clips.rs>: the B-spline channels of the forward jump clips' root (bone 0) for
`mapdata::controller::jump` (A364 C2 rows 11/12): `on_site`, `on_site_fwd` (the short jump) and `sprint/sprint_from_left_leg`,
`sprint/sprint_from_right_leg` (the sprint jump), each channel's (knot, value) keys as the clip file stores them (the exe's
loader's layout, `clip_table.py`'s `tracks`), as f32 bits. The Rust side evaluates them as `clip_table.py`'s `curve` does
(clamped cubic B-splines). Reads only the clip files; writes the module with LF line ends.

The inputs are the stock `resources.db`'s rifle jump clips, `animations/single/weapons/ak/player/stand/3rd_view/jump/`, taken
out flattened as `animations__single__...__jump__<name>.b-spline` (see README.md)."""
import os
import struct
import sys

CLIPS = [
    ('ON_SITE', 'on_site'),
    ('ON_SITE_FWD', 'on_site_fwd'),
    ('SPRINT_FROM_LEFT_LEG', 'sprint__sprint_from_left_leg'),
    ('SPRINT_FROM_RIGHT_LEG', 'sprint__sprint_from_right_leg'),
]
# The root's channels 0..2 are x (side), y (rise), z (ahead): `clip_table.py` reads X, Y, Z from tracks 0, 1, 2.
CHANNELS = [('side', 0), ('rise', 1), ('ahead', 2)]


def tracks(path):
    b = open(path, 'rb').read()
    bones, events, _kind = struct.unpack_from('<HBB', b, 0)
    off = 4 + bones * 0x48 + events * 0x10
    out = []
    for _ in range(3):
        n = struct.unpack_from('<I', b, off)[0]
        raw = struct.unpack_from('<%dI' % (2 * n), b, off + 4)
        out.append(list(zip(raw[0::2], raw[1::2])))
        off += 4 + 8 * n
    return out


def main():
    d, out = sys.argv[1], sys.argv[2]
    lines = [
        '//! The forward jump clips\' root channels (bone 0), as the stock clip files store them: generated by',
        '//! `scripts/jump-arc/make_jump_clips.py` from the stock `resources.db`\'s',
        '//! `animations/single/weapons/ak/player/stand/3rd_view/jump/` clips. Each channel is its (knot, value) keys, f32 bits;',
        '//! a value under -1e8 is a knot only (`clip_table.py`\'s `curve`). Do not edit by hand.',
        '',
        '/// One clip\'s root channels: side (x), rise (y), ahead (z), each its (knot, value) keys as f32 bits.',
        'pub struct ClipKeys {',
        '    pub side: &\'static [(u32, u32)],',
        '    pub rise: &\'static [(u32, u32)],',
        '    pub ahead: &\'static [(u32, u32)],',
        '}',
        '',
    ]
    for const, name in CLIPS:
        p = os.path.join(d, 'animations__single__weapons__ak__player__stand__3rd_view__jump__%s.b-spline' % name)
        t = tracks(p)
        lines.append('/// `%s`.' % name.replace('sprint__', 'sprint/'))
        lines.append('pub const %s: ClipKeys = ClipKeys {' % const)
        for field, i in CHANNELS:
            keys = ', '.join('(0x%08X, 0x%08X)' % kv for kv in t[i])
            lines.append('    %s: &[%s],' % (field, keys))
        lines.append('};')
        lines.append('')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
