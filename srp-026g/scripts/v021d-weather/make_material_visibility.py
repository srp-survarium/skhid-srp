#!/usr/bin/env python3
"""Restore original 0.21 visibility selectors without changing native materials.

The importer now preserves these selectors before native deduplication. This
authored edit retrofits the already published packs, preserving their reviewed
native finishes, textures and other schema adaptations. Inputs record original
values, previous converted values and every affected model binding from the
15-project audit. No geometry or local lighting adjustment is made.
"""
import json
from pathlib import Path
import sys


def make(source):
    copies, flags, bindings = [], [], []
    for row in source['materials']:
        old, new = row['current_material'], row['target_material']
        destination = f'material_instances/{new}.material'
        if old != new:
            assert not old.startswith('ported/v021d/')
            assert new == f'ported/v021d/original_visibility/{old}'
            origin = f'material_instances/{old}.material'
            copies.append({'files': origin, 'from': origin, 'to': destination})
            for settings in sorted({b['settings'] for b in row['bindings']}):
                assert settings.startswith('models/ported/v021d/')
                bindings.append({'files': settings, 'from': old, 'to': new})
        assert new.startswith('ported/v021d/')
        for path, values in sorted(row['changes'].items()):
            assert path.endswith('.value') and path.split('.')[-2] in source['selectors']
            assert type(values['original']) is bool and type(values['port']) is bool
            assert values['original'] != values['port']
            flags.append({'file': destination, 'path': path.replace('.', '/'),
                          'from': values['port'], 'to': values['original']})
    return {'_about': __doc__.strip() + ' Generated by make_material_visibility.py; '
            'donor values and unchanged-property hashes in material-visibility-inputs.json.',
            'copy': copies, 'set_bool': flags, 'replace_string': bindings}


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(json.dumps(make(json.loads(source.read_text())), indent=2) + '\n')
