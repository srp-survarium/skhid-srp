#!/usr/bin/env python3
"""Make explicit original constructor defaults for weather environments.

Input is the authored weather content packs, whose environment converter keeps
only original donor fields and documented shader compatibility fields. Omitted
height-ambient values use the same original defaults as day-map authoring:
0.21 constructor 0x215157, optional loader 0x2157F7. No artistic adjustment.
"""
import json
from pathlib import Path
import sys

from check_packs import lamps

DEFAULTS = {'height_based_ambient_low_color': [0, 0, 0, 1],
            'height_based_ambient_high_color': [1, 1, 1, 1]}


def make(*packs):
    rows = []
    for pack in packs:
        rows += rows_of(pack)
    return {'_about': __doc__.strip() + ' Generated by scripts/v021d-weather/make_environment.py.',
            'add_value': rows}


def rows_of(pack):
    rows = []
    files = pack / 'files'
    projects = sorted(files.glob('projects/v021d_level_*/*/client_project'))
    if len(projects) % 4 or not projects:
        raise ValueError('expected four weather projects a map')
    for project in projects:
        objects = lamps.tree(project.read_bytes())['client_objects']
        environments = [(i, o['properties']) for i, o in enumerate(objects)
                        if o.get('game_object_type') == 'environment']
        if len(environments) != 1:
            raise ValueError(f'{project}: expected one environment')
        i, properties = environments[0]
        for key, value in DEFAULTS.items():
            if key not in properties:
                rows.append({'files': [project.relative_to(files).as_posix()],
                             'table': f'client_objects[{i}]/properties', 'key': key, 'value': value})
    return rows


if __name__ == '__main__':
    *packs, out = map(Path, sys.argv[1:])
    out.write_text(json.dumps(make(*packs), indent=2) + '\n')
