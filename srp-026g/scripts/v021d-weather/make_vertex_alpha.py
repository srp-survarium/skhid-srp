"""Restore original painted-alpha cutouts and ordinary shadow thresholds.

The 28 private materials have no active original vertex blending. Native
technique/tiled-mask selectors translate that state to the ordinary shader;
five alpha_ref codes select the original visible equation and shadow threshold.
The five materials with alpha testing disabled remain unchanged.
"""
import json
from pathlib import Path
import sys

PREFIX = 'material.g_stage.effect.'
ALPHA_REF = PREFIX + 'alpha_ref.value'
PROFILES = {
    (.1, .5, False, .5): -21210.,
    (.5, 1., False, .25): -21211.,
    (1., 1., False, .5): -21212.,
    (1., 1., True, .25): -21213.,
    (1., 1., False, .25): -21215.,
}
INACTIVE = {
    'vertex_blend_technique': 0,
    'use_tiled_vertex_blended_mask': False,
    'alpha_test_consider_vertex_blend': False,
    'use_vertex_blended_diffuse': False,
    'use_vertex_blended_normal': False,
    'use_vertex_blended_specular': False,
    'use_vertex_blended_mask': False,
}


def make(source):
    assert source['schema'] == 2
    numbers, flags = [], []
    active, inactive = 0, 0
    seen = set()
    for row in source['materials']:
        target = row['target_material']
        assert target not in seen
        seen.add(target)
        if row['state'] == 'inactive_alpha_test_disabled':
            assert 'changes' not in row
            inactive += 1
            continue
        assert row['state'] == 'active' and target.startswith('ported/v021d/')
        active += 1
        original = row['original_profile']
        profile = tuple(original[k] for k in ('dark_border', 'light_border', 'multiply', 'shadow_threshold'))
        marker = PROFILES[profile]
        blend = row['original_blend']
        assert not (blend['master'] and any(blend['channels'].values()))
        expected = {ALPHA_REF}
        for name, value in INACTIVE.items():
            if row['native_selectors'][name] != value:
                expected.add(PREFIX + name + '.value')
        assert set(row['changes']) == expected
        for key, change in sorted(row['changes'].items()):
            before, after = change['from'], change['to']
            edit = {'file': f'material_instances/{target}.material', 'path': key.replace('.', '/'),
                    'from': before, 'to': after}
            if key == ALPHA_REF:
                assert before == original['shadow_threshold'] == change['original']
                assert after == marker and change['as_float'] is True
                edit['as_float'] = True
            else:
                name = key.removeprefix(PREFIX).removesuffix('.value')
                assert after == INACTIVE[name] and type(after) is type(INACTIVE[name])
                assert before == row['native_selectors'][name] and before != after
            (flags if type(after) is bool else numbers).append(edit)
    assert (active, inactive) == (28, 5)
    return {'_about': __doc__.strip() + ' Generated by make_vertex_alpha.py; provenance in vertex-alpha-inputs.json.',
            'set': numbers, 'set_bool': flags}


def prior_material(values, material, source):
    """Undo only exact checked later deltas for an earlier edit's snapshot."""
    result = dict(values)
    matches = [r for r in source['materials'] if r['target_material'] == material and r['state'] == 'active']
    assert len(matches) <= 1
    for row in matches:
        for key, change in row['changes'].items():
            assert result[key] == change['to'], (material, key, 'painted-alpha final value')
            result[key] = change['from']
    return result


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(json.dumps(make(json.loads(source.read_text())), indent=2) + '\n')
