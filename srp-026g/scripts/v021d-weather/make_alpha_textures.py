"""Restore original alpha-sensitive texture mipchains on imported 0.21 materials.

Original alpha-test/transparency textures may have the same full-resolution
image but different lower-mip coverage in 0.26g. A private original DDS/options
pack preserves the complete donor data. These precise reference edits retain
all visibility flags, native finish adaptations and unrelated material leaves.
Shared native materials are copied privately before any reference changes.
"""
import json
from pathlib import Path
import sys


def make(source):
    copies, textures, bindings = [], [], []
    known = {r['texture'] for r in source['textures']}
    for row in source['materials']:
        old, new = row['current_material'], row['target_material']
        destination = f'material_instances/{new}.material'
        if old != new:
            assert not old.startswith('ported/v021d/')
            assert new == f'ported/v021d/original_alpha_mips/{old}'
            origin = f'material_instances/{old}.material'
            copies.append({'files': origin, 'from': origin, 'to': destination})
            for settings in sorted({b['settings'] for b in row['bindings']}):
                assert settings.startswith('models/ported/v021d/')
                bindings.append({'files': settings, 'from': old, 'to': new})
        assert new.startswith('ported/v021d/')
        for key, values in sorted(row['changes'].items()):
            assert key.endswith(('.texture_diffuse.value', '.texture_transparency.value'))
            assert values['source_texture'] in known
            assert values['from'] == values['source_texture']
            assert values['to'] == 'ported/v021d/original_alpha_mips/' + values['source_texture']
            textures.append({'file': destination, 'path': key.replace('.', '/'),
                             'from': values['from'], 'to': values['to']})
    return {'_about': __doc__.strip() + ' Generated by make_alpha_textures.py; '
            'exact donor hashes and unchanged-property hashes in alpha-texture-inputs.json.',
            'copy': copies, 'edit_text': textures, 'replace_string': bindings}


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(json.dumps(make(json.loads(source.read_text())), indent=2) + '\n')
