"""Restore the original vertex-alpha equations on active 0.21 materials.

The selector enables a renderer compatibility equation, not a strength retune.
Private copies isolate materials also used by native maps. Original normal
blending flags and second-texture activation are restored; reviewed native
finishes and all unrelated leaves remain unchanged. Masked materials select
their original base-alpha equation, with exact original factor and falloff.
"""
import json
from pathlib import Path
import sys
import struct

PREFIX = 'material.g_stage.effect.'
STRENGTH = PREFIX + 'constant_vertex_blended_strength.value'
TECHNIQUE = PREFIX + 'vertex_blend_technique.value'
NORMAL = PREFIX + 'use_vertex_blended_normal.value'
FALLOFF = PREFIX + 'constant_vertex_blended_falloff.value'
ALPHA_CONSIDER = PREFIX + 'alpha_test_consider_vertex_blend.value'


def masked_marker(factor):
    factor = struct.unpack('<f', struct.pack('<f', factor))[0]
    assert 1 <= factor <= 2
    strength = -int(factor * 8388608)
    assert struct.pack('<f', -strength / 8388608) == struct.pack('<f', factor)
    return strength


def make(source):
    assert source['schema'] == 2
    copies, numbers, flags, bindings = [], [], [], []
    for row in source['materials']:
        old, new = row['current_material'], row['target_material']
        destination = f'material_instances/{new}.material'
        if old != new:
            assert not old.startswith('ported/v021d/')
            assert new == f'ported/v021d/original_blend/{old}'
            origin = f'material_instances/{old}.material'
            copies.append({'files': origin, 'from': origin, 'to': destination})
            for settings in sorted({b['settings'] for b in row['bindings']}):
                assert settings.startswith('models/ported/v021d/')
                bindings.append({'files': settings, 'from': old, 'to': new})
        assert new.startswith('ported/v021d/')
        original = row['original_blend']
        assert original[PREFIX + 'use_vertex_blended_textures.value'] is True
        assert original[PREFIX + 'use_vertex_blended_diffuse.value'] is True
        mode = row['mode']
        assert mode in ('linear', 'masked')
        assert original[PREFIX + 'use_vertex_blended_mask.value'] is (mode == 'masked')
        marker = -21021 if mode == 'linear' else masked_marker(original[PREFIX + 'constant_vertex_blended_factor.value'])
        for key, values in sorted(row['changes'].items()):
            before, after = values['from'], values['to']
            if key == STRENGTH:
                assert type(before) is int and before >= 0 and after == marker
            elif key == TECHNIQUE:
                assert type(before) is int and before == 0 and after == 1
            elif key == FALLOFF:
                assert mode == 'masked' and after == original[key] and before != after
                assert values['as_float'] is True and type(after) is float
            elif key == ALPHA_CONSIDER:
                assert row['alpha_cutoff'] == 'base_texture'
                assert original[PREFIX + 'use_alpha_test.value'] is True
                assert before is True and after is False
            else:
                assert key == NORMAL
                assert type(before) is bool and type(after) is bool and before != after
                assert after == original[key]
            target = flags if type(after) is bool else numbers
            target.append({'file': destination, 'path': key.replace('.', '/'), **values})
    return {'_about': __doc__.strip() + ' Generated by make_vertex_blend.py; '
            'source values, bindings and unchanged-property hashes in vertex-blend-inputs.json.',
            'copy': copies, 'set': numbers, 'set_bool': flags, 'replace_string': bindings}


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(json.dumps(make(json.loads(source.read_text())), indent=2) + '\n')
