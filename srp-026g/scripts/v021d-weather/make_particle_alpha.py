"""Preserve original particle transparency mipchains using private material copies.

Only the exact imported particle Material leaves listed in provenance are rebound.
Original particle parameters, material flags and all shared native assets remain
unchanged. DDS and options come byte-for-byte from the original 0.21 archive.
"""
import json
from pathlib import Path
import sys

PREFIX = 'ported/v021d/original_particle_alpha/'


def make(source):
    copies, edits = [], []
    known = {row['texture'] for row in source['textures']}
    material_bindings = {}
    for row in source['materials']:
        old, new = row['current_material'], row['target_material']
        assert new == PREFIX + row['original_material'] and old != new
        origin = 'material_instances/' + old + '.material'
        target = 'material_instances/' + new + '.material'
        copies.append({'files': origin, 'from': origin, 'to': target})
        for key, change in sorted(row['changes'].items()):
            assert key.endswith(('.texture_diffuse.value', '.texture_transparency.value'))
            assert change['source_texture'] in known
            assert change['from'] == change['source_texture']
            assert change['to'] == PREFIX + change['source_texture']
            edits.append({'file': target, 'path': key.replace('.', '/'),
                          'from': change['from'], 'to': change['to']})
        for binding in row['bindings']:
            slot = (binding['particle'], binding['key'])
            assert slot not in material_bindings
            material_bindings[slot] = {'from': old, 'to': new}
    particle_bindings = {}
    for row in source['particles']:
        assert row['path'].startswith('particles/ported/v021d/')
        for key, change in sorted(row['changes'].items()):
            assert key.endswith('.Material')
            particle_bindings[(row['path'], key)] = change
            edits.append({'file': row['path'], 'path': key.replace('.', '/'), **change})
    assert material_bindings == particle_bindings
    return {'_about': __doc__.strip() + ' Generated by make_particle_alpha.py; '
            'source hashes and unchanged-property snapshots in particle-alpha-inputs.json.',
            'copy': copies, 'edit_text': edits}


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(json.dumps(make(json.loads(source.read_text())), indent=2) + '\n')
