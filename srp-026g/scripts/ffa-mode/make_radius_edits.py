#!/usr/bin/env python3
"""Set every FFA spawn's exclusion radius to 20 m after all spawn additions.

Generate the source edit with --live DIR containing the projects as the earlier
manifest rows leave them. Placement/donor TSVs retain their original evidence;
this final balance retune also covers School's pre-existing solo spawn.
"""
import argparse
from pathlib import Path

import make_edits as base
import make_ported_edits as ports

RADIUS = 20
OUTPUT = base.HERE.parent / 'content-edit/ffa-radius-1.json'


def projects():
    return [base.project(level, weather) for level, _, weather, _ in base.MAPS] + [
        base.copy_of(f'projects/{name}/day_4/client_project') for name, _ in ports.MAPS]


def edits(live):
    out = {'_about': 'FFA exclusion radius 20 m on every solo spawn, requested 2026-11-12. '
           'Generated by scripts/ffa-mode/make_radius_edits.py. Apply after ffa-1, ffa-ported-1 '
           'and ffa-london-center-1. Includes School\'s existing 50 m solo spawn; Cologne already '
           'uses 20 m. Changes only team-2 enemy_check_radius; preserves placement, protection, '
           'all other fields and every team spawn.', 'set_entry': []}
    for path in projects():
        entries = base.tree((live / path).read_bytes())['server_objects']['respawn_points']
        solo = [entry for entry in entries if entry['team'] == 2]
        if not solo:
            raise ValueError(f'{path}: no FFA spawns')
        for entry in solo:
            radius = entry['enemy_check_radius']
            if radius == RADIUS:
                continue
            if radius not in (30, 50):
                raise ValueError(f'{path}: unexpected pre-retune radius {radius}')
            out['set_entry'].append({'file': path, 'list': base.POINTS,
                'where': {key: entry[key] for key in ('point_id', 'name', 'team')},
                'from': {'enemy_check_radius': radius}, 'to': {'enemy_check_radius': RADIUS}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    base.write(edits(args.live), OUTPUT)
    print(OUTPUT)


if __name__ == '__main__':
    main()
