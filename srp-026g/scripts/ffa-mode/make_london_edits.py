#!/usr/bin/env python3
"""Add reviewed central London FFA spawns after ffa-1.json.

Run check-points' central binary on archives containing the original 22 London
FFA spawns, inspect its floor plot, and save london-center.tsv. Generate this
source recipe with --live DIR (the current London project at its game path).
"""
import argparse
import csv
from pathlib import Path
import math

import make_edits as base

HERE = Path(__file__).resolve().parent
POINTS = HERE / 'london-center.tsv'
OUTPUT = HERE.parent / 'content-edit/ffa-london-center-1.json'
PROJECT = 'level_09/day_4'
PATH = base.copy_of('projects/' + PROJECT + '/client_project')
COUNT = 6
AREA = (-35., -30., 40., 30.)
SPACING = 12.


def points():
    with POINTS.open(newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    if len(rows) != COUNT or len({p['point'] for p in rows}) != COUNT:
        raise ValueError('expected six unique central London points')
    for i, row in enumerate(rows):
        if row['project'] != PROJECT or row['verdict'] != 'kept':
            raise ValueError('point is not checked London geometry')
        values = [float(row[k]) for k in ('x', 'y', 'z', 'rx', 'ry', 'rz')]
        if not all(math.isfinite(v) for v in values):
            raise ValueError('point contains non-finite values')
        x, _, z = values[:3]
        if not (AREA[0] <= x <= AREA[2] and AREA[1] <= z <= AREA[3]):
            raise ValueError('point is outside central London')
        if float(row['invulnerability_time']) != 2 or float(row['enemy_check_radius']) != 30:
            raise ValueError('incorrect protection or enemy radius')
        for other in rows[:i]:
            if (x-float(other['x']))**2 + (z-float(other['z']))**2 < SPACING**2 - 0.001:
                raise ValueError('central points are too close')
    return rows


def edits(live):
    buf = (live / PATH).read_bytes()
    entries = base.tree(buf)['server_objects']['respawn_points']
    existing = [p for p in entries if p['team'] == 2]
    if len(existing) != 22 or [p['point_id'] for p in entries] != list(range(len(entries))):
        raise ValueError('expected the original 22 London FFA spawns and consecutive IDs')
    model = next(p for p in existing if all(base.walked_types(buf, f"{base.POINTS}[{p['point_id']}]")[k]
                                           == base.c.T_FLOAT for k in base.RADII))
    if any(model[z]['collision_geometries'] for z in ('ally_zones', 'enemy_zones')):
        raise ValueError('solo template has team-base zones')
    taken = {p['name'] for p in entries}
    out = {'_about': 'Six additional London central FFA spawns requested 2026-11-12. Generated by '
           'scripts/ffa-mode/make_london_edits.py from london-center.tsv after geometry review. '
           'Reachable standing floors, clear body, harmful zones at least 2 m away, walkable facing '
           '6 m, at least 12 m from existing solo spawns and each other. Keeps all original points '
           'and IDs; new solo group 2, 2 s protection, empty team zones. Apply after ffa-1.json.',
           'add_entry': []}
    for i, row in enumerate(points()):
        name = 'ffa_london_' + row['point']
        position = [float(row[k]) for k in ('x', 'y', 'z')]
        if name in taken:
            raise ValueError('new point name already exists')
        if any((position[0]-p['position'][0])**2 + (position[2]-p['position'][2])**2 < SPACING**2 - 0.001
               for p in existing):
            raise ValueError('new point is too close to an existing FFA spawn')
        point_id = len(entries) + i
        out['add_entry'].append({'files': PATH, 'list': base.POINTS,
            'after': {'point_id': point_id-1}, 'like': {'point_id': model['point_id']}, 'values': {
                'name': name, 'full_name': 'logic/modes/ffa/respawn/' + name, 'point_id': point_id,
                'team': 2, 'position': position, 'rotation': [float(row[k]) for k in ('rx', 'ry', 'rz')],
                'enemy_check_radius': 30., 'ally_check_radius': 1., 'invulnerability_time': 2,
                'priority': 1, 'is_temporary': False}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    base.write(edits(args.live), OUTPUT)
    print(OUTPUT)


if __name__ == '__main__':
    main()
