#!/usr/bin/env python3
"""Add reviewed London FFA spawns: the central ones after ffa-1.json, the underpass's after
ffa-center-1.json.

Run check-points' central binary (`--region central` on archives containing the original 22 London
FFA spawns; `--region underpass` on the projects as every row above ffa-london-underpass-1 leaves
them, 28 solo spawns), inspect its floor plot, and save its rows as the region's TSV. Generate the
region's source recipe with --region <name> --live DIR (the current London project at its game
path, as the rows above the list leave it).
"""
import argparse
import csv
from dataclasses import dataclass
from pathlib import Path
import math
from typing import Callable

import make_edits as base

HERE = Path(__file__).resolve().parent
PATH = base.copy_of('projects/level_09/day_4/client_project')
AREA = (-35., -30., 40., 30.)
# The underpass under the roundabout: its floor 0.7, the plate over it 4.73, the street 6.
UNDERPASS_BELOW = 4.5


def in_central(x, y, z):
    return AREA[0] <= x <= AREA[2] and AREA[1] <= z <= AREA[3]


def in_underpass(x, y, z):
    return in_central(x, y, z) and y < UNDERPASS_BELOW


@dataclass(frozen=True)
class Region:
    """One list of added London spawns: its reviewed points, its edit list, how many are added to
    how many, their radius and where they stand. They were authored 12 m from every solo spawn (in
    plan in central London, in 3D under it); since 2026-11-14 no spacing is checked (the owner: "we
    don't need this rules at all")."""
    name: str
    points: Path
    output: Path
    project: str
    count: int
    existing: int
    radius: float
    holds: Callable
    about: str


CENTRAL = Region(
    'central', HERE / 'london-center.tsv', HERE.parent / 'content-edit/ffa-london-center-1.json',
    'level_09/day_4', 6, 22, 30., in_central,
    'Six additional London central FFA spawns requested 2026-11-12. Generated by '
    'scripts/ffa-mode/make_london_edits.py from london-center.tsv after geometry review. '
    'Reachable standing floors, clear body, harmful zones at least 2 m away, walkable facing '
    '6 m, at least 12 m from existing solo spawns and each other. Keeps all original points '
    'and IDs; new solo group 2, 2 s protection, empty team zones. Apply after ffa-1.json.')
UNDERPASS = Region(
    'underpass', HERE / 'london-underpass.tsv', HERE.parent / 'content-edit/ffa-london-underpass-1.json',
    'level_09/day_8', 4, 28, 20., in_underpass,
    'Four London FFA spawns in the underpass under the roundabout (the owner, 2026-11-14: "put more '
    'points in basement there"). Generated by scripts/ffa-mode/make_london_edits.py --region underpass '
    'from london-underpass.tsv after geometry review. Reachable standing floors under its ceiling, clear '
    'body, harmful zones at least 2 m away, a walkable 6 m facing along it with 20 m of view, at least '
    '12 m in 3D from every solo spawn and each other. Keeps all points and IDs; new solo group 2, 20 m '
    'exclusion, 2 s protection, empty team zones. Apply after ffa-center-1.json.')
REGIONS = {r.name: r for r in (CENTRAL, UNDERPASS)}


def points(region):
    with region.points.open(newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    if len(rows) != region.count or len({p['point'] for p in rows}) != region.count:
        raise ValueError(f'expected {region.count} unique {region.name} London points')
    for row in rows:
        if row['project'] != region.project or row['verdict'] != 'kept':
            raise ValueError('point is not checked London geometry')
        values = [float(row[k]) for k in ('x', 'y', 'z', 'rx', 'ry', 'rz')]
        if not all(math.isfinite(v) for v in values):
            raise ValueError('point contains non-finite values')
        if not region.holds(*values[:3]):
            raise ValueError(f'point is outside the {region.name} region')
        if float(row['invulnerability_time']) != 2 or float(row['enemy_check_radius']) != region.radius:
            raise ValueError('incorrect protection or enemy radius')
    return rows


def edits(region, live):
    buf = (live / PATH).read_bytes()
    entries = base.tree(buf)['server_objects']['respawn_points']
    existing = [p for p in entries if p['team'] == 2]
    if len(existing) != region.existing or [p['point_id'] for p in entries] != list(range(len(entries))):
        raise ValueError(f'expected {region.existing} London FFA spawns and consecutive IDs')
    model = next(p for p in existing if all(base.walked_types(buf, f"{base.POINTS}[{p['point_id']}]")[k]
                                           == base.c.T_FLOAT for k in base.RADII))
    if any(model[z]['collision_geometries'] for z in ('ally_zones', 'enemy_zones')):
        raise ValueError('solo template has team-base zones')
    taken = {p['name'] for p in entries}
    out = {'_about': region.about, 'add_entry': []}
    for i, row in enumerate(points(region)):
        name = 'ffa_london_' + row['point']
        position = [float(row[k]) for k in ('x', 'y', 'z')]
        if name in taken:
            raise ValueError('new point name already exists')
        point_id = len(entries) + i
        out['add_entry'].append({'files': PATH, 'list': base.POINTS,
            'after': {'point_id': point_id-1}, 'like': {'point_id': model['point_id']}, 'values': {
                'name': name, 'full_name': 'logic/modes/ffa/respawn/' + name, 'point_id': point_id,
                'team': 2, 'position': position, 'rotation': [float(row[k]) for k in ('rx', 'ry', 'rz')],
                'enemy_check_radius': region.radius, 'ally_check_radius': 1., 'invulnerability_time': 2,
                'priority': 1, 'is_temporary': False}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--live', type=Path, required=True)
    parser.add_argument('--region', choices=REGIONS, default='central')
    args = parser.parse_args()
    region = REGIONS[args.region]
    base.write(edits(region, args.live), region.output)
    print(region.output)


if __name__ == '__main__':
    main()
