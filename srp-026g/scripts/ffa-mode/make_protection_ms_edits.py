#!/usr/bin/env python3
"""ffa-protection-ms-1.json: half a second of spawn protection at every Free for All point.

    make_protection_ms_edits.py LIVE

The owner, 2026-11-14: "let's change it to 0.5 everywhere" (Free for All's spawn protection,
2 s since revision 57; Training Camp's 0.5 s since PR #1790). The game reads the points' whole
seconds `invulnerability_time` (respawn_point_core's load, 0x2F4628: seconds x 1000); the
client hook that shipped in revision 57 (docs/notes/stalker-ffa.md, "Millisecond protection")
reads an optional `invulnerability_time_ms` first. So each team-2 point of every <weather>_8
project gets `invulnerability_time` 2 -> 0 and `invulnerability_time_ms` 500, as
training-camp-arena-1.json gave Training Camp's, which this list leaves as it is.

LIVE is a folder of the projects as every row before this list's leaves them (srp-game-data get
of a build-content patch over players' files): the points are addressed by their index there,
so the list is made again whenever a list above it adds or removes a respawn point.
Writes srp-026g/scripts/content-edit/ffa-protection-ms-1.json.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'content-edit'))
import content_edit as ce  # noqa: E402

OUT = HERE.parent / 'content-edit' / 'ffa-protection-ms-1.json'
MS = 500
SECONDS = 2
POINTS = 'server_objects/respawn_points'


def value(buf, key, entry):
    try:
        data, _, _, _, _ = ce.rec(buf, ce.find(buf, key, entry))
    except KeyError:
        return None
    return data & 0xffffffff


def main():
    live = Path(sys.argv[1])
    sets, adds, done = [], [], []
    projects = sorted(live.glob('projects/*/*_8/client_project'))
    if not projects:
        raise SystemExit(f'{live}: no <weather>_8 projects')
    for path in projects:
        rel = path.relative_to(live).as_posix()
        buf = bytearray(path.read_bytes())
        points = [(i, e) for i, e in enumerate(ce.children(buf, ce.find(buf, POINTS)))
                  if value(buf, 'team', e) == 2]
        if not points:
            raise SystemExit(f'{rel}: no team-2 point')
        has_ms = [value(buf, 'invulnerability_time_ms', e) for _, e in points]
        if all(v == MS for v in has_ms):
            done.append(rel)
            continue
        if any(v is not None for v in has_ms):
            raise SystemExit(f'{rel}: some team-2 points have invulnerability_time_ms already')
        for i, e in points:
            seconds = value(buf, 'invulnerability_time', e)
            if seconds != SECONDS:
                raise SystemExit(f'{rel}: team-2 point at {i} has {seconds} s, not {SECONDS}')
            sets.append({'file': rel, 'list': POINTS,
                         'where': {'team': 2, 'point_id': value(buf, 'point_id', e)},
                         'from': {'invulnerability_time': SECONDS}, 'to': {'invulnerability_time': 0}})
            adds.append({'files': [rel], 'table': f'{POINTS}[{i}]',
                         'key': 'invulnerability_time_ms', 'value': MS})
    about = ('Free for All spawn protection 0.5 s on every map (the owner, 2026-11-14: "let\'s change it to 0.5 '
             'everywhere"; it was 2 s, the whole seconds the game reads, since revision 57). Each team-2 point of '
             f'every <weather>_8 project but those that have it already ({", ".join(done) or "none"}) gets '
             'invulnerability_time 2 -> 0 and invulnerability_time_ms 500, which the client hook of revision 57 '
             'reads first (docs/notes/stalker-ffa.md, "Millisecond protection"), as training-camp-arena-1.json '
             f'gave Training Camp. {len(sets)} points in {len({s["file"] for s in sets})} projects. Team '
             'Deathmatch\'s points (teams 0 and 1) and projects are untouched. After every list that adds a Free '
             'for All point: the points are addressed by index. Generated by scripts/ffa-mode/'
             'make_protection_ms_edits.py.')
    rows = lambda xs: '[\n' + ',\n'.join('  ' + json.dumps(x) for x in xs) + '\n ]'
    OUT.write_text('{\n "_about": %s,\n "set_entry": %s,\n "add_value": %s\n}\n'
                   % (json.dumps(about), rows(sets), rows(adds)))
    print(f'{OUT.name}: {len(sets)} points in {len({s["file"] for s in sets})} projects; already 500 ms: {done}')


if __name__ == '__main__':
    main()
