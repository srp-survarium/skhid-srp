#!/usr/bin/env python3
"""FFA configs and authored, collision-checked solo spawns for the five ported maps.

Run check-points' `ported` binary on the current layered game archives to regenerate
ported.tsv, review its floor plots, then `python make_ported_edits.py --live DIR`.
DIR contains --paths as ffa-1.json leaves them. The resulting ffa-ported-1.json
is applied after ffa-1.json; no existing two-team spawn is changed. The new spawns
have empty ally/enemy zones, including ports whose original points use base zones.
"""
import argparse
import csv
import json
from pathlib import Path

import make_edits as base

HERE = Path(__file__).resolve().parent
POINTS = HERE / 'ported.tsv'
OUTPUT = HERE.parent / 'content-edit/ffa-ported-1.json'
# IDs 164/165/167..169 are vacant after ffa-1; 166 and 175 are older ports.
# Keep 12..41 free for Scarcity, and keep every existing FFA ID stable.
MAPS = [('v021d_level_03', 164), ('v021d_level_06', 165),
        ('v011e_level_04', 167), ('v011e_level_03', 168), ('v069d_level_01', 169)]


def paths():
    return [base.DICTIONARY] + [p for name, _ in MAPS for p in (
        f'gameplay/game_modes/{name}_day_4.options', f'projects/{name}/day_4/client_project')]


def points():
    by = {}
    with POINTS.open(newline='') as stream:
        for row in csv.DictReader(stream, delimiter='\t'):
            if row['verdict'] != 'kept':
                raise ValueError('ported.tsv contains an unchecked point')
            by.setdefault(row['project'], []).append(row)
    if set(by) != {name + '/day_4' for name, _ in MAPS}:
        raise ValueError('ported.tsv does not cover exactly the five ports')
    for project, rows in by.items():
        if len(rows) != 22 or len({r['point'] for r in rows}) != len(rows):
            raise ValueError(f'{project}: expected 22 unique authored points')
        for i, row in enumerate(rows):
            if float(row['invulnerability_time']) != 2 or float(row['enemy_check_radius']) != 30:
                raise ValueError(f'{project}: incorrect protection or enemy radius')
            for other in rows[:i]:
                distance = sum((float(row[k]) - float(other[k])) ** 2 for k in ('x', 'z'))
                if distance < 12 ** 2 - 0.001:
                    raise ValueError(f'{project}: points less than 12 m apart')
    return by


def edits(live):
    def read(path):
        return (live / path).read_bytes()
    dictionary = base.tree(read(base.DICTIONARY))['maps_dict']
    ids = {entry['id'] for entry in dictionary}
    names = {entry['cfg_mode_name'] for entry in dictionary}
    authored = points()
    out = {'_about': 'FFA on all five ported day maps: Vostok/Mamayev v0.21d, Chemical Plant/Vostok '
           'v0.11e, Rudnya v0.69d. Generated by scripts/ffa-mode/make_ported_edits.py from ported.tsv; '
           '22 reachable, standing-body-clear, harmful-zone-free points per map, spaced at least 12 m '
           'inside the established spawn footprint and facing a walkable 6 m. Apply after ffa-1.json. Copies final TDM configs into ffa/ as '
           'mode 8, rules 93/91/94, 30 kills, 10 players. Adds only solo spawn group 2 with 2 s '
           'protection and empty ally/enemy collision zones; leaves all original team spawns intact.',
           'copy': [], 'set': [], 'replace_string': [], 'remove_item': [], 'append_entry': [],
           'add_entry': [], 'add_value': [], 'remove_entry': []}
    for map_index, (name, map_id) in enumerate(MAPS):
        src = f'gameplay/game_modes/{name}_day_4.options'
        dst = f'gameplay/game_modes/ffa/{name}_day_8.options'
        project = name + '/day_4'
        mode = base.tree(read(src))['mode']
        if mode['mode'] != 4 or mode['rules'] != base.RULES or mode['match_making_params']['map_name'] != project:
            raise ValueError(f'{src}: unexpected TDM config')
        if map_id in ids or dst[len(base.MODES):] in names or src[len(base.MODES):] not in names:
            raise ValueError(f'{src}: occupied ID/name or absent TDM dictionary entry')
        out['copy'].append({'files': src, 'from': src, 'to': dst})
        out['set'].append({'file': dst, 'path': 'mode/mode', 'from': 4, 'to': 8})
        if mode['ui']['icon'] != base.ICON:
            out['set'].append({'file': dst, 'path': 'mode/ui/icon', 'from': mode['ui']['icon'], 'to': base.ICON})
        if not mode['name'].endswith('_4'):
            raise ValueError(f'{src}: unexpected mode name')
        out['replace_string'].append({'files': dst, 'from': mode['name'], 'to': mode['name'][:-1] + '8'})
        for key, pattern in base.TEXTS.items():
            if mode['ui'][key] != pattern.format(4):
                raise ValueError(f'{src}: unexpected {key}')
            out['replace_string'].append({'files': dst, 'from': pattern.format(4), 'to': pattern.format(8)})
        out['remove_item'].append({'file': dst, 'path': 'mode/rules', 'value': 90})
        for table, key, value in base.ADDED:
            out['add_value'].append({'files': [dst], 'table': table, 'key': key, 'value': value})
        out['append_entry'].append({'file': base.DICTIONARY, 'list': 'maps_dict',
                                   'expected_count': len(dictionary) + map_index, 'unique_key': 'id',
                                   'value': {'cfg_mode_name': dst[len(base.MODES):], 'id': map_id}})
        path = 'projects/' + project + '/client_project'
        buf = read(path)
        entries = base.tree(buf)['server_objects']['respawn_points']
        if [e['point_id'] for e in entries] != list(range(len(entries))) or any(e['team'] not in (0, 1) for e in entries):
            raise ValueError(f'{path}: unexpected source spawn IDs or sides')
        model = entries[0]
        for i, row in enumerate(authored[project]):
            point_id = len(entries) + i
            point_name = 'ffa_' + row['point']
            values = {'name': point_name, 'full_name': 'logic/modes/ffa/respawn/' + point_name,
                      'point_id': point_id, 'team': 2, 'priority': 1, 'is_temporary': False,
                      'position': [float(row[k]) for k in ('x', 'y', 'z')],
                      'rotation': [float(row[k]) for k in ('rx', 'ry', 'rz')], 'invulnerability_time': 2}
            point_path = f'{base.POINTS}[{point_id}]'
            for key, value in [('enemy_check_radius', 30.0), ('ally_check_radius', 1.0)]:
                if key in model:
                    values[key] = value
                else:
                    out['add_value'].append({'files': [path], 'table': point_path, 'key': key, 'value': value})
            out['add_entry'].append({'files': path, 'list': base.POINTS,
                                     'after': {'point_id': point_id - 1}, 'like': {'point_id': 0}, 'values': values})
            for zone in ('ally_zones', 'enemy_zones'):
                for shape in model[zone]['collision_geometries']:
                    out['remove_entry'].append({'file': path, 'list': point_path + '/' + zone + '/collision_geometries',
                                                'where': {'name': shape['name']}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    what = parser.add_mutually_exclusive_group(required=True)
    what.add_argument('--paths', action='store_true')
    what.add_argument('--live', type=Path)
    args = parser.parse_args()
    if args.paths:
        print('\n'.join(paths()))
    else:
        base.write(edits(args.live), OUTPUT)
        print(OUTPUT)


if __name__ == '__main__':
    main()
