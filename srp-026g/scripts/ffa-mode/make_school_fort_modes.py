#!/usr/bin/env python3
"""Writes content-edit/v021d-school-fort-modes-1.json: Blackout and Free for All on School and
Tarakanovsky Fort v0.21 (pack maps-021d-school-fort@4), as Vostok and Mamayev Kurgan v0.21 have
them, in one list after every other row, so it can wait for its maps_dict ids:

    python3 make_school_fort_modes.py --live <folder> \\
        --blackout v021d_level_02=<id>,v021d_level_05=<id> --ffa v021d_level_02=<id>,v021d_level_05=<id>

its row in release/content.tsv right above stalker-tdm-hold-1.json, the last list that edits
maps_dict (edit v021d-school-fort-modes-1.json). The ids are the list's only parameters: maps_dict
holds a byte, so take ids no live row and no open branch has.

<folder>: gameplay/db_static_dictionaries, gameplay/game_modes/v021d_level_0{2,5}_day_{2,4}.options
and projects/v021d_level_0{2,5}/day_4/client_project as every row of the manifest leaves them (the
build's files: vostok-port extract from its patch); no row below this list's edits these maps, and
the dictionary's count here is the build's plus the rows stalker-tdm-hold-1 takes out.

- Blackout (blackout-mode-1.json's rule): each battery config once more under blackout/, srp_variant
  blackout, the name st_srp_mode_blackout, a maps_dict row.
- Free for All, as ffa-projects-1, ffa-ported-1, no-ammo-crates-1, ffa-radius-1 and
  ffa-protection-ms-1 made it for the other ports: the TDM project copied to day_8; the TDM config
  copied under ffa/ as mode 8 (rules 93/91/94, 30 kills) on the copy, a maps_dict row; 22 solo spawns
  (school-fort-v021.tsv, check-points' `ported`, the footprint of native level_02/05's own Free for
  All points: the same layout) with 20 m enemy exclusion and 500 ms protection; the copy's ammo
  crates out (the breakable lamps' indices after them follow).
"""
import argparse
import csv
import json
from pathlib import Path

import make_edits as base
import make_no_crates_edits as crates

HERE = Path(__file__).resolve().parent
POINTS = HERE / 'school-fort-v021.tsv'
OUTPUT = HERE.parent / 'content-edit/v021d-school-fort-modes-1.json'
MAPS = ['v021d_level_02', 'v021d_level_05']
RADIUS = 20.0
PROTECTION_MS = 500


def ids(text):
    out = dict(item.split('=') for item in text.split(','))
    if set(out) != set(MAPS):
        raise argparse.ArgumentTypeError(f'give an id for each of {MAPS}')
    return {name: int(v) for name, v in out.items()}


def authored():
    by = {}
    with POINTS.open(newline='') as stream:
        for row in csv.DictReader(stream, delimiter='\t'):
            if row['verdict'] != 'kept':
                raise ValueError(f'{POINTS.name}: an unchecked point')
            by.setdefault(row['project'], []).append(row)
    if set(by) != {name + '/day_4' for name in MAPS} or any(len(r) != 22 for r in by.values()):
        raise ValueError(f'{POINTS.name}: 22 points for each of {MAPS}')
    return by


def edits(live, blackout, ffa):
    def read(path):
        return (live / path).read_bytes()
    dictionary = base.tree(read(base.DICTIONARY))['maps_dict']
    taken = {e['id'] for e in dictionary}
    wanted = list(blackout.values()) + list(ffa.values())
    if len(set(wanted)) != len(wanted) or taken & set(wanted) or not all(0 < i < 255 for i in wanted):
        raise ValueError(f'ids {wanted}: each its own, a byte below 255 (none), none of a live row')
    points = authored()
    out = {'_about': (
        'Blackout and Free for All on School and Tarakanovsky Fort v0.21 (maps-021d-school-fort@4), as Vostok and '
        'Mamayev Kurgan v0.21 have them: Blackout as blackout-mode-1 (each battery config under blackout/, '
        f'srp_variant blackout, st_srp_mode_blackout; maps_dict {", ".join(f"{m} {blackout[m]}" for m in MAPS)}); Free '
        'for All as ffa-projects-1, ffa-ported-1, no-ammo-crates-1, ffa-radius-1 and ffa-protection-ms-1 made it '
        'for the other ports (the TDM project copied to day_8, the TDM config under ffa/ as mode 8 on the copy; '
        f'maps_dict {", ".join(f"{m} {ffa[m]}" for m in MAPS)}; 22 solo spawns each by check-points\' ported, '
        f'{RADIUS:g} m enemy exclusion, {PROTECTION_MS} ms protection; the copy without its ammo crates). The last '
        'list of the manifest; generated by scripts/ffa-mode/make_school_fort_modes.py.'),
        'copy': [], 'set': [], 'replace_string': [], 'remove_item': [], 'add_entry': [], 'append_entry': [],
        'add_value': [], 'remove_entry': []}
    held = json.loads((HERE.parent / 'content-edit/stalker-tdm-hold-1.json').read_text())['remove_entry']
    count = len(dictionary) + sum(1 for e in held if e['list'] == 'maps_dict')

    def row(cfg, map_id):
        nonlocal count
        out['append_entry'].append({'file': base.DICTIONARY, 'list': 'maps_dict', 'expected_count': count,
                                    'unique_key': 'id', 'value': {'cfg_mode_name': cfg, 'id': map_id}})
        count += 1

    for name in MAPS:   # Blackout
        src = f'{base.MODES}{name}_day_2.options'
        dst = f'{base.MODES}blackout/{name}_day_2.options'
        if base.tree(read(src))['mode']['mode'] != 2:
            raise ValueError(f'{src}: not a battery config')
        out['copy'].append({'files': src, 'from': base.MODES, 'to': base.MODES + 'blackout/'})
        out['replace_string'].append({'files': dst, 'from': 'st_mode_02_name', 'to': 'st_srp_mode_blackout'})
        out['add_value'].append({'files': [dst], 'table': 'mode', 'key': 'srp_variant', 'value': 'blackout'})
        row(dst[len(base.MODES):], blackout[name])
    for name in MAPS:   # Free for All
        src = f'{base.MODES}{name}_day_4.options'
        dst = f'{base.MODES}ffa/{name}_day_8.options'
        tdm = f'projects/{name}/day_4/client_project'
        copy = base.copy_of(tdm)
        mode = base.tree(read(src))['mode']
        if mode['mode'] != 4 or mode['rules'] != base.RULES or mode['match_making_params']['map_name'] != name + '/day_4':
            raise ValueError(f'{src}: unexpected TDM config')
        out['copy'].append({'files': tdm, 'from': tdm.removesuffix('client_project'),
                            'to': copy.removesuffix('client_project')})
        out['copy'].append({'files': src, 'from': src, 'to': dst})
        out['set'].append({'file': dst, 'path': 'mode/mode', 'from': 4, 'to': 8})
        if mode['ui']['icon'] != base.ICON:
            out['set'].append({'file': dst, 'path': 'mode/ui/icon', 'from': mode['ui']['icon'], 'to': base.ICON})
        out['replace_string'].append({'files': dst, 'from': mode['name'], 'to': mode['name'][:-1] + '8'})
        for key, pattern in base.TEXTS.items():
            out['replace_string'].append({'files': dst, 'from': pattern.format(4), 'to': pattern.format(8)})
        out['replace_string'].append({'files': dst, 'from': name + '/day_4', 'to': name + '/day_8'})
        out['remove_item'].append({'file': dst, 'path': 'mode/rules', 'value': 90})
        for table, key, value in base.ADDED:
            out['add_value'].append({'files': [dst], 'table': table, 'key': key, 'value': value})
        row(dst[len(base.MODES):], ffa[name])
        tree = base.tree(read(tdm))
        entries = tree['server_objects']['respawn_points']
        if [e['point_id'] for e in entries] != list(range(len(entries))) or any(e['team'] not in (0, 1) for e in entries):
            raise ValueError(f'{tdm}: unexpected spawn ids or sides')
        model = entries[0]
        for i, p in enumerate(points[name + '/day_4']):
            point_id = len(entries) + i
            point_name = 'ffa_' + p['point']
            values = {'name': point_name, 'full_name': 'logic/modes/ffa/respawn/' + point_name,
                      'point_id': point_id, 'team': 2, 'priority': 1, 'is_temporary': False,
                      'position': [float(p[k]) for k in ('x', 'y', 'z')],
                      'rotation': [float(p[k]) for k in ('rx', 'ry', 'rz')], 'invulnerability_time': 0}
            at = f'{base.POINTS}[{point_id}]'
            extra = [('enemy_check_radius', RADIUS), ('ally_check_radius', base.ALLY_CHECK_RADIUS)]
            for key, value in extra:
                if key in model:
                    values[key] = value
                else:
                    out['add_value'].append({'files': [copy], 'table': at, 'key': key, 'value': value})
            out['add_value'].append({'files': [copy], 'table': at, 'key': 'invulnerability_time_ms', 'value': PROTECTION_MS})
            out['add_entry'].append({'files': copy, 'list': base.POINTS, 'after': {'point_id': point_id - 1},
                                     'like': {'point_id': 0}, 'values': values})
            for zone in ('ally_zones', 'enemy_zones'):
                for shape in model[zone]['collision_geometries']:
                    out['remove_entry'].append({'file': copy, 'list': at + '/' + zone + '/collision_geometries',
                                                'where': {'name': shape['name']}})
        # The copy without its ammo crates (no-ammo-crates-1's rule; the copy is the TDM project's bytes).
        found, models = crates.crates(tree, tdm)
        if not found:
            raise ValueError(f'{tdm}: no ammo crate')
        for _, inside in found:
            for o in inside:
                out['remove_entry'].append({'file': copy, 'list': 'client_objects',
                                            'where': {'game_object_type': o['game_object_type'], 'full_name': o['full_name']}})
        removed = sorted(i for i, _ in models)
        for lamp, lamp_row in tree.get('srp_lamps', {}).get('lamps', {}).items():
            for key, visual in lamp_row['visuals'].items():
                index = visual['index']
                if index in removed:
                    raise ValueError(f'{tdm}: lamp {lamp} {key} is a crate\'s model')
                below = sum(i < index for i in removed)
                if below:
                    out['set'].append({'file': copy, 'path': f'srp_lamps/lamps/{lamp}/visuals/{key}/index',
                                       'from': index, 'to': index - below})
        import math
        for _, v in models:
            out['remove_entry'].append({'file': copy, 'list': 'render_visuals',
                                        'where': {'lib_name': v['lib_name'], 'position': crates.at(v['position'])}})
            prefix = f'resources/models/{v["lib_name"]}.model/'
            for c in tree['collision_objects']:
                if c['lib_name'].startswith(prefix) and math.dist(c['position'], v['position']) < 0.0005:
                    out['remove_entry'].append({'file': copy, 'list': 'collision_objects',
                                                'where': {'lib_name': c['lib_name'], 'position': crates.at(c['position'])}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--live', type=Path, required=True)
    parser.add_argument('--blackout', type=ids, required=True)
    parser.add_argument('--ffa', type=ids, required=True)
    parser.add_argument('--out', type=Path, default=OUTPUT)
    args = parser.parse_args()
    base.write(edits(args.live, args.blackout, args.ffa), args.out)
    print(args.out)


if __name__ == '__main__':
    main()
