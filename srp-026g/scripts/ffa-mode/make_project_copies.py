#!/usr/bin/env python3
"""Writes content-edit/ffa-projects-1.json: each Free for All map's own project, a copy of its Team
Deathmatch project (`projects/<map>/<weather>_4/` -> `<weather>_8/`, make_edits.copy_of) as every row
above leaves it (the owner, 2026-11-13: "TDM is good, nothing should change about it"), as Research
got its own project of Vostok v0.11 (v011e-vostok-modes-1.json).

Its row goes right before ffa-1.json, after every TDM retune. The FFA lists (LISTS) then edit the
copies only, and no-ammo-crates-1 points the FFA configs at them and takes their crates out; TDM's
projects stay exactly as they would be without Free for All. The projects copied are every one the
FFA lists edit, read from those lists.

    python3 make_project_copies.py
"""
import json
import re

import make_edits as base

OUTPUT = base.HERE.parent / 'content-edit/ffa-projects-1.json'
LISTS = ['ffa-1.json', 'ffa-ported-1.json', 'ffa-london-center-1.json', 'ffa-radius-1.json',
         'ffa-stalker-1.json', 'ffa-stalker-radius-1.json', 'ffa-stalker-2.json', 'training-camp-arena-1.json']


def copies():
    """{the copy: its TDM project} of every project the FFA lists edit."""
    out = {}
    for name in LISTS:
        text = (base.HERE.parent / 'content-edit' / name).read_text()
        for path in set(re.findall(r'projects/[^"]+/client_project', text)):
            tdm = re.sub(rf'_{base.FFA}/client_project$', f'_{base.TDM}/client_project', path)
            if base.copy_of(tdm) != path:
                raise ValueError(f'{name}: {path} is not a free-for-all copy of a TDM project')
            out[path] = tdm
    return dict(sorted(out.items()))


def folder(path):
    """`projects/<map>/<weather>_<n>/` of its client_project."""
    return path.removesuffix('client_project')


def edits():
    pairs = copies()
    return {'_about': (
        'Each Free for All map\'s own project (the owner, 2026-11-13: "TDM is good, nothing should change '
        'about it"): a copy of its Team Deathmatch project as every row above leaves it, '
        f'projects/<map>/<weather>_{base.TDM}/ -> <weather>_{base.FFA}/, {len(pairs)} projects: every one the '
        'FFA lists edit. Before ffa-1.json, after every TDM retune; the FFA lists edit the copies, '
        'no-ammo-crates-1 points the FFA configs at them. Generated by scripts/ffa-mode/make_project_copies.py.'),
        # As Research's own project of Vostok v0.11 (v011e-vostok-modes-1.json): the folder from and to.
        'copy': [{'files': tdm, 'from': folder(tdm), 'to': folder(copy)} for copy, tdm in pairs.items()]}


def main():
    base.write(edits(), OUTPUT)
    print(OUTPUT)


if __name__ == '__main__':
    main()
