#!/usr/bin/env python3
"""Move half of each FFA map's perimeter spawns to its centre (the owner, 2026-11-13: "I would
remove half spawns on perimeter", "almost on all maps", "and put them in the center").

center.tsv is the reviewed output of check-points' to_center binary (its doc says the rule): one row
a moved spawn, `point` its point id, the new position and yaw. Run on the projects as players have
them (the stock db, every patch of release/patches.tsv and what the manifest makes over them):

  cd check-points && cargo run --release --bin to_center -- --db <resources.db> \\
      --patch <resources.db.patch_12> ... --plots <folder> \\
      --project level_01/day_8 ... \\
      --project v010b_cs_mp_bath/day_8@-48.13,-22.87,34.12,53.13 \\
      --project v010b_cs_mp_military_1/day_8@-127.47,-71.12,115.78,95.38 > ../center.tsv

(the STALKER maps with their reviewed play area, scripts/stalker-maps/ffa-points). Then

  python3 make_center_edits.py --live <folder>

with the projects (center.tsv's) at their game paths as the rows above the list leave them, writes
../content-edit/ffa-center-1.json: each moved spawn, matched by its point id, name and team 2, gets
the new position and rotation [0, yaw, 0]; its id, name, radii and protection stay. Only the free
for all's own projects (`<weather>_8`) are edited; Team Deathmatch's are never named.
"""
import argparse
import csv
import math
from pathlib import Path

import make_edits as base

POINTS_TSV = base.HERE / 'center.tsv'
OUTPUT = base.HERE.parent / 'content-edit/ffa-center-1.json'
SPACING = 12.


def path_of(project):
    level, weather = project.split('/')
    if not weather.endswith(f'_{base.FFA}'):
        raise ValueError(f'{project}: not a free for all project')
    return f'projects/{project}/client_project'


def moved():
    """center.tsv's rows by project: {point id: (position, yaw)}."""
    with POINTS_TSV.open(newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    out = {}
    for row in rows:
        if row['verdict'] != 'moved':
            raise ValueError(f'{row["project"]} {row["point"]}: not a checked move')
        values = [float(row[k]) for k in ('x', 'y', 'z', 'ry')]
        if not all(math.isfinite(v) for v in values):
            raise ValueError(f'{row["project"]} {row["point"]}: not finite')
        points = out.setdefault(path_of(row['project']), {})
        point = int(row['point'])
        if point in points:
            raise ValueError(f'{row["project"]}: point {point} moved twice')
        points[point] = (values[:3], values[3])
    return out


def edits(live):
    out = {'_about': 'Half of each Free for All map\'s perimeter spawns moved to its centre (the owner, '
           '2026-11-13). Generated by scripts/ffa-mode/make_center_edits.py from center.tsv '
           '(check-points to_center). Each moved team-2 spawn keeps its id, name, radii and protection; '
           'only its position and rotation change. The free for all\'s own projects only; after the FFA '
           'spawn lists.', 'set_entry': []}
    for path, points in moved().items():
        entries = base.tree((live / path).read_bytes())['server_objects']['respawn_points']
        solo = {e['point_id']: e for e in entries if e['team'] == 2}
        missing = set(points) - set(solo)
        if missing:
            raise ValueError(f'{path}: no solo spawn {sorted(missing)}')
        after = {i: (points[i][0] if i in points else list(e['position'])) for i, e in solo.items()}
        for i in points:
            near = min(math.dist((after[i][0], after[i][2]), (p[0], p[2])) for j, p in after.items() if j != i)
            if near < SPACING - 0.001:
                raise ValueError(f'{path}: moved point {i} is {near:.2f} m from another solo spawn')
        for i in sorted(points):
            entry = solo[i]
            position, yaw = points[i]
            out['set_entry'].append({'file': path, 'list': base.POINTS,
                'where': {k: entry[k] for k in ('point_id', 'name', 'team')},
                'from': {'position': [round(v, 6) for v in entry['position']],
                         'rotation': [round(v, 6) for v in entry['rotation']]},
                'to': {'position': position, 'rotation': [0., yaw, 0.]}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    base.write(edits(args.live), OUTPUT)
    print(OUTPUT)


if __name__ == '__main__':
    main()
