#!/usr/bin/env python3
"""Free for All spawns by the spawn rule on every map but Rudnya and Training Camp (the owner,
2026-11-14: "there should be a rule that spawns are inside buildings or close to two walls or some
cover", "and none at the perimeter"; docs/notes/ffa.md, "Cover").

cover-maps.tsv is the reviewed output of check-points' to_cover binary (its doc says how a spawn is
kept, turned or replaced): one row a changed spawn, `point` its point id, `verdict` `replaced` (a new
position and yaw) or `turned` (its place kept, a new yaw). Run on the projects as players would have
them (the stock db, every patch of release/patches.tsv and a build of the manifest's rows above this
list's over them):

  cd check-points && cargo run --release --bin to_cover -- --db <resources.db> \\
      --patch <resources.db.patch_12> ... --patch <the build's patch> --plots <folder> \\
      --project level_02/day_8 ... --project level_09/day_8 --below level_09/day_8=14.5 \\
      --project v010b_cs_mp_bath/day_8@-48.13,-22.87,34.12,53.13 \\
      --project v010b_cs_mp_military_1/day_8@-127.47,-71.12,115.78,95.38 > ../cover-maps.tsv

(the STALKER maps with their reviewed play area, as make_center_edits.py; none of London's above its
rotunda's second storey). Then

  python3 make_cover_edits.py --live <folder>

with the projects at their game paths as the rows above the list leave them, writes
../content-edit/ffa-cover-maps-1.json: each changed spawn, matched by its point id, name and team 2,
gets the new position and rotation [0, yaw, 0] (a turned one the rotation only); its id, name, radii
and protection stay, and no spawn is added or removed. No distance between spawns is kept (the owner,
2026-11-14: "spawns can be as close as possible": the respawn's 20 m enemy exclusion keeps players
apart). Only the free for all's own projects (`<weather>_8`) are edited; Team Deathmatch's are never
named.
"""
import argparse
import csv
import math
from pathlib import Path

import make_center_edits as center
import make_edits as base

POINTS_TSV = base.HERE / 'cover-maps.tsv'
OUTPUT = base.HERE.parent / 'content-edit/ffa-cover-maps-1.json'
VERDICTS = ('replaced', 'turned')
# Maps this list leaves to others: Rudnya (its own redo from the owner's picks) and Training Camp (its
# own arena, docs/notes/stalker-ffa.md).
NOT_HERE = ('projects/level_01/', 'projects/v010b_cs_training_camp/')


def changed():
    """cover-maps.tsv's rows by project: {point id: (verdict, position, yaw)}."""
    with POINTS_TSV.open(newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    out = {}
    for row in rows:
        if row['verdict'] not in VERDICTS:
            raise ValueError(f'{row["project"]} {row["point"]}: not a checked change')
        values = [float(row[k]) for k in ('x', 'y', 'z', 'ry')]
        if not all(math.isfinite(v) for v in values):
            raise ValueError(f'{row["project"]} {row["point"]}: not finite')
        path = center.path_of(row['project'])
        if path.startswith(NOT_HERE):
            raise ValueError(f'{row["project"]}: not this list\'s map')
        points = out.setdefault(path, {})
        point = int(row['point'])
        if point in points:
            raise ValueError(f'{row["project"]}: point {point} changed twice')
        points[point] = (row['verdict'], values[:3], values[3])
    return out


def edits(live):
    out = {'_about': 'Free for All spawns by the spawn rule (the owner, 2026-11-14: "there should be a rule '
           'that spawns are inside buildings or close to two walls or some cover", "and none at the perimeter"): '
           'on every map but Rudnya and Training Camp, each team-2 spawn that fails the rule (cover, past the '
           'perimeter band) or the spawn checks (standing floor, body clear, harmful zones 2 m away) moves to a '
           'place that passes them, chosen so the inner area has places to spawn everywhere; one that passes '
           'but faces a wall is turned. No distance between spawns is kept ("spawns can be as close as '
           'possible"). Generated by scripts/ffa-mode/make_cover_edits.py from cover-maps.tsv (check-points '
           'to_cover). Each changed spawn keeps its id, name, radii and protection; only its position and '
           'rotation change. The free for all\'s own projects only; after every Free for All spawn list.',
           'set_entry': []}
    for path, points in changed().items():
        entries = base.tree((live / path).read_bytes())['server_objects']['respawn_points']
        solo = {e['point_id']: e for e in entries if e['team'] == 2}
        missing = set(points) - set(solo)
        if missing:
            raise ValueError(f'{path}: no solo spawn {sorted(missing)}')
        for i in sorted(points):
            entry = solo[i]
            verdict, position, yaw = points[i]
            keys = ('position', 'rotation') if verdict == 'replaced' else ('rotation',)
            to = {'position': position, 'rotation': [0., yaw, 0.]}
            out['set_entry'].append({'file': path, 'list': base.POINTS,
                'where': {k: entry[k] for k in ('point_id', 'name', 'team')},
                'from': {k: [round(v, 6) for v in entry[k]] for k in keys},
                'to': {k: to[k] for k in keys}})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--live', type=Path, required=True)
    args = parser.parse_args()
    base.write(edits(args.live), OUTPUT)
    print(OUTPUT)


if __name__ == '__main__':
    main()
