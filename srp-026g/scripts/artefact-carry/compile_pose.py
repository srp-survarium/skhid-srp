#!/usr/bin/env python3
"""Compile the authored carry hand curves for the draw-time skeletal layer.

The resource clips and this layer share the same pinned source and pose edit.
The runtime layer keeps native locomotion and camera bones, overriding arms
and fingers only. --check refuses a stale generated Rust file.
"""
import argparse
import json
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'content-edit'))
import content_edit as content

OUTPUT = HERE.parents[1] / 'client-patches/rust/patches/src/artefact_carry/curves.rs'

def compile_curves(source, names):
    spec = json.loads((HERE.parent / 'content-edit/artefact-carry-pose-1.json').read_text())['make_pose_clip'][0]
    # This validates hashes, rig, full-pose kind and every authored track.
    clip = content.make_pose_clip(source, names, spec)
    rig = [content.name_at(names, content.rec(names, at)[0]).decode()
           for at in content.children(names, content.find(names, 'bones_names'))]
    data = content.clip_parse(clip)[2]
    tracks, offset = {}, 0
    for name in rig:
        values = []
        for _ in range(9):
            count = struct.unpack_from('<I', data, offset)[0]
            values.append(struct.unpack_from('<f', data, offset + 8)[0])
            offset += 4 + count * 8
        tracks[name] = values[3:6]
    chosen = list(dict.fromkeys(list(spec['start']) + [n for n in rig if any(f in n for f in ('Thumb', 'Index', 'Middle', 'Ring', 'Pinky'))]))
    out = ['// Generated by scripts/artefact-carry/compile_pose.py; edit the pose source.',
           'pub const CURVES: &[(&str, [f32; 3], [f32; 3])] = &[']
    def xyz(v):
        def number(x):
            text = format(x, '.6f').rstrip('0').rstrip('.')
            return text if '.' in text else text + '.0'
        return '[' + ', '.join(number(x) for x in v) + ']'
    for name in chosen:
        a = spec['start'].get(name, tracks[name])
        b = spec['end'].get(name, tracks[name])
        out.append(f'    ("{name}", {xyz(a)}, {xyz(b)}),')
    return '\n'.join(out + ['];', ''])

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--clip', required=True, type=Path)
    p.add_argument('--names', required=True, type=Path)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    text = compile_curves(a.clip.read_bytes(), a.names.read_bytes())
    if a.check:
        if OUTPUT.read_text() != text: p.error('stale carry curves; regenerate without --check')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text)
    print('carry curves: ' + ('checked' if a.check else 'written'))

if __name__ == '__main__': main()
