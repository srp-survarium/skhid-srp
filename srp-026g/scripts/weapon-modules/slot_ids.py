#!/usr/bin/env python3
"""0.69d0's weapon slot ids as the weapon-modules crate's closed enum.

    python slot_ids.py <game.options leaves> [--write]

The input is 0.69d0's `game.options` as the porter prints it
(`vostok-port dump-config --leaves`): one `key<TAB>type:value` line a leaf.
A slot id is every `weapons.<gun>.slots[].id`, every module's
`slots_to_attach_to[].slot` and every `slots_to_add[].id`.

The numbers are the table format's (`crates/weapon-modules`, a slot is one
byte), so they never change: an id the file already has keeps its number, a
new one is appended. Without --write the script only says whether
`src/slot_ids.rs` is current.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "crates/weapon-modules/src/slot_ids.rs"
SLOT = re.compile(
    r"^(?:weapons\.[^.]+\.slots\[\d+\]\.id"
    r"|weapon_modules\.[^.]+\.slots_to_attach_to\[\d+\]\.slot"
    r"|weapon_modules\.[^.]+\.(?:exceptions\.[^.]+\.)?slots_to_attach_to\[\d+\]\.slot"
    r"|weapon_modules\.[^.]+\.attach_params(?:_\d+)?\.slots_to_add\[\d+\]\.id)\tstring:\"([^\"]+)\"$"
)
ROW = re.compile(r'^    (\w+) = (\d+), "([^"]+)";$')


def variant(name: str) -> str:
    camel = "".join(part[:1].upper() + part[1:] for part in name.split("_"))
    return "NoneSlot" if camel == "None" else camel


def found(leaves: Path) -> set[str]:
    with leaves.open(encoding="utf-8", errors="replace") as lines:
        return {m.group(1) for line in lines if (m := SLOT.match(line.rstrip("\n")))}


def kept() -> list[str]:
    if not OUT.is_file():
        return []
    rows = [m for line in OUT.read_text().splitlines() if (m := ROW.match(line))]
    assert [int(m.group(2)) for m in rows] == list(range(len(rows))), "slot_ids.rs: numbers out of order"
    return [m.group(3) for m in rows]


def render(names: list[str]) -> str:
    assert len(names) <= 256 and len({variant(n) for n in names}) == len(names)
    rows = "".join(f'    {variant(name)} = {number}, "{name}";\n' for number, name in enumerate(names))
    return (
        "// Generated by scripts/weapon-modules/slot_ids.py from 0.69d0's game.options:\n"
        "// every slot id its guns and modules name. A number is the table format's and\n"
        "// never changes; a new id is appended. Do not edit by hand.\n"
        "slot_ids! {\n" + rows + "}\n"
    )


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--write"]
    if len(args) != 1:
        print(__doc__)
        return 2
    old = kept()
    names = old + sorted(found(Path(args[0])) - set(old))
    gone = sorted(set(old) - found(Path(args[0])))
    if gone:
        print("kept though the input no longer has them:", ", ".join(gone))
    text = render(names)
    if "--write" in sys.argv:
        OUT.write_text(text)
        print(f"{OUT}: {len(names)} slot ids ({len(names) - len(old)} new)")
        return 0
    current = OUT.is_file() and OUT.read_text() == text
    print(f"{len(names)} slot ids; {OUT.name} is {'current' if current else 'STALE'}")
    return 0 if current else 1


if __name__ == "__main__":
    sys.exit(main())
