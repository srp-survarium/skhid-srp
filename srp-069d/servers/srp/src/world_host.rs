//! The world host daemon (`servers/world-host`, `world-host daemon --config FILE`) as srp runs it.
//!
//! * The daemon config is generated from the settings ([`daemon_config`]): socket, exe, limits, pre-warm lists. It names
//!   no project: the daemon serves the projects of the game data (every PvP row whose level ships in the client and the
//!   PvE mazes, `GameData::host_projects`), and srp asks the daemon for that list ([`fetch_projects`]): one place.
//! * [`start`]: a daemon that already answers on the socket is used as it is; otherwise srp starts one (when
//!   `world_host.exe` is set), writes its output to `<log_dir>/world-host.log` and stops it when srp exits (the child
//!   gets SIGTERM when srp's main thread ends, even on a crash).
//! * [`run_foreground`]: `srp world-host`, the daemon alone in the foreground (the same generated config).

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

use crate::{Config, DaemonSettings};

/// How long a freshly started daemon may take to answer on its socket.
pub const START_WAIT: Duration = Duration::from_secs(30);

/// The world host binary of a daemon setting: `bin`, else `world-host` (or `srp-world-host`) next to the srp binary.
pub fn binary(d: &DaemonSettings) -> Result<PathBuf, String> {
    if let Some(b) = &d.bin {
        return Ok(b.clone());
    }
    let me = std::env::current_exe().map_err(|e| format!("own path: {e}"))?;
    let dir = me.parent().map(Path::to_path_buf).unwrap_or_default();
    ["world-host", "srp-world-host"]
        .iter()
        .map(|n| dir.join(n))
        .find(|p| p.is_file())
        .ok_or_else(|| format!("no world host binary next to {} (build it: cargo build --release -p world-host; or set world_host.bin)", me.display()))
}

/// The pre-warm folder: the setting, else `prewarm` in the game table folder. The world host writes a project's list
/// there after the project's first match (the resources a match creation asks for), so later zygotes load them ahead.
pub fn prewarm_dir(c: &Config, d: &DaemonSettings) -> Option<PathBuf> {
    d.prewarm_dir.clone().or_else(|| c.data_dir.as_ref().map(|dd| dd.join("prewarm")))
}

/// The daemon's config file text (world-host `DaemonCfg`): no `[project]` section, the daemon takes the data's projects.
pub fn daemon_config(c: &Config, d: &DaemonSettings, prewarm: Option<&Path>) -> String {
    let mut t = String::from("# generated by srp from its config file at every start: edit srp.toml, not this file\n");
    let mut kv = |k: &str, v: String| t.push_str(&format!("{k} = {v}\n"));
    kv("socket", c.world_host.socket.display().to_string());
    kv("exe", d.exe.display().to_string());
    kv("exe_win", d.exe_win.clone());
    kv("out", c.log_dir.join("world-host").display().to_string());
    kv("max_matches", d.max_matches.to_string());
    kv("max_zygotes", d.max_zygotes.to_string());
    kv("idle_secs", d.idle_secs.to_string());
    if let Some(p) = prewarm {
        kv("prewarm_dir", p.display().to_string());
    }
    if !d.prestart.is_empty() {
        kv("prestart", d.prestart.join(", "));
    }
    if let Some(dd) = &c.data_dir {
        kv("data_dir", dd.display().to_string());
    }
    t
}

/// The daemon's project list, or why there is none.
#[cfg(unix)]
pub fn projects(socket: &Path, timeout: Duration) -> Result<Vec<String>, String> {
    match_server::query_projects(&match_server::HostConfig::unix(socket), timeout).map_err(|e| e.to_string())
}

#[cfg(not(unix))]
pub fn projects(_socket: &Path, _timeout: Duration) -> Result<Vec<String>, String> {
    Err("the world host needs a unix socket (Linux / WSL2)".into())
}

/// Ask the daemon for its projects until it answers (every 5 s), then hand them to the PvP queue. Until then every row
/// of the data counts as served.
pub fn fetch_projects(socket: &Path, online: &crate::online::Online) {
    let mut warned = false;
    loop {
        match projects(socket, Duration::from_secs(5)) {
            Ok(p) => {
                log::info!("the world host serves {} project(s): {}", p.len(), p.join(", "));
                online.set_host_projects(p);
                return;
            }
            Err(e) => {
                if !warned {
                    log::warn!("the world host at {} does not list its projects yet ({e}); asking again every 5 s, online starts are refused until it answers", socket.display());
                    warned = true;
                }
                std::thread::sleep(Duration::from_secs(5));
            }
        }
    }
}

/// A daemon srp started: SIGTERM'd and reaped when dropped.
pub struct Daemon {
    child: Child,
}

impl Daemon {
    pub fn pid(&self) -> u32 {
        self.child.id()
    }
}

impl Drop for Daemon {
    fn drop(&mut self) {
        log::info!("stopping the world host (pid {})", self.child.id());
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

/// Write the generated daemon config into the run folder and build the daemon's command.
fn command(c: &Config, d: &DaemonSettings) -> Result<(Command, PathBuf), String> {
    let bin = binary(d)?;
    if !bin.is_file() {
        return Err(format!("world_host.bin {} does not exist", bin.display()));
    }
    if !d.exe.is_file() {
        return Err(format!("world_host.exe {} does not exist", d.exe.display()));
    }
    crate::setup::check_exe(&d.exe)?;
    let prewarm = prewarm_dir(c, d);
    if let Some(p) = &prewarm {
        std::fs::create_dir_all(p).map_err(|e| format!("{}: {e}", p.display()))?;
    } else {
        log::warn!("no pre-warm folder (world_host.prewarm_dir): every match loads its shared resources itself");
    }
    for dir in [&c.run_dir, &c.log_dir] {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    if let Some(parent) = c.world_host.socket.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    let cfg = c.run_dir.join("daemon.cfg");
    std::fs::write(&cfg, daemon_config(c, d, prewarm.as_deref())).map_err(|e| format!("{}: {e}", cfg.display()))?;
    let mut cmd = Command::new(&bin);
    cmd.arg("daemon").arg("--config").arg(&cfg).current_dir(&c.run_dir);
    Ok((cmd, cfg))
}

/// Make sure a world host answers on the socket: use a running one, else start one from the settings. None = srp did
/// not start one (one was running, or no `world_host.exe` is set: then a warning, online starts are refused until a
/// daemon answers).
pub fn start(c: &Config) -> Result<Option<Daemon>, String> {
    let socket = &c.world_host.socket;
    if let Ok(p) = projects(socket, Duration::from_secs(3)) {
        log::info!("using the world host already running on {} ({} projects)", socket.display(), p.len());
        return Ok(None);
    }
    let Some(d) = &c.world_host.daemon else {
        log::warn!("no world host answers on {} and world_host.exe is not set: online matches need one", socket.display());
        return Ok(None);
    };
    if !cfg!(unix) {
        return Err("the world host runs on Linux (or WSL2) only".into());
    }
    let (mut cmd, cfg) = command(c, d)?;
    let log_path = c.log_dir.join("world-host.log");
    let log = std::fs::OpenOptions::new().create(true).append(true).open(&log_path).map_err(|e| format!("{}: {e}", log_path.display()))?;
    let err = log.try_clone().map_err(|e| e.to_string())?;
    cmd.stdin(Stdio::null()).stdout(log).stderr(err);
    die_with_parent(&mut cmd);
    let child = cmd.spawn().map_err(|e| format!("world host: {e}"))?;
    let daemon = Daemon { child };
    log::info!("started the world host (pid {}, config {}, output {})", daemon.pid(), cfg.display(), log_path.display());
    let t0 = Instant::now();
    loop {
        if projects(socket, Duration::from_secs(2)).is_ok() {
            log::info!("the world host answers on {} after {:.1} s", socket.display(), t0.elapsed().as_secs_f32());
            return Ok(Some(daemon));
        }
        if t0.elapsed() > START_WAIT {
            return Err(format!("the world host did not answer on {} within {START_WAIT:?}; see {}", socket.display(), log_path.display()));
        }
        std::thread::sleep(Duration::from_millis(250));
    }
}

/// `srp world-host`: the daemon alone, in the foreground (output on this terminal). Returns its exit code.
pub fn run_foreground(c: &Config) -> Result<i32, String> {
    let d = c.world_host.daemon.as_ref().ok_or("world_host.exe is not set")?;
    let (mut cmd, cfg) = command(c, d)?;
    log::info!("world host: {} daemon --config {}", cmd.get_program().to_string_lossy(), cfg.display());
    let st = cmd.status().map_err(|e| format!("world host: {e}"))?;
    Ok(st.code().unwrap_or(1))
}

/// How long the self-test waits for the start world (a cold level loads in about 8 s on a fast PC).
pub const SELFTEST_WAIT: Duration = Duration::from_secs(180);

/// `srp selftest [project]`: start a world host of its own (socket, run and log folders under `selftest/`, so a running
/// server is not touched), ask it for its projects and have it build the start world of one PvP project (the first one
/// it serves, or `project`), the way the match server asks for every online match. Then a few seconds of a bot match on
/// the same project ([`bot_match`]): the world host's AI drives the AI players and their inputs come back in the DFs.
/// Prints OK or the failing part. Returns the exit code (0 = OK).
#[cfg(unix)]
pub fn selftest(c: &Config, project: Option<&str>) -> i32 {
    use std::io::Write;
    use world_host_proto::{read_frame, Create, FromHost, Record, ToHost, KIND_PVP, PROTO_VERSION};
    let fail = |part: &str, e: String| {
        println!("FAILED   {part}: {e}");
        2
    };
    println!("srp selftest: start a world host, build one start world and play {BOT_MATCH_SECS} s of a bot match (about 10-60 s)");
    let Some(d) = &c.world_host.daemon else {
        return fail("world host", "world_host.exe is not set: run srp setup first".into());
    };
    let mut t = c.clone();
    t.run_dir = c.run_dir.join("selftest");
    t.log_dir = c.log_dir.join("selftest");
    t.world_host.socket = t.run_dir.join("world-host.sock");
    let mut td = d.clone();
    td.prestart.clear();
    td.max_zygotes = 1;
    t.world_host.daemon = Some(td);
    let _ = std::fs::remove_file(&t.world_host.socket);
    let t0 = Instant::now();
    let daemon = match start(&t) {
        Ok(d) => d,
        Err(e) => return fail("world host start", e),
    };
    println!("ok       world host started in {:.1} s (output {})", t0.elapsed().as_secs_f32(), t.log_dir.join("world-host.log").display());
    let served = match projects(&t.world_host.socket, Duration::from_secs(10)) {
        Ok(p) => p,
        Err(e) => return fail("project list", e),
    };
    println!("ok       the world host serves {} project(s)", served.len());
    let gd = match crate::load_tables(c) {
        Ok(g) => g,
        Err(e) => return fail("game data", e),
    };
    let row = gd.matches.modes().iter().find(|r| match project {
        Some(p) => r.project == p,
        // a PvP project with AI players (the gun race has none)
        None => served.contains(&r.project) && !r.project.starts_with("pve") && r.mode != game_data::gunrace::MODE,
    });
    let Some(row) = row else {
        return fail("project", format!("no PvP data row for {} among the served projects", project.unwrap_or("any")));
    };
    let match_id = 0x5E1F_7E57;
    let tick = local_match::options::TICK_MS as u8;
    let p = local_match::OnlineParams {
        map: row.map,
        mode: row.mode,
        weather: row.variation,
        match_id,
        tick_ms: tick,
        send_period_ms: local_match::options::SEND_PERIOD_MS,
        match_type: local_match::options::MATCH_TYPE_PLAIN,
        max_delay_ms: local_match::options::max_delay_ms(tick),
    };
    let human = local_match::OnlinePlayer { team: 0, human: local_match::HumanLoadout::default_loadout(), hero: None, pve_budget: (0, 0) };
    let options = match local_match::online_options_row(&gd, &p, row, &[human], &[]) {
        Ok(o) => o,
        Err(e) => return fail("match options", e.to_string()),
    };
    let create = Create {
        version: PROTO_VERSION,
        match_id,
        kind: KIND_PVP,
        project: row.project.clone(),
        map: row.map,
        mode: row.mode,
        tick_ms: tick,
        records: vec![Record { bot: false, team: 0 }],
        options,
        world: Vec::new(),
        drive_bots: false,
        ai_ignore_players: false,
    };
    let t1 = Instant::now();
    let result = (|| -> Result<String, String> {
        let mut s = std::os::unix::net::UnixStream::connect(&t.world_host.socket).map_err(|e| format!("connect: {e}"))?;
        s.set_read_timeout(Some(SELFTEST_WAIT)).ok();
        s.write_all(&ToHost::Create(create).frame().map_err(|e| e.to_string())?).map_err(|e| format!("write: {e}"))?;
        loop {
            let f = read_frame(&mut s).map_err(|e| format!("no answer after {:.0} s: {e}", t1.elapsed().as_secs_f32()))?.ok_or("the world host closed the connection")?;
            match FromHost::decode(&f).map_err(|e| e.to_string())? {
                FromHost::Ready(r) => {
                    let _ = s.shutdown(std::net::Shutdown::Both);
                    return match r.start {
                        Some(w) if !w.is_empty() => Ok(format!("{} bytes", w.len())),
                        _ => Err("Ready without a start world".into()),
                    };
                }
                FromHost::Fault { reason } => return Err(format!("fault: {reason}")),
                _ => {}
            }
        }
    })();
    let size = match result {
        Ok(size) => size,
        Err(e) => return fail(&format!("start world of {}", row.project), format!("{e}; see {}", t.log_dir.join("world-host").display())),
    };
    println!("ok       start world of {} built in {:.1} s ({size})", row.project, t1.elapsed().as_secs_f32());
    if row.mode == game_data::gunrace::MODE {
        println!("skipped  bot match: the gun race has no AI players");
    } else {
        let t2 = Instant::now();
        match bot_match(&t.world_host.socket, &gd, row) {
            Ok(r) => println!(
                "ok       bot match on {}: {} AI players, {BOT_MATCH_SECS} s of match in {:.1} s; input from {} of them ({} inputs, {} AI entries); closed with Final",
                row.project,
                r.bots,
                t2.elapsed().as_secs_f32(),
                r.bots_with_input,
                r.inputs,
                r.ai
            ),
            Err(e) => return fail(&format!("bot match on {}", row.project), format!("{e}; see {}", t.log_dir.join("world-host").display())),
        }
    }
    drop(daemon);
    // the kill log (kills per weapon, kill achievements) reads deaths with hardware breakpoints: a missing permission
    // costs only that, so a warning
    let mut warnings = 0;
    match binary(t.world_host.daemon.as_ref().unwrap_or(d)).map(|b| Command::new(b).arg("perf-probe").output()) {
        Ok(Ok(o)) if o.status.success() => println!("ok       hardware breakpoints for the kill log"),
        Ok(Ok(o)) => {
            warnings += 1;
            println!("WARNING  hardware breakpoints refused ({}): matches run, but without the kill log (kills per weapon, kill achievements)", String::from_utf8_lossy(&o.stdout).trim());
            println!("         -> Linux: sudo sysctl kernel.perf_event_paranoid=2 (keep it: a line in /etc/sysctl.d/); Docker: run with --cap-add PERFMON");
        }
        Ok(Err(e)) => {
            warnings += 1;
            println!("WARNING  hardware breakpoints not checked: world-host perf-probe: {e}");
        }
        Err(e) => {
            warnings += 1;
            println!("WARNING  hardware breakpoints not checked: {e}");
        }
    }
    let note = if warnings > 0 { " (see the warning above)" } else { "" };
    println!("OK: the world host runs the game's world code and its AI players; online matches can start{note}.");
    0
}

/// Seconds of match time the self-test's bot match plays: a PvP match's 20 s countdown from the enter (the AI players
/// stand still in it), then about 10 s of play. The host steps it faster than real time.
pub const BOT_MATCH_SECS: u32 = 30;

/// What the self-test's bot match saw.
#[derive(Debug, Default)]
pub struct BotMatch {
    pub bots: usize,
    pub bots_with_input: usize,
    pub inputs: usize,
    pub ai: usize,
}

/// The self-test's bot match: one idle human and five AI players (2 + 3; the production bot pick and options writer)
/// on `row`; the world host builds the start world and drives the AI players (`Create.drive_bots`). A small relay: one
/// DF per tick, the enter of every record in one DF and the spawn profile one tick later (as the offline synthetic bot
/// match), and each `Bots` frame's entries filed into the DF they are for, as the match server does; the next DF goes
/// out once the host answered the last one. Fails on a `Fault`, a `Diverged` (an entry the world refused, or the
/// host's bots not getting their own entries back), a missing `Bots` frame, no input from any AI player, or no `Final`
/// after `Close`.
#[cfg(unix)]
pub fn bot_match(socket: &Path, gd: &game_data::GameData, row: &game_data::ModeRow) -> Result<BotMatch, String> {
    use match_server::match_msgs::{GameUpdate, PlayerInput, ProfileInput};
    use protocol::Encode;
    use std::collections::{BTreeMap, BTreeSet};
    use std::io::Write;
    use std::os::unix::net::UnixStream;
    use world_host_proto::{read_frame, Create, Df, FromHost, Record, ToHost, KIND_PVP, PROTO_VERSION};
    let match_id = 0x5E1F_7E58;
    let tick = local_match::options::TICK_MS;
    let p = local_match::OnlineParams {
        map: row.map,
        mode: row.mode,
        weather: row.variation,
        match_id,
        tick_ms: tick as u8,
        send_period_ms: local_match::options::SEND_PERIOD_MS,
        match_type: local_match::options::MATCH_TYPE_PLAIN,
        max_delay_ms: local_match::options::max_delay_ms(tick as u8),
    };
    let human = local_match::OnlinePlayer { team: 0, human: local_match::HumanLoadout::default_loadout(), hero: None, pve_budget: (0, 0) };
    let bots = local_match::pick_online_bots(gd, [2, 3], game_data::matches::DEFAULT_BOT_LEVEL);
    if bots.len() != 5 {
        return Err(format!("only {} AI players in the game data", bots.len()));
    }
    let options = local_match::online_options_row(gd, &p, row, &[human], &bots).map_err(|e| format!("match options: {e}"))?;
    let mut records = vec![Record { bot: false, team: 0 }];
    records.extend(bots.iter().map(|b| Record { bot: true, team: b.team }));
    let n = records.len();
    let bot_slots: Vec<u8> = (1..n as u8).collect();
    let create = Create {
        version: PROTO_VERSION,
        match_id,
        kind: KIND_PVP,
        project: row.project.clone(),
        map: row.map,
        mode: row.mode,
        tick_ms: tick as u8,
        records,
        options,
        world: Vec::new(),
        drive_bots: true,
        ai_ignore_players: false,
    };
    let send = |s: &mut UnixStream, m: ToHost| -> Result<(), String> { s.write_all(&m.frame().map_err(|e| e.to_string())?).map_err(|e| format!("write: {e}")) };
    let mut s = UnixStream::connect(socket).map_err(|e| format!("connect: {e}"))?;
    s.set_read_timeout(Some(SELFTEST_WAIT)).ok();
    send(&mut s, ToHost::Create(create))?;
    // the start item's time (its first u32) is the host's present: the DFs follow it on the tick grid
    let t0 = loop {
        let f = read_frame(&mut s).map_err(|e| format!("no Ready: {e}"))?.ok_or("the world host closed the connection before Ready")?;
        match FromHost::decode(&f).map_err(|e| e.to_string())? {
            FromHost::Ready(r) => {
                let item = r.start.filter(|w| w.len() >= 4).ok_or("Ready without a start world")?;
                break u32::from_le_bytes([item[0], item[1], item[2], item[3]]);
            }
            FromHost::Fault { reason } => return Err(format!("fault: {reason}")),
            _ => {}
        }
    };
    s.set_read_timeout(Some(Duration::from_secs(20))).ok();
    let (t_enter, t_spawn, t_last) = (t0 + 300, t0 + 350, t0 + BOT_MATCH_SECS * 1000);
    let all: u32 = (1u32 << n) - 1;
    // the host's entries per DF time
    let mut inputs_at: BTreeMap<u32, Vec<(u8, PlayerInput)>> = BTreeMap::new();
    let mut ai_at: BTreeMap<u32, Vec<(u8, u16, u16)>> = BTreeMap::new();
    let mut seen = BotMatch { bots: bot_slots.len(), ..Default::default() };
    let mut with_input = BTreeSet::new();
    let mut t = t0 + tick;
    while t <= t_last {
        let mut df = GameUpdate::empty(t);
        if t == t_enter {
            df.enter_mask = all;
        }
        if t == t_spawn {
            df.profile = (0..n as u8).map(|k| (k, ProfileInput { head: match_server::BOT_SPAWN_PROFILE, entries: vec![] })).collect();
        }
        let mut now = inputs_at.remove(&t).unwrap_or_default();
        now.sort_by_key(|(k, _)| *k);
        for (k, i) in now {
            df.input_mask |= 1 << k;
            df.inputs.push(i);
        }
        df.ai = ai_at.remove(&t).unwrap_or_default();
        let bytes = df.to_bytes().map_err(|e| format!("DF {t}: {e}"))?;
        send(&mut s, ToHost::Df(Df { t, bytes }))?;
        // the host answers every stepped DF with one Bots frame, for DF t + tick
        loop {
            let f = read_frame(&mut s).map_err(|e| format!("no Bots frame for DF {t}: {e}"))?.ok_or_else(|| format!("the world host closed the connection after DF {t}"))?;
            match FromHost::decode(&f).map_err(|e| e.to_string())? {
                FromHost::Bots(b) => {
                    if b.t_for <= t {
                        return Err(format!("Bots for {} after DF {t}", b.t_for));
                    }
                    if b.offgrid != 0 {
                        return Err(format!("{} bot entries off the tick grid at DF {t}", b.offgrid));
                    }
                    for (k, w) in &b.inputs {
                        if !bot_slots.contains(k) {
                            return Err(format!("Bots input for slot {k}, not an AI player"));
                        }
                        let mut full = [0u8; 8];
                        full[1..].copy_from_slice(&w[4..11]);
                        let i = PlayerInput { rot: [u16::from_le_bytes([w[0], w[1]]), u16::from_le_bytes([w[2], w[3]])], actions: u64::from_be_bytes(full) };
                        let v = inputs_at.entry(b.t_for).or_default();
                        v.retain(|(s, _)| s != k);
                        v.push((*k, i));
                        with_input.insert(*k);
                        seen.inputs += 1;
                    }
                    seen.ai += b.ai.len();
                    ai_at.entry(b.t_for).or_default().extend(b.ai.iter().copied());
                    if b.t_for == t + tick {
                        break;
                    }
                }
                FromHost::Fault { reason } => return Err(format!("fault at DF {t}: {reason}")),
                FromHost::Diverged(d) => return Err(format!("the world diverged at {} ({} entries refused or not echoed)", d.t, d.merged)),
                FromHost::Outcome(o) => return Err(format!("the match ended after {} ms (state {})", t - t0, o.state)),
                _ => {}
            }
        }
        t += tick;
    }
    seen.bots_with_input = with_input.len();
    if seen.inputs == 0 {
        return Err(format!("no input from any AI player in {BOT_MATCH_SECS} s"));
    }
    send(&mut s, ToHost::Close { t_last: t - tick })?;
    loop {
        let f = read_frame(&mut s).map_err(|e| format!("no Final after Close: {e}"))?.ok_or("the world host closed the connection without a Final")?;
        match FromHost::decode(&f).map_err(|e| e.to_string())? {
            FromHost::Final(_) => break,
            FromHost::Fault { reason } => return Err(format!("fault after Close: {reason}")),
            _ => {}
        }
    }
    let _ = s.shutdown(std::net::Shutdown::Both);
    Ok(seen)
}

