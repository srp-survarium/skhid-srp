#!/usr/bin/env bash
# Patch 158: the console's output scrolls (the wheel, Page Up, Page Down; End, Enter and opening go back
# to the newest line); the original never moves the view.
set -euo pipefail
main=$(git worktree list --porcelain | sed -n '1s/^worktree //p')
exe=${SKHID_ORIGINAL_EXE:-$main/private/function-map/inputs/026g/survarium.exe}
cd srp-026g
unicorn=$(nix build --no-link --print-out-paths --inputs-from . nixpkgs#python3Packages.unicorn)
nix develop -c bash -c '
    set -euo pipefail
    py=$(python3 -c "import sys; print(\"python%d.%d\" % sys.version_info[:2])")
    export PYTHONPATH="$1/lib/$py/site-packages"
    cd client-patches
    python3 -u check_console_scroll_026g.py "$2"
' console-scroll "$unicorn" "$exe"
